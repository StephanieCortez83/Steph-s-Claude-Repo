SELECT
	 [CHART_ADDITIONAL_PROCEDURE_AUTOMATION].[CHART_ADDITIONAL_PROCEDURE_AUTOMATION_ID]
	,[CHART_ADDITIONAL_PROCEDURE_AUTOMATION].[CREATION_DATE_TIME]
	,[CHART_ADDITIONAL_PROCEDURE_AUTOMATION].[CREATING_USER_PROFILE_ID]
