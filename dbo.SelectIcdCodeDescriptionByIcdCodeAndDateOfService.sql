-- CREATE OR ALTER PROCEDURE [dbo].[SelectIcdCodeDescriptionByIcdCodeAndDateOfService] 
CREATE PROCEDURE [dbo].[SelectIcdCodeDescriptionByIcdCodeAndDateOfService] 
    @ICD_CODE           VARCHAR(10) 
   ,@DATE_OF_SERVICE    DATE
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT 
    CASE WHEN 
    ( 
        LEN([ICD_10_CODE_MASTER].[DESCRIPTION]) = 0 
    OR  [ICD_10_CODE_MASTER].[DESCRIPTION] IS NULL 
    )
    THEN
        [ICD10_CM].[SHORT_DESCRIPTION]
    ELSE 
        [ICD_10_CODE_MASTER].[DESCRIPTION]
    END AS 
        [DESCRIPTION]
FROM   
    [ICD_10_CODE_MASTER] WITH (NOLOCK)
LEFT OUTER JOIN 
    [ICD10_CM] WITH (NOLOCK)
ON 
    [ICD10_CM].ICD10_CM = UPPER(REPLACE([ICD_10_CODE_MASTER].[ICD_10_CODE], '.', ''))
WHERE  
    [ICD_10_CODE_MASTER].[ICD_10_CODE] = UPPER(@ICD_CODE)
AND [ICD_10_CODE_MASTER].[EFFECTIVE_DT] <= @DATE_OF_SERVICE
AND [ICD_10_CODE_MASTER].[EXPIRATION_DT] >= @DATE_OF_SERVICE

GO
