CREATE   PROCEDURE [dbo].[ClearChartFlaggedForPbaDTByChartId]
	  @ChartId INT
	
AS

	IF @ChartId > 0
	BEGIN
		UPDATE
			[dbo].[CHART]
		SET 
			[FLAGGED_FOR_POST_BILL_AUDIT_DT] = NULL
		WHERE
			[CHART_ID] = @ChartId;
	END;
		
	SELECT
		COUNT(CHART_ID)
	FROM
		[dbo].[CHART] WITH (NOLOCK)
	WHERE
		[CHART_ID] = @ChartId
		AND [FLAGGED_FOR_POST_BILL_AUDIT_DT] IS NULL;

GO
