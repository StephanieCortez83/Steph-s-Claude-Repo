CREATE   PROCEDURE [dbo].[ICD_10_RULE_SELECT_BY_SECTION_ID_AND_CODE_AND_DATE_OF_SERVICE]  
	  @SECTION_ID VARCHAR(10) = NULL  
	 ,@CODE VARCHAR(10) = NULL  
     ,@DATE_OF_SERVICE DATE = NULL  
AS  
  
SET NOCOUNT ON  
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED  
   
SELECT   
    [IR].[ICD_10_RULE_ID]  
   ,[IR].[DESCRIPTION]  
   ,[IR].[RULE_TYPE_CD]  
   ,[IR].[FIRST_CODE]  
   ,[IR].[LAST_CODE] 
   ,[IR].[RULE_LEVEL]
FROM     
    [ICD_10_RULE] IR WITH (NOLOCK)  
	INNER JOIN [ICD_10_SECTION] S WITH (NOLOCK) 
ON
    [IR].[FIRST_CODE] = [S].[FIRST_CODE]
	AND [IR].[LAST_CODE] = [S].[LAST_CODE]
WHERE    
	[S].[SECTION_ID] = @SECTION_ID
	AND [IR].[RULE_LEVEL] = 'S'
	AND [IR].[EFFECTIVE_DT] <= @DATE_OF_SERVICE  
	AND [IR].[EXPIRATION_DT] >= @DATE_OF_SERVICE  
UNION ALL  
SELECT  
	ICD_10_RULE_ID
	,[DESCRIPTION] 
	,RULE_TYPE_CD 	
	,FIRST_CODE
	,LAST_CODE
	,RULE_LEVEL
FROM 
	ICD_10_RULE with (NOLOCK)
WHERE 
	((@CODE BETWEEN FIRST_CODE and LAST_CODE ) 
	OR FIRST_CODE = @CODE
    OR @CODE >= FIRST_CODE and @CODE LIKE (LAST_CODE + '%') 
	)
	AND RULE_LEVEL = 'D'
	AND [EFFECTIVE_DT] <= @DATE_OF_SERVICE  
	AND [EXPIRATION_DT] >= @DATE_OF_SERVICE  
ORDER  BY   
    [ICD_10_RULE_ID]  
GO
