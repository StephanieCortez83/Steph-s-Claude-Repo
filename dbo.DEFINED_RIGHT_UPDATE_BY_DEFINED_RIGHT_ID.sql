CREATE PROCEDURE [dbo].[DEFINED_RIGHT_UPDATE_BY_DEFINED_RIGHT_ID]
	 @DEFINED_RIGHT_ID int
	,@NAME varchar(50) = NULL
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@ALLOW_INHERITANCE bit = NULL
	,@DEFINITION varchar(2000) = NULL
	,@IS_ADMIN bit
AS

UPDATE [dbo].[DEFINED_RIGHT] SET
	 [NAME] = @NAME
	,[CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
	,[ALLOW_INHERITANCE] = @ALLOW_INHERITANCE
	,[DEFINITION] = @DEFINITION
	,[IS_ADMIN] = @IS_ADMIN
WHERE
	[DEFINED_RIGHT_ID] = @DEFINED_RIGHT_ID
GO
