CREATE PROCEDURE [dbo].[CEP_USER_SESSION_SELECT_PARALLEL_SESSION_BY_USER_PROFILE_ID_AND_UU_ID_AND_SESSION_ID]
	 @USER_PROFILE_ID int
	,@UU_ID uniqueidentifier
	,@SESSION_ID varchar(50)
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CEP_USER_SESSION_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)

SET @sql = 'INSERT INTO #tmp (CEP_USER_SESSION_ID) ' +
		   'SELECT [CEP_USER_SESSION].[CEP_USER_SESSION_ID] ' +
		   'FROM [CEP_USER_SESSION] WITH (NOLOCK) ' +
		   'WHERE [CEP_USER_SESSION].[USER_PROFILE_ID] = ' + CAST(@USER_PROFILE_ID AS VARCHAR(10)) + 
           '  AND [CEP_USER_SESSION].[IS_SIGNED_OUT] = 0 ' +
           '  AND [CEP_USER_SESSION].[UU_ID] <> ''' + CAST(@UU_ID AS VARCHAR(36)) + '''' +
		   '  AND SESSION_START_DATE_TIME >= ( ' +
           '	SELECT TOP 1 SESSION_START_DATE_TIME '+
           '	FROM CEP_USER_SESSION WITH (NOLOCK) ' +
           '	WHERE USER_PROFILE_ID = ' + CAST(@USER_PROFILE_ID AS VARCHAR(10)) + 
           '      AND SESSION_ID = ''' + CAST(@SESSION_ID AS VARCHAR(50)) + ''''  +
		   '	ORDER BY SESSION_START_DATE_TIME DESC ' +
           '  ) '

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CEP_USER_SESSION].[LAST_REQUEST_DATE_TIME] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CEP_USER_SESSION].[CEP_USER_SESSION_ID]
	,[CEP_USER_SESSION].[USER_PROFILE_ID]
	,[CEP_USER_SESSION].[SESSION_ID]
	,[CEP_USER_SESSION].[UU_ID]
	,[CEP_USER_SESSION].[IS_SIGNED_OUT]
	,[CEP_USER_SESSION].[SESSION_START_DATE_TIME]
	,[CEP_USER_SESSION].[LAST_REQUEST_DATE_TIME]
	,[CEP_USER_SESSION].[CREATION_DATE_TIME]
	,[CEP_USER_SESSION].[CREATING_USER_PROFILE_ID]
	,[CEP_USER_SESSION].[CHANGED_DATE_TIME]
	,[CEP_USER_SESSION].[CHANGING_USER_PROFILE_ID]
FROM
	#tmp [tmp]
	INNER JOIN [CEP_USER_SESSION] 
			ON [CEP_USER_SESSION].[CEP_USER_SESSION_ID] = [tmp].[CEP_USER_SESSION_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]
GO
