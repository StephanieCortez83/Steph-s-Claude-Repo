CREATE PROCEDURE [dbo].[CHART_SELECT_TOP_50_MOST_RECENT_BY_USER_PROFILE_ID]
	@USER_PROFILE_ID INT = NULL
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

IF OBJECT_ID('TEMPDB..#FACILITYLIST', 'U') IS NOT NULL DROP TABLE #FACILITYLIST 
IF OBJECT_ID('TEMPDB..#RESULTS', 'U') IS NOT NULL DROP TABLE #RESULTS 
 
-- GET LIST OF AUTHORIZED FACILITIES BASED ON USER ID AND USER AUTHORIZATION EFFECTIVE DATES
SELECT 
	[FUA].[FACILITY_ID]
INTO 
	[#FACILITYLIST]
FROM  
	[USER_PROFILE] AS [UP] WITH (NOLOCK)
JOIN 
	[FACILITY_USER_AUTHORIZATION] AS [FUA] WITH (NOLOCK)
ON 
	[UP].[USER_PROFILE_ID] = [FUA].[USER_PROFILE_ID]
WHERE  
	[UP].[USER_PROFILE_ID] = @USER_PROFILE_ID 
AND CAST(GETDATE() AS DATE) BETWEEN CAST([FUA].[EFFECTIVE_DATE] AS DATE) AND CAST([FUA].[EXPIRATION_DATE] AS DATE) 
 
-- GET TOP 50 CHARTS BASED ON USER'S AUTHORIZED FACILITIES AND LAST ACCESS DATE
-- SET FACILITY_CHART_ID AND PATIENT_LAST_NAME = NULL. THEY'RE PULLED IN THE NEXT SUB-QUERY
SELECT TOP 50 
	[C].[CHART_ID]
   ,[F].[NAME]
   ,[CA].[ACCESS_DATE_TIME]
   ,[FACILITY_CHART_ID] = CAST(NULL AS VARCHAR(50))
   ,[PATIENT_LAST_NAME] = CAST(NULL AS VARCHAR(100)) 
INTO
	[#RESULTS]
FROM 
	[CHART] AS [C] WITH (NOLOCK)
JOIN 
	[CHART_ACCESS] AS CA WITH (NOLOCK)
ON 
	[C].[CHART_ID] = [CA].[CHART_ID]
JOIN 
	[FACILITY] AS [F] WITH (NOLOCK) 
ON 
	[C].[FACILITY_ID] = [F].[FACILITY_ID]
JOIN 
	[#FACILITYLIST] AS [T] WITH (NOLOCK) 
ON 
	[F].[FACILITY_ID] = [T].[FACILITY_ID]
WHERE 
	[CA].[USER_PROFILE_ID] = @USER_PROFILE_ID
ORDER BY
	[CA].[ACCESS_DATE_TIME] DESC  

-- GET FACILITY_CHART_ID AND PATIENT_LAST_NAME FOR ALL ROWS IN #RESULT
UPDATE 
	[T]
SET 
	[T].[FACILITY_CHART_ID] = [C].[FACILITY_CHART_ID]
   ,[T].[PATIENT_LAST_NAME] = [C].[PATIENT_LAST_NAME]
FROM 
	[#RESULTS] AS [T] WITH (NOLOCK)
JOIN 
	[CHART] AS [C] WITH (NOLOCK)
ON 
	[T].[CHART_ID] = [C].[CHART_ID]
 
-- FINALLY, RETURN THE COMPLETE RESULT SET FROM #RESULTS
SELECT 
	[CHART_ID]
   ,[FACILITY_CHART_ID]
   ,[PATIENT_LAST_NAME]
   ,[NAME]
   ,[ACCESS_DATE_TIME]
FROM 
	[#RESULTS] WITH (NOLOCK)
ORDER BY 
	[ACCESS_DATE_TIME] DESC 

GO
