CREATE   PROCEDURE [dbo].[CHART_DIAGNOSIS_CODE_ICD10_SELECT_BY_CHART_DIAGNOSIS_CODE_ICD10_ID_AND_DATE_OF_SERVICE] @DIAGNOSIS_CODE_ICD10_ID int  
																													   , @DATE_OF_SERVICE		  date 
AS
	SET NOCOUNT ON;

	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

	SELECT	[CDC].[CHART_DIAGNOSIS_CODE_ICD10_ID]
		  , [CDC].[ICD10_CODE]
		  , [CDC].[CHART_ID]
		  , [CDC].[DIAGNOSIS_TYPE_ID]
		  , [CDC].[LEVEL_NUMBER]
		  , [CDC].[IS_PRIMARY]
		  , [CDC].[CREATION_DATE_TIME]
		  , [CDC].[CREATING_USER_PROFILE_ID]
		  , [CDC].[CHANGED_DATE_TIME]
		  , [CDC].[CHANGING_USER_PROFILE_ID]
		  , [CDC].[POSTING_ORDER]
		  , [CDC].[MAPPED_ICD9_CODE]
		  , [CDC].[FULFILLS_REQUIREMENT_OF_ICD10_CODE]
		  , [CDC].[OVERRIDE_RULE_EDIT]
		  , [CDC].[OVERRIDE_RULE_EDIT_USER_PROFILE_ID]
		  , [CM].[DESCRIPTION]
		  , 0
	FROM	[CHART_DIAGNOSIS_CODE_ICD10]		 CDC WITH (NOLOCK)
			LEFT OUTER JOIN [ICD_10_CODE_MASTER] CM WITH (NOLOCK)
				ON [CM].[ICD_10_CODE] = [CDC].[ICD10_CODE]
				   AND @DATE_OF_SERVICE BETWEEN [CM].[EFFECTIVE_DT] AND [CM].[EXPIRATION_DT]
	--[jburge	10/30/24] removed joins as they were actually never used
	WHERE	[CDC].[CHART_DIAGNOSIS_CODE_ICD10_ID] = @DIAGNOSIS_CODE_ICD10_ID;
GO
