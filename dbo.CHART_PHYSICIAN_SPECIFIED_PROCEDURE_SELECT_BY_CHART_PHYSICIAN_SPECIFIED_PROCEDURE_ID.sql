CREATE PROCEDURE [dbo].[CHART_PHYSICIAN_SPECIFIED_PROCEDURE_SELECT_BY_CHART_PHYSICIAN_SPECIFIED_PROCEDURE_ID]

	@CHART_PHYSICIAN_SPECIFIED_PROCEDURE_ID int

AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[CHART_PHYSICIAN_SPECIFIED_PROCEDURE_ID]
	,[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[CHART_ID]
	,[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[CPT_CODE]
	,[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[MODIFIERS]
	,[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[QUANTITY]
	,[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[CREATION_DATE_TIME]
	,[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[CREATING_USER_PROFILE_ID]
	,[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[CHANGED_DATE_TIME]
	,[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[CHANGING_USER_PROFILE_ID]
FROM
	[dbo].[CHART_PHYSICIAN_SPECIFIED_PROCEDURE] with (NOLOCK)
WHERE
	[CHART_PHYSICIAN_SPECIFIED_PROCEDURE].[CHART_PHYSICIAN_SPECIFIED_PROCEDURE_ID] = @CHART_PHYSICIAN_SPECIFIED_PROCEDURE_ID

GO
