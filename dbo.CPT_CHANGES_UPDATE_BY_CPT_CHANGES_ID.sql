CREATE PROCEDURE [dbo].[CPT_CHANGES_UPDATE_BY_CPT_CHANGES_ID]
	 @CPT_CHANGES_ID int
	,@CHART_ID int
	,@CPT varchar(20)
	,@CPT_MODIFIERS varchar(100) = NULL
	,@CPT_COUNT int
	,@CHANGE_REASON varchar(100) = NULL
	,@IS_ACTIVE bit
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@IS_MATCH_PRESENT bit = NULL
AS

UPDATE [dbo].[CPT_CHANGES] SET
	 [CHART_ID] = @CHART_ID
	,[CPT] = @CPT
	,[CPT_MODIFIERS] = @CPT_MODIFIERS
	,[CPT_COUNT] = @CPT_COUNT
	,[CHANGE_REASON] = @CHANGE_REASON
	,[IS_ACTIVE] = @IS_ACTIVE
	,[CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
	,[IS_MATCH_PRESENT] = @IS_MATCH_PRESENT
WHERE
	[CPT_CHANGES_ID] = @CPT_CHANGES_ID
GO
