CREATE OR ALTER PROCEDURE [dbo].[PqrsMeasureIsSatisfiedByMeasureId_Type76] 
	  @ChartId INT
	, @MeasureId INT = NULL
	, @PqrsNum VARCHAR(20) = NULL
	, @Dos DATETIME = NULL
	, @ShowDebug BIT = 0
WITH EXEC AS CALLER AS
BEGIN
