CREATE PROCEDURE [dbo].[CEP_FACILITY_SELECT_BY_CEP_FACILITY_ID]
	@CEP_FACILITY_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [CEP_FACILITY].[CEP_FACILITY_ID]
	,[CEP_FACILITY].[CEP_ORGANIZATION_ID]
	,[CEP_FACILITY].[FACILITY_NAME]
	,[CEP_FACILITY].[CEP_FACILITY_TYPE_CODE]
	,[CEP_FACILITY].[PRIMARY_CONTACT_FIRST_NAME]
	,[CEP_FACILITY].[PRIMARY_CONTACT_LAST_NAME]
	,[CEP_FACILITY].[PRIMARY_CONTACT_EMAIL_ADDRESS]
	,[CEP_FACILITY].[CREATION_DATE_TIME]
	,[CEP_FACILITY].[CREATING_USER_PROFILE_ID]
	,[CEP_FACILITY].[CHANGED_DATE_TIME]
	,[CEP_FACILITY].[CHANGING_USER_PROFILE_ID]
FROM
	[dbo].[CEP_FACILITY]
WHERE
	[CEP_FACILITY].[CEP_FACILITY_ID] = @CEP_FACILITY_ID
GO
