CREATE PROCEDURE [dbo].[OBSERVATION_EXCLUSION_HOURS_REASON_SELECT_DISTINCT_BY_SERVICE_AGREEMENT_DESCRIPTION]
	@SERVICE_AGREEMENT_DESCRIPTION varchar(50)
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

DECLARE @FOUND_SERVICE_AGREEMENT_ID int;

SELECT @FOUND_SERVICE_AGREEMENT_ID = [SERVICE_AGREEMENT_ID]
	FROM
		[dbo].[SERVICE_AGREEMENT] with (NOLOCK)
	WHERE
		([DESCRIPTION] = @SERVICE_AGREEMENT_DESCRIPTION);

SELECT DISTINCT 
	 [SERVICE_AGREEMENT_ID]
	,[EXCLUSION_HOURS_REASON_ID]
	,[DESCRIPTION]
FROM 
	[dbo].[OBSERVATION_EXCLUSION_HOURS_REASON] with (NOLOCK)
WHERE
	([SERVICE_AGREEMENT_ID] = @FOUND_SERVICE_AGREEMENT_ID);

GO
