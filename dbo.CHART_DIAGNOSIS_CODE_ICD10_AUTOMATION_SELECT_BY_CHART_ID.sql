CREATE PROCEDURE [dbo].[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION_SELECT_BY_CHART_ID]
	 @CHART_ID int
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)
DECLARE @KeyWhereClause nvarchar(1000)

SET @sql = 'INSERT INTO #tmp (CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION_ID) ' +
		   'SELECT [CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION_ID] ' +
		   'FROM [CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION] ' +
		   'WHERE [CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CHART_ID] = ' + CAST(@CHART_ID AS VARCHAR(10)) 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CREATION_DATE_TIME] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION_ID]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CREATION_DATE_TIME]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CREATING_USER_PROFILE_ID]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CHANGED_DATE_TIME]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CHANGING_USER_PROFILE_ID]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CHART_DIAGNOSIS_CODE_ICD10_ID]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CHART_ID]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[ICD10_CODE]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[DIAGNOSIS_TYPE_ID]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[IS_PRIMARY]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[POSTING_ORDER]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[MAPPED_ICD9_CODE]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[FULFILLS_REQUIREMENT_OF_ICD10_CODE]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[OVERRIDE_RULE_EDIT]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[OVERRIDE_RULE_EDIT_USER_PROFILE_ID]
	,[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[LEVEL_NUMBER]
FROM
	#tmp [tmp]
	INNER JOIN [CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION] 
			ON [CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION].[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION_ID] = [tmp].[CHART_DIAGNOSIS_CODE_ICD10_AUTOMATION_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
