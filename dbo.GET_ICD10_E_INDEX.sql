CREATE PROC [dbo].[GET_ICD10_E_INDEX]
(
	@root int
)
AS
BEGIN
;With ret as (		
	SELECT d.SEQ_NUMBER,  d.PARENT_SEQ_NUMBER, d.[LEVEL], d.TITLE, d.INDEX_LETTER_VALUE, d.CODE, d.SEE_DESCRIPTION, d.SEE_ALSO_DESCRIPTION, 
	d.SEE_CATEGORY, d.SUB_CATEGORY, d.NON_ESSENTIAL_MODIFIER_DESCRIPTION
	from ICD_10_E_INDEX d
	where d.PARENT_SEQ_NUMBER = @root 
	UNION ALL
	SELECT d.SEQ_NUMBER,  d.PARENT_SEQ_NUMBER, d.[LEVEL], d.TITLE, d.INDEX_LETTER_VALUE, d.CODE, d.SEE_DESCRIPTION, d.SEE_ALSO_DESCRIPTION, 
	d.SEE_CATEGORY, d.SUB_CATEGORY, d.NON_ESSENTIAL_MODIFIER_DESCRIPTION
	from ICD_10_E_INDEX d
		INNER JOIN ret r on d.PARENT_SEQ_NUMBER = r.SEQ_NUMBER 
	)	
	
	select distinct * from ret	
	order by ret.seq_number
END

GO
