CREATE PROCEDURE [dbo].[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_SELECT]
	@PAGE_INDEX		 int		  = NULL
   ,@PAGE_SIZE		 int		  = 25
   ,@WHERE_CLAUSE	 varchar(500) = NULL
   ,@ORDER_BY_CLAUSE varchar(250) = NULL
   ,@RECORD_COUNT	 int OUTPUT
AS
BEGIN
	SET NOCOUNT ON
	SET CONCAT_NULL_YIELDS_NULL OFF
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	--[ID LIST]------------------------------------------------------
	CREATE TABLE #tmp
	(
		[INDEX_ID]													   int IDENTITY (1, 1) NOT NULL,
		[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID] int NOT NULL
	)

	DECLARE @sql nvarchar(1000)
	DECLARE @KeyWhereClause nvarchar(1000)
	SET @sql = 'INSERT INTO #tmp (FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID) ' +
			   'SELECT [FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID] ' +
			   'FROM [FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON] ' 
		
	IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
		SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

	IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
		SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
	ELSE
		SET @sql = @sql + 'ORDER BY [FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[DESCRIPTION] '

	EXEC sp_executesql @sql

	--[RANGE]----------------------------------------------------------

	SELECT @RECORD_COUNT = @@ROWCOUNT

	DECLARE @FIRST_RECORD int
	DECLARE @LAST_RECORD  int

	IF @PAGE_INDEX IS NOT NULL
	BEGIN
		SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
		SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
	
	END
	ELSE
	BEGIN
		SET @FIRST_RECORD = 1
		SET @LAST_RECORD  = @RECORD_COUNT
	END

	--[DATA]------------------------------------------------------------

	SELECT [FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID]
		  ,[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[DESCRIPTION]
		  ,[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[CREATION_DATE_TIME]
		  ,[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[CREATED_BY_USER_PROFILE_ID]
		  ,[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[CHANGED_DATE_TIME]
		  ,[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[CHANGED_BY_USER_PROFILE_ID]
	 FROM 
		#tmp [tmp]
		INNER JOIN [FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON]
				ON [FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON].[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID] = [tmp].[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID]
	 WHERE
		[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
	 ORDER BY
		[tmp].[INDEX_ID]
END
GO
