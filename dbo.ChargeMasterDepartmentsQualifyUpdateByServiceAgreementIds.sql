CREATE   PROCEDURE [dbo].[ChargeMasterDepartmentsQualifyUpdateByServiceAgreementIds]
	 @SourceSAId INT
	,@TargetSAId INT
	,@UPId INT
	,@EffectiveDate DATETIME
	,@ExpirationDate DATETIME
	,@InsDate DATETIME = NULL
	,@MaxToProcess INT = 1000
AS
BEGIN

	IF @SourceSAId IS NULL OR @SourceSAId <= 0
	BEGIN
		SELECT Result = -1, Error = 'Error: Source SA Id is invalid.';
		RETURN;
	END;

	IF @TargetSAId IS NULL OR @TargetSAId <= 0
	BEGIN
		SELECT Result = -2, Error = 'Error: Target SA Id is invalid.';
		RETURN;
	END;

	IF @UPId IS NULL OR @UPId <= 0
	BEGIN
		SELECT Result = -3, Error = 'Error: UP Id is invalid.';
		RETURN;
	END;

	IF @InsDate IS NULL
	BEGIN
		SET @InsDate = CONVERT (date, GETDATE());
	END;


	IF @MaxToProcess IS NULL OR @MaxToProcess <= 0
	BEGIN
		SET @MaxToProcess = 1000;
	END;

	IF OBJECT_ID('tempdb..#TempRows') IS NOT NULL
	BEGIN
		DROP TABLE #TempRows
	END;

	-- Fill temp table with our data
	SELECT 
		 [SERVICE_AGREEMENT_ID]
		,[NAME]
		,[EFFECTIVE_DATE]
		,[EXPIRATION_DATE]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[COPIED_FROM_DEPT_ID]
		,[FACILITY_DEPARTMENT_CODE]
		,[FACILITY_DEPARTMENT_ALT] 
		,[ACTIVE]
		,[CALCULATE_APC_RATES_IND]
		,[DEFAULT_IND]
		,[OBSERVATION_IND]
		,[OBSERVATION_CODER_ASSIGNMENT_CODE]
		,[CHARGE_MASTER_DEPARTMENT_CLASS_ID]
		,[FACILITY_CAMPUS_CODE]
	INTO #TempRows
	FROM
		(SELECT 
				 @TargetSAId AS [SERVICE_AGREEMENT_ID]
				,[NAME]
				,@EffectiveDate AS [EFFECTIVE_DATE]
				,@ExpirationDate AS [EXPIRATION_DATE]
				,@InsDate AS [CREATION_DATE_TIME]
				,@UPId AS [CREATING_USER_PROFILE_ID]
				,@InsDate AS [CHANGED_DATE_TIME]
				,@UPId AS [CHANGING_USER_PROFILE_ID]
				,[CHARGE_MASTER_DEPT_ID] AS [COPIED_FROM_DEPT_ID]
				,[FACILITY_DEPARTMENT_CODE]
				,[FACILITY_DEPARTMENT_ALT] 
				,[ACTIVE]
				,[CALCULATE_APC_RATES_IND]
				,[DEFAULT_IND]
				,[OBSERVATION_IND]
				,[OBSERVATION_CODER_ASSIGNMENT_CODE]
				,[CHARGE_MASTER_DEPARTMENT_CLASS_ID]
				,[FACILITY_CAMPUS_CODE]
		FROM
			[RevCycleDB].[dbo].[CHARGE_MASTER_DEPARTMENT] WITH (NOLOCK)
		WHERE 
			[SERVICE_AGREEMENT_ID] = @SourceSAId
			AND LOWER(RTRIM([NAME])) NOT IN 
				(
					SELECT DISTINCT LOWER(RTRIM([NAME])) 
						FROM [RevCycleDB].[dbo].[CHARGE_MASTER_DEPARTMENT] WITH (NOLOCK)
						WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId
				)
		) AS sourceList

	-- check our data if needed
	-- SELECT COUNT(*) FROM #TempRows;
	-- SELECT * FROM #TempRows;

	DECLARE @tempTableRowCount INT = (SELECT COUNT(*) FROM #TempRows);

	IF @tempTableRowCount <= 0
	BEGIN
		SELECT Result = 0, Error = 'No new data rows to insert';
		RETURN;
	END;

	-- Perform insert action here
	BEGIN TRANSACTION
	BEGIN TRY

		INSERT INTO [RevCycleDB].[dbo].[CHARGE_MASTER_DEPARTMENT]
			(
			 [SERVICE_AGREEMENT_ID]
			,[NAME]
			,[EFFECTIVE_DATE]
			,[EXPIRATION_DATE]
			,[CREATION_DATE_TIME]
			,[CREATING_USER_PROFILE_ID]
			,[CHANGED_DATE_TIME]
			,[CHANGING_USER_PROFILE_ID]
			,[COPIED_FROM_DEPT_ID]
			,[FACILITY_DEPARTMENT_CODE]
			,[FACILITY_DEPARTMENT_ALT] 
			,[ACTIVE]
			,[CALCULATE_APC_RATES_IND]
			,[DEFAULT_IND]
			,[OBSERVATION_IND]
			,[OBSERVATION_CODER_ASSIGNMENT_CODE]
			,[CHARGE_MASTER_DEPARTMENT_CLASS_ID]
			,[FACILITY_CAMPUS_CODE]
			)
			SELECT TOP (@MaxToProcess)
				 #TempRows.[SERVICE_AGREEMENT_ID]
				,#TempRows.[NAME]
				,#TempRows.[EFFECTIVE_DATE]
				,#TempRows.[EXPIRATION_DATE]
				,#TempRows.[CREATION_DATE_TIME]
				,#TempRows.[CREATING_USER_PROFILE_ID]
				,#TempRows.[CHANGED_DATE_TIME]
				,#TempRows.[CHANGING_USER_PROFILE_ID]
				,#TempRows.[COPIED_FROM_DEPT_ID]
				,#TempRows.[FACILITY_DEPARTMENT_CODE]
				,#TempRows.[FACILITY_DEPARTMENT_ALT] 
				,#TempRows.[ACTIVE]
				,#TempRows.[CALCULATE_APC_RATES_IND]
				,#TempRows.[DEFAULT_IND]
				,#TempRows.[OBSERVATION_IND]
				,#TempRows.[OBSERVATION_CODER_ASSIGNMENT_CODE]
				,#TempRows.[CHARGE_MASTER_DEPARTMENT_CLASS_ID]
				,#TempRows.[FACILITY_CAMPUS_CODE]
			From #TempRows;

		COMMIT TRANSACTION;

	END TRY
	BEGIN CATCH
		SELECT Result = -4, 
			Error = 'Error: Exception occurred.  Rollback Processed. Error = ' 
				+ CAST(ERROR_NUMBER() AS VARCHAR(30)) 
				+ ' :: ' + CAST(ERROR_MESSAGE() AS VARCHAR(4000));
		ROLLBACK TRANSACTION;
	END CATCH;


	DECLARE @resultCount INT = (SELECT COUNT([CHARGE_MASTER_DEPT_ID]) FROM [RevCycleDB].[dbo].[CHARGE_MASTER_DEPARTMENT] WITH (NOLOCK) WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId)

	SELECT Result = @tempTableRowCount, Error = 'Total Rows = ' + CAST(@resultCount AS VARCHAR(20));

END -- end of stored procedure

GO
