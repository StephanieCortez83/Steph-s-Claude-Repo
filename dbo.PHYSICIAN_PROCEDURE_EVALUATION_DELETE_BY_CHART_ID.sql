CREATE PROCEDURE [dbo].[PHYSICIAN_PROCEDURE_EVALUATION_DELETE_BY_CHART_ID]
	@CHART_ID INT = NULL
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

-- Delete all Physician Procedure Evaluation rows
-- Don't delete codes '99292', '99217', '99417' or 'G2212'
-- unless they're in the charge master with a usage of 5, or 'Physician Procedure'.
DELETE 
	[PPE]
FROM   
	[CHARGE_MASTER] [CM]
JOIN 
	[PHYSICIAN_PROCEDURE_EVALUATION] [PPE]
ON	[PPE].[PHYSICIAN_PROCEDURE_ID] = [CM].[CHARGE_MASTER_ID]
WHERE  
	[PPE].[CHART_ID] = @CHART_ID
AND 
( 
	( 
		[CM].[CPT_CODE] <> '99217'
	AND	[CM].[CPT_CODE] <> '99292'
	AND [CM].[CPT_CODE] <> '99417'
	AND [CM].[CPT_CODE] <> 'G2212' 
	)
	OR 	
	( 
		[CM].[CPT_CODE] = '99217'
	AND [CM].[CHARGE_MASTER_USAGE_CODE] = 5 
	) 
	OR
	(
		[CM].[CPT_CODE] = '99292'
	AND	[CM].[CHARGE_MASTER_USAGE_CODE] = 5
	)
	OR
	(
		[CM].[CPT_CODE] = '99417'
	AND	[CM].[CHARGE_MASTER_USAGE_CODE] = 5
	)
	OR
	(
		[CM].[CPT_CODE] = 'G2212'
	AND	[CM].[CHARGE_MASTER_USAGE_CODE] = 5
	)	
)
AND [CM].[CHARGE_MASTER_USAGE_CODE] <> 9 

GO
