	 @CEP_ORGANIZATION_ID int
	,@FACILITY_NAME varchar(50)
	,@CEP_FACILITY_TYPE_CODE int
	,@PRIMARY_CONTACT_FIRST_NAME varchar(25)
	,@PRIMARY_CONTACT_LAST_NAME varchar(25)
	,@PRIMARY_CONTACT_EMAIL_ADDRESS varchar(50)
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@CEP_FACILITY_ID int OUTPUT
AS

INSERT INTO [dbo].[CEP_FACILITY]
(
	 [CEP_ORGANIZATION_ID]
	,[FACILITY_NAME]
	,[CEP_FACILITY_TYPE_CODE]
	,[PRIMARY_CONTACT_FIRST_NAME]
	,[PRIMARY_CONTACT_LAST_NAME]
	,[PRIMARY_CONTACT_EMAIL_ADDRESS]
	,[CREATING_USER_PROFILE_ID]
	,[CHANGING_USER_PROFILE_ID]
