CREATE PROCEDURE [dbo].[AUDIT_LOG_OBJECT_STATE_SELECT_BY_AUDIT_LOG_ID]
   @AUDIT_LOG_ID int
AS

SET NOCOUNT ON
SET CONCAT_NULL_YIELDS_NULL OFF
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT [AUDIT_LOG_OBJECT_STATE_ID]
      ,[AUDIT_LOG_ID]
      ,[STATE]
      ,[CREATION_DATE_TIME]
FROM 
	[dbo].[AUDIT_LOG_OBJECT_STATE] WITH (NOLOCK)
WHERE
	[AUDIT_LOG_OBJECT_STATE].[AUDIT_LOG_ID] = @AUDIT_LOG_ID
GO
