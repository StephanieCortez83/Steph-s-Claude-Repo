CREATE PROCEDURE [dbo].[FACILITY_USER_AUTHORIZATION_EXPIRE_USER_BY_USERNAME_AND_FACILITY_NAME]
    @USER_NAME								VARCHAR(15)
   ,@FACILITY_NAME							VARCHAR(50)
   ,@EXPIRY_DATE							DATE
   ,@EXPIRY_REASON_ID						INT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

DECLARE @USER_ID							INT
DECLARE @FACILITY_ID						INT
DECLARE @FACILITY_USR_AUTH_ID				INT
DECLARE @FACILITY_COMMENT					VARCHAR(255)
DECLARE @OUTPUT_AUDIT_LOG_ID				INT
DECLARE @STATE_STRING						VARCHAR(MAX)
DECLARE @OUTPUT_AUDIT_LOG_OBJECT_STATE_ID	INT
DECLARE @ADMINISTRATOR_USER_PROFILE_ID		INT
DECLARE @ADMINISTRATOR_USERNAME				VARCHAR(15)
DECLARE @ADMINISTRATOR_EMAIL_ADDR			VARCHAR(50)
DECLARE @ADMINISTRATOR_FIRST_NAME			VARCHAR(25)
DECLARE @ADMINISTRATOR_LAST_NAME			VARCHAR(25)
DECLARE @EXPIRY_REASON_DESCRIPTION			VARCHAR(500)
-------------------------------------------------------
-- GET ADMINISTRATOR INFO
-------------------------------------------------------
SET @ADMINISTRATOR_USERNAME =				'ADMIN'

SELECT
	@ADMINISTRATOR_USER_PROFILE_ID = [USP].[USER_PROFILE_ID]
   ,@ADMINISTRATOR_EMAIL_ADDR = [USP].[EMAIL_ADDRESS]
   ,@ADMINISTRATOR_FIRST_NAME = [USP].[FIRST_NAME]
   ,@ADMINISTRATOR_LAST_NAME = [USP].[LAST_NAME]
FROM
	[dbo].[USER_PROFILE] AS [USP] WITH (NOLOCK) 
WHERE
	[USP].[SIGN_ON_ID] = @ADMINISTRATOR_USERNAME	

IF @@ROWCOUNT > 1
BEGIN
	RAISERROR('Found multiple users with Username "ADMIN"', 16, 1) WITH NOWAIT
	RETURN
END
IF @ADMINISTRATOR_USER_PROFILE_ID IS NULL 
BEGIN
	RAISERROR('Unable to find System Administrator info', 16, 1) WITH NOWAIT
	RETURN
END
-------------------------------------------------------
-- GET USER PROFILE ID
-------------------------------------------------------
SELECT
	@USER_ID = [USP].[USER_PROFILE_ID]
FROM
	[dbo].[USER_PROFILE] AS [USP] WITH (NOLOCK) 
WHERE
	[USP].[SIGN_ON_ID] = @USER_NAME

IF @@ROWCOUNT > 1
BEGIN
	RAISERROR('Found multiple User Profile IDs for Username "%s"', 16, 1, @USER_NAME) WITH NOWAIT
	RETURN
END
IF @USER_ID IS NULL 
BEGIN
	RAISERROR('Unable to find User Profile ID for Username "%s"', 16, 1, @USER_NAME) WITH NOWAIT
	RETURN
END
-------------------------------------------------------
-- GET FACILITY ID
-------------------------------------------------------
SELECT
	@FACILITY_ID = [FAC].[FACILITY_ID]
FROM
	[dbo].[FACILITY] AS [FAC] WITH (NOLOCK) 
WHERE
	[FAC].[NAME] = @FACILITY_NAME

IF @@ROWCOUNT > 1
BEGIN
	RAISERROR('Found multiple Facility IDs for Facility Name "%s"', 16, 1, @FACILITY_NAME) WITH NOWAIT
	RETURN
END
IF @FACILITY_ID IS NULL
BEGIN
	RAISERROR('Unable to find Facility ID for Facility Name "%s"', 16, 1, @FACILITY_NAME) WITH NOWAIT
	RETURN
END
-------------------------------------------------------
-- GET FACILITY AUTHORIZATION ID
-------------------------------------------------------
SELECT
	@FACILITY_USR_AUTH_ID = [FUA].[FACILITY_AUTH_ID]
FROM
	[dbo].[FACILITY_USER_AUTHORIZATION] AS [FUA] WITH (NOLOCK)
WHERE
	[FUA].[FACILITY_ID] = @FACILITY_ID
AND [FUA].[USER_PROFILE_ID] = @USER_ID
AND GETDATE() BETWEEN [FUA].[EFFECTIVE_DATE] AND [FUA].[EXPIRATION_DATE]

IF @@ROWCOUNT > 1
BEGIN
	RAISERROR('Found multiple active facility authorization entries for user "%s" at facility "%s"', 16, 1, @USER_NAME, @FACILITY_NAME) WITH NOWAIT
	RETURN
END
IF @FACILITY_USR_AUTH_ID IS NULL
BEGIN
	RAISERROR('Unable to find active facility authorization entry for user "%s" at facility "%s"', 0, 1, @USER_NAME, @FACILITY_NAME) WITH NOWAIT
	RETURN
END
-----------------------------------------------------------
-- GET EXPIRATION EXPIRATION DATE CHANGE REASON DESCRIPTION
-----------------------------------------------------------
SELECT
	@EXPIRY_REASON_DESCRIPTION = [DCR].[DESCRIPTION]
FROM
	[dbo].[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON] AS [DCR] WITH (NOLOCK)
WHERE
	[DCR].[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID] = @EXPIRY_REASON_ID

IF @EXPIRY_REASON_DESCRIPTION IS NULL 
BEGIN 
	RAISERROR('Unable to find an expiration reason entry for reason ID "%d"', 16, 1, @EXPIRY_REASON_ID) WITH NOWAIT 
	RETURN 
END 
-------------------------------------------------------
-- UPDATE BASED ON FINDINGS
-------------------------------------------------------
PRINT 'Attempting to set expiration date on user "' + @USER_NAME + '" for facility "' + @FACILITY_NAME + '"'

UPDATE
	[dbo].[FACILITY_USER_AUTHORIZATION]
SET
	[EXPIRATION_DATE] = CONVERT(DATETIME, @EXPIRY_DATE)
   ,[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID] = @EXPIRY_REASON_ID
   ,[CHANGED_DATE_TIME] = GETDATE()
   ,[CHANGING_USER_PROFILE_ID] = @ADMINISTRATOR_USER_PROFILE_ID
WHERE
	[FACILITY_AUTH_ID] = @FACILITY_USR_AUTH_ID

IF @@ROWCOUNT > 0
	PRINT 'SUCCESS'
ELSE
	PRINT 'FAIL'
---------------------------------------------------------------------
-- HANDLE LOGGING
---------------------------------------------------------------------
-- INSERT "FACILITY AUTHORIZATION" AUDIT LOG & AUDIT LOG OBJECT STATE
SET @FACILITY_COMMENT =				'Updated authorized facility ' + @FACILITY_NAME
SET @STATE_STRING =					'{"Expiration Date":"' 
								  + FORMAT(CONVERT(DATETIME, @EXPIRY_DATE), 'MM/dd/yyyy hh:mm:ss tt') 
								  + '","Expiration Date Changed Reason":"'
								  + CONVERT(VARCHAR, @EXPIRY_REASON_ID) + '=' + @EXPIRY_REASON_DESCRIPTION
								  + '"}'

EXEC [dbo].[AUDIT_LOG_INSERT]
	@OBJECT_TYPE =					'Facility Authorization'
   ,@OBJECT_ID = 					@FACILITY_USR_AUTH_ID
   ,@EVENT_NAME =					'Updated'
   ,@COMMENT =						''
   ,@CHANGING_USER_PROFILE_ID =		@ADMINISTRATOR_USER_PROFILE_ID
   ,@CHANGING_SIGN_ON_ID =			@ADMINISTRATOR_USERNAME
   ,@CHANGING_EMAIL_ADDRESS =		@ADMINISTRATOR_EMAIL_ADDR
   ,@CHANGING_FIRST_NAME =			@ADMINISTRATOR_FIRST_NAME
   ,@CHANGING_LAST_NAME =			@ADMINISTRATOR_LAST_NAME
   ,@AUDIT_LOG_ID =					@OUTPUT_AUDIT_LOG_ID OUTPUT

EXEC [dbo].[AUDIT_LOG_OBJECT_STATE_INSERT]
	@AUDIT_LOG_ID =					@OUTPUT_AUDIT_LOG_ID
   ,@STATE =						@STATE_STRING
   ,@AUDIT_LOG_OBJECT_STATE_ID =	@OUTPUT_AUDIT_LOG_OBJECT_STATE_ID

-- INSERT "USER PROFILE" AUDIT LOG & AUDIT LOG OBJECT STATE
EXEC [dbo].[AUDIT_LOG_INSERT]
	@OBJECT_TYPE =					'User Profile'
   ,@OBJECT_ID = 					@USER_ID
   ,@EVENT_NAME =					'Updated'
   ,@COMMENT =						@FACILITY_COMMENT
   ,@CHANGING_USER_PROFILE_ID =		@ADMINISTRATOR_USER_PROFILE_ID
   ,@CHANGING_SIGN_ON_ID =			@ADMINISTRATOR_USERNAME
   ,@CHANGING_EMAIL_ADDRESS =		@ADMINISTRATOR_EMAIL_ADDR
   ,@CHANGING_FIRST_NAME =			@ADMINISTRATOR_FIRST_NAME
   ,@CHANGING_LAST_NAME =			@ADMINISTRATOR_LAST_NAME
   ,@AUDIT_LOG_ID =					@OUTPUT_AUDIT_LOG_ID OUTPUT

EXEC [dbo].[AUDIT_LOG_OBJECT_STATE_INSERT]
	@AUDIT_LOG_ID =					@OUTPUT_AUDIT_LOG_ID
   ,@STATE =						@STATE_STRING
   ,@AUDIT_LOG_OBJECT_STATE_ID =	@OUTPUT_AUDIT_LOG_OBJECT_STATE_ID		


GO
