CREATE PROCEDURE [dbo].[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT_SELECT_BY_CEP_PROJECT_RECORD_ID_AND_CEP_COMMENT_OBJECT_TYPE_CODE]
	@CEP_PROJECT_RECORD_ID int,
	@CEP_COMMENT_OBJECT_TYPE_CODE int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT_ID]
	,[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CEP_PROJECT_RECORD_ID]
	,[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CEP_COMMENT_OBJECT_TYPE_CODE]
	,[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[COMMENT]
	,[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CREATION_DATE_TIME]
	,[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CREATING_USER_PROFILE_ID]
	,[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CHANGED_DATE_TIME]
	,[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CHANGING_USER_PROFILE_ID]
FROM
	[dbo].[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT]
WHERE
	[CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CEP_PROJECT_RECORD_ID] = @CEP_PROJECT_RECORD_ID
AND [CEP_PROJECT_RECORD_LEVEL_ONE_AUDIT_COMMENT].[CEP_COMMENT_OBJECT_TYPE_CODE] = @CEP_COMMENT_OBJECT_TYPE_CODE

GO
