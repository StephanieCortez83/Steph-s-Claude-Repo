CREATE PROCEDURE [dbo].[CHART_INFUSION_AUTOMATION_SELECT_BY_CHART_ID]
	 @CHART_ID int
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CHART_INFUSION_AUTOMATION_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)
DECLARE @KeyWhereClause nvarchar(1000)

SET @sql = 'INSERT INTO #tmp (CHART_INFUSION_AUTOMATION_ID) ' +
		   'SELECT [CHART_INFUSION_AUTOMATION].[CHART_INFUSION_AUTOMATION_ID] ' +
		   'FROM [CHART_INFUSION_AUTOMATION] ' +
		   'WHERE [CHART_INFUSION_AUTOMATION].[CHART_ID] = ' + CAST(@CHART_ID AS VARCHAR(10)) 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CHART_INFUSION_AUTOMATION].[CREATION_DATE_TIME] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CHART_INFUSION_AUTOMATION].[CHART_INFUSION_AUTOMATION_ID]
	,[CHART_INFUSION_AUTOMATION].[CREATION_DATE_TIME]
	,[CHART_INFUSION_AUTOMATION].[CREATING_USER_PROFILE_ID]
	,[CHART_INFUSION_AUTOMATION].[CHANGED_DATE_TIME]
	,[CHART_INFUSION_AUTOMATION].[CHANGING_USER_PROFILE_ID]
	,[CHART_INFUSION_AUTOMATION].[CHART_INFUSION_ID]
	,[CHART_INFUSION_AUTOMATION].[CHART_ID]
	,[CHART_INFUSION_AUTOMATION].[IV_SITE]
	,[CHART_INFUSION_AUTOMATION].[SUBSTANCE_NUMBER]
	,[CHART_INFUSION_AUTOMATION].[INFUSION_TYPE]
	,[CHART_INFUSION_AUTOMATION].[START_DATE]
	,[CHART_INFUSION_AUTOMATION].[STOP_DATE]
	,[CHART_INFUSION_AUTOMATION].[INITIALS]
	,[CHART_INFUSION_AUTOMATION].[NO_STOP_TIME]
	,[CHART_INFUSION_AUTOMATION].[UNITS]
	,[CHART_INFUSION_AUTOMATION].[CHARGE_MASTER_DEPT_ID]
	,[CHART_INFUSION_AUTOMATION].[GENERIC_SUBSTANCE_NAME]
	,[CHART_INFUSION_AUTOMATION].[ICD_10_PCS_CODE]
FROM
	#tmp [tmp]
	INNER JOIN [CHART_INFUSION_AUTOMATION] 
			ON [CHART_INFUSION_AUTOMATION].[CHART_INFUSION_AUTOMATION_ID] = [tmp].[CHART_INFUSION_AUTOMATION_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
