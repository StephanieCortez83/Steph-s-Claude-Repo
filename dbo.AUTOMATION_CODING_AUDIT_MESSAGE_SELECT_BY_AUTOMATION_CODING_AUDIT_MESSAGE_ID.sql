	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CHANGING_USER_PROFILE_ID]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CHART_ID]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[MESSAGE]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[IS_ACKNOWLEDGED]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[RULE_ID]
