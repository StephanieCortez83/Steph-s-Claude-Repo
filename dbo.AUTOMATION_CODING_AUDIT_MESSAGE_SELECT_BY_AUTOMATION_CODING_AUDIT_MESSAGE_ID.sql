	 [AUTOMATION_CODING_AUDIT_MESSAGE].[AUTOMATION_CODING_AUDIT_MESSAGE_ID]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CREATION_DATE_TIME]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CREATING_USER_PROFILE_ID]
