CREATE PROCEDURE [dbo].[CHART_SELECT_CONDITION_OF_ACCIDENT_ID_AND_DESCRIPTION_SERVICE_AGREEMENT_ID_BY_CHART_ID]
	 @CHART_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		 DISTINCT saca.CONDITION_OF_ACCIDENT_ID
		,saca.SERVICE_AGREEMENT_ID
		,saca.[DESCRIPTION]
    FROM 
		CHART c WITH (NOLOCK)
        join SERVICE_AGREEMENT sa WITH (NOLOCK) on sa.SERVICE_AGREEMENT_ID = c.SERVICE_AGREEMENT_ID
        join SERVICE_AGREEMENT_CONDITION_OF_ACCIDENT saca WITH (NOLOCK) on saca.SERVICE_AGREEMENT_ID=c.SERVICE_AGREEMENT_ID
        left outer join FACILITY_FINANCIAL_CLASS ffc WITH (NOLOCK) on ffc.SERVICE_AGREEMENT_ID=saca.SERVICE_AGREEMENT_ID
        left outer join SERVICE_AGREEMENT_PAYOR sap WITH (NOLOCK) on sap.SERVICE_AGREEMENT_ID=saca.SERVICE_AGREEMENT_ID
    WHERE
		c.CHART_ID=@CHART_ID
        AND (
             (ffc.COLLECT_CONDITION_OF_ACCIDENT_IND=1 OR sap.COLLECT_ACCIDENT_DATE=1)
             OR (sa.COLLECT_FINANCIAL_CLASS='N' AND sa.COLLECT_PAYOR='N')
            )
        AND DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) 
		    BETWEEN ISNULL(saca.EFFECTIVE_DATE, sa.EFFECTIVE_DATE) 
		AND ISNULL(saca.EXPIRATION_DATE, '12/31/9999');

GO
