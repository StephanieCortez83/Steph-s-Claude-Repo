CREATE PROCEDURE [dbo].[ICD_10_ADDITIONAL_INCLUSION_TERM_SELECT_BY_ICD_10_INCLUSION_TERM_ID]
	@ICD_10_INCLUSION_TERM_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		 [ICD_10_INCLUSION_TERM_ID]
		,[INCLUSION_TERM_DESC]
		,[FIRST_CODE]
		,[LAST_CODE]
		,[CREATION_DTTM]
		,[CREATED_BY_USER_ID]
		,[UPDATE_DTTM]
		,[UPDATED_BY_USER_ID]
	FROM 
		[dbo].[ICD_10_ADDITIONAL_INCLUSION_TERM] with (NOLOCK)
    WHERE
        ICD_10_INCLUSION_TERM_ID = @ICD_10_INCLUSION_TERM_ID
	
GO
