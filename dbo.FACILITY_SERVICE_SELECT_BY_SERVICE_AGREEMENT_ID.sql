CREATE   PROCEDURE [dbo].[FACILITY_SERVICE_SELECT_BY_SERVICE_AGREEMENT_ID]
--CREATE PROCEDURE [dbo].[FACILITY_SERVICE_SELECT_BY_SERVICE_AGREEMENT_ID]
	@SERVICE_AGREEMENT_ID INT
	,@Direction VARCHAR(4)
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	IF	@Direction = 'DESC'
	BEGIN
		SELECT  [FACILITY_SERVICE_ID]
				,[SERVICE_AGREEMENT_ID]
				,[MAX_POINTS]
				,[DESCRIPTION]
				,[LONG_DESCRIPTION]
				,[EXCLUSION_OPTION]
				,[SEQUENCE]
				,[EXPIRATION_DATE]
				,[CRITICAL_CARE]
				,[REQUIRE_25_MODIFIER]
		FROM	[dbo].[FACILITY_SERVICE]
		WHERE [SERVICE_AGREEMENT_ID] = @SERVICE_AGREEMENT_ID
		ORDER BY [SEQUENCE] DESC
	END
	ELSE
	BEGIN
		SELECT  [FACILITY_SERVICE_ID]
				,[SERVICE_AGREEMENT_ID]
				,[MAX_POINTS]
				,[DESCRIPTION]
				,[LONG_DESCRIPTION]
				,[EXCLUSION_OPTION]
				,[SEQUENCE]
				,[EXPIRATION_DATE]
				,[CRITICAL_CARE]
				,[REQUIRE_25_MODIFIER]
		FROM	[dbo].[FACILITY_SERVICE]
		WHERE [SERVICE_AGREEMENT_ID] = @SERVICE_AGREEMENT_ID
		ORDER BY [SEQUENCE]
	END
END

GO
