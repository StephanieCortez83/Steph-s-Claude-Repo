-- Author:		Daniel Bonebrake
-- Create date: 6/14/2013
-- Description:	SQL for LCD/NCD Medical Necessity Report
-- =============================================
CREATE PROCEDURE [dbo].[rpt_LCDMedicalNecessity] @StartDOS DATE,
	@EndDOS DATE = '12/31/9999',
	@Organization INT,
	@Facility INT = - 1,
	@MonthView BIT = 0,
  @DateType INT = 0, -- Default to DOS
  @ReportUser INT = 6
AS
BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

	DECLARE @m_StartDOS DATE = CASE 
			WHEN @MonthView = 0
				THEN @StartDOS
			ELSE DATEADD(dd, - (DAY(@StartDOS) - 1), @StartDOS)
			END;
	DECLARE @m_EndDOS DATE = CASE 
			WHEN @MonthView = 0
				THEN @EndDOS
			ELSE DATEADD(dd, - (DAY(DATEADD(mm, 1, @StartDOS))), DATEADD(mm, 1, @StartDOS))
			END;
	DECLARE @m_Organization INT = @Organization;
	DECLARE @m_Facility INT = @Facility;
  DECLARE @m_DateType INT = @DateType;
  DECLARE @m_ReportUser INT = @ReportUser;

-- LCDs
SELECT c.PHYSICIAN_ID,
	UPPER(fp.LAST_NAME + ', ' + fp.FIRST_NAME) PHYSICIAN_NAME,
	c.FACILITY_CHART_ID,
	UPPER(c.PATIENT_LAST_NAME + ', ' + c.PATIENT_FIRST_NAME) PATIENT_NAME,
	c.TIME_OF_SERVICE,
	lcd.TITLE [DESCRIPTION],
	CONVERT(VARCHAR, lcd.LCD_ID) LCD_ID,
	sal.CHARGE_AMOUNT
FROM CHART c WITH (NOLOCK)
INNER JOIN CHART_CMS_LCD ccl WITH (NOLOCK) ON ccl.CHART_ID = c.CHART_ID
INNER JOIN SERVICE_AGREEMENT sa WITH (NOLOCK) ON sa.SERVICE_AGREEMENT_ID = c.SERVICE_AGREEMENT_ID
INNER JOIN SERVICE_AGREEMENT_CMS_LCD sal WITH (NOLOCK) ON sal.SERVICE_AGREEMENT_ID = c.SERVICE_AGREEMENT_ID
	AND sal.LCD_ID = ccl.LCD_ID
INNER JOIN FACILITY_PROFESSIONAL fp WITH (NOLOCK) ON fp.FACILITY_PROF_ID = c.PHYSICIAN_ID
INNER JOIN CMS_LCD lcd WITH (NOLOCK) ON lcd.LCD_ID = ccl.LCD_ID
WHERE c.CHART_STATUS_ID = 5
	AND sa.PERFORM_DIAGNOSIS_CODING = 1
	AND sa.COMPANY_ID = @m_Organization
	AND (
		@m_Facility = - 1
		OR sa.FACILITY_ID = @m_Facility
		)
	AND (
		(
			@m_DateType = 0
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN @m_StartDOS AND @m_EndDOS
			)
		OR (
			@m_DateType = 1
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.SENT_DATE), 0) BETWEEN @m_StartDOS AND @m_EndDOS
			)
		)
	AND ccl.LCD_TYPE_CD = 'L'
	AND (
		SELECT COUNT(*)
		FROM CMS_LCD_ICD9_SUPPORT WITH (NOLOCK)
		INNER JOIN CHART_DIAGNOSIS_CODE WITH (NOLOCK) ON CHART_DIAGNOSIS_CODE.CHART_ID = c.CHART_ID
		WHERE CMS_LCD_ICD9_SUPPORT.LCD_ID = ccl.LCD_ID
			AND CHART_DIAGNOSIS_CODE.ICD9_CODE = CMS_LCD_ICD9_SUPPORT.ICD9_CODE_ID
		) = 0
  AND EXISTS (
    SELECT *
    FROM FACILITY_USER_AUTHORIZATION
    WHERE FACILITY_ID = c.FACILITY_ID
      AND USER_PROFILE_ID = @m_ReportUser
  )

UNION

-- NCDs
SELECT c.PHYSICIAN_ID,
	UPPER(fp.LAST_NAME + ', ' + fp.FIRST_NAME) PHYSICIAN_NAME,
	c.FACILITY_CHART_ID,
	UPPER(c.PATIENT_LAST_NAME + ', ' + c.PATIENT_FIRST_NAME) PATIENT_NAME,
	c.TIME_OF_SERVICE,
	ncd.NCD_MNL_SECT_TITLE [DESCRIPTION],
	ncd.NCD_mnl_sect LCD_ID,
	sal.CHARGE_AMOUNT
FROM CHART c WITH (NOLOCK)
INNER JOIN CHART_CMS_LCD ccl WITH (NOLOCK) ON ccl.CHART_ID = c.CHART_ID
INNER JOIN SERVICE_AGREEMENT sa WITH (NOLOCK) ON sa.SERVICE_AGREEMENT_ID = c.SERVICE_AGREEMENT_ID
INNER JOIN SERVICE_AGREEMENT_CMS_LCD sal WITH (NOLOCK) ON sal.SERVICE_AGREEMENT_ID = c.SERVICE_AGREEMENT_ID
	AND sal.LCD_ID = ccl.LCD_ID
INNER JOIN FACILITY_PROFESSIONAL fp WITH (NOLOCK) ON fp.FACILITY_PROF_ID = c.PHYSICIAN_ID
INNER JOIN CMS_NCD ncd WITH (NOLOCK) ON ncd.NCD_ID = ccl.LCD_ID
WHERE c.CHART_STATUS_ID = 5
	AND sa.PERFORM_DIAGNOSIS_CODING = 1
	AND sa.COMPANY_ID = @m_Organization
	AND (
		@m_Facility = - 1
		OR sa.FACILITY_ID = @m_Facility
		)
	AND (
		(
			@m_DateType = 0
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN @m_StartDOS AND @m_EndDOS
			)
		OR (
			@m_DateType = 1
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.SENT_DATE), 0) BETWEEN @m_StartDOS AND @m_EndDOS
			)
		)
	AND ccl.LCD_TYPE_CD = 'N'
	AND (
		SELECT COUNT(*)
		FROM CMS_NCD WITH (NOLOCK)
		INNER JOIN CHART_DIAGNOSIS_CODE WITH (NOLOCK) ON CHART_DIAGNOSIS_CODE.CHART_ID = c.CHART_ID
		INNER JOIN CMS_NCD_ICD9 WITH (NOLOCK) ON LEFT(cms_ncd_icd9.NCD_NUMBER, 6) = CMS_NCD.NCD_MNL_SECT
		WHERE CMS_NCD.NCD_ID = ccl.LCD_ID
			AND CMS_NCD_ICD9.RESOLUTION_CODE = '1'
			AND (
				CMS_NCD_ICD9.[ICD-9_CODE] = '@@@@@'
				OR (
					REPLACE(CHART_DIAGNOSIS_CODE.icd9_code, '.', '') BETWEEN CASE 
								WHEN CHARINDEX('-', CMS_NCD_ICD9.[ICD-9_CODE]) = 0
									THEN CMS_NCD_ICD9.[ICD-9_CODE]
								ELSE SUBSTRING(CMS_NCD_ICD9.[ICD-9_CODE], 1, (CHARINDEX('-', CMS_NCD_ICD9.[ICD-9_CODE]) - 1))
								END AND CASE 
								WHEN CHARINDEX('-', CMS_NCD_ICD9.[ICD-9_CODE]) = 0
									THEN CMS_NCD_ICD9.[ICD-9_CODE]
								ELSE SUBSTRING(CMS_NCD_ICD9.[ICD-9_CODE], (CHARINDEX('-', CMS_NCD_ICD9.[ICD-9_CODE]) + 1), (len(CMS_NCD_ICD9.[ICD-9_CODE]) - CHARINDEX('-', CMS_NCD_ICD9.[ICD-9_CODE])))
								END
					)
				)
		) = 0
  AND EXISTS (
    SELECT *
    FROM FACILITY_USER_AUTHORIZATION
    WHERE FACILITY_ID = c.FACILITY_ID
      AND USER_PROFILE_ID = @m_ReportUser
  )
ORDER BY FACILITY_CHART_ID
END




GO
