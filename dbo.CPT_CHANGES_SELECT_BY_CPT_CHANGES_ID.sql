CREATE PROCEDURE [dbo].[CPT_CHANGES_SELECT_BY_CPT_CHANGES_ID]
	@CPT_CHANGES_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [CPT_CHANGES].[CPT_CHANGES_ID]
	,[CPT_CHANGES].[CHART_ID]
	,[CPT_CHANGES].[CPT]
	,[CPT_CHANGES].[CPT_MODIFIERS]
	,[CPT_CHANGES].[CPT_COUNT]
	,[CPT_CHANGES].[CHANGE_REASON]
	,[CPT_CHANGES].[IS_ACTIVE]
	,[CPT_CHANGES].[CREATION_DATE_TIME]
	,[CPT_CHANGES].[CREATING_USER_PROFILE_ID]
	,[CPT_CHANGES].[CHANGED_DATE_TIME]
	,[CPT_CHANGES].[CHANGING_USER_PROFILE_ID]
	,[CPT_CHANGES].[IS_MATCH_PRESENT]
FROM
	[dbo].[CPT_CHANGES]
WHERE
	[CPT_CHANGES].[CPT_CHANGES_ID] = @CPT_CHANGES_ID

GO
