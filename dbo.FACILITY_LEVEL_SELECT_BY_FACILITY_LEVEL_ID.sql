--CREATE OR ALTER PROCEDURE [dbo].[FACILITY_LEVEL_SELECT_BY_FACILITY_LEVEL_ID]
CREATE PROCEDURE [dbo].[FACILITY_LEVEL_SELECT_BY_FACILITY_LEVEL_ID]
	@FACILITY_LEVEL_ID INT
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT	[FACILITY_LEVEL_ID]
			,[SERVICE_AGREEMENT_ID]
			,[LEVEL_LOW]
			,[LEVEL_HIGH]
			,[DESCRIPTION]
			,[CPT_CODE]
			,[MODIFIER]
			,[PROCEDURES]
			,[BILLING_CODE]
			,[CRITICAL_CARE]
			,[PATIENT_CLASS_ID]
			,[REPORTING_COLUMN]
			,[LEVEL_NUMBER]
			,[DEPARTMENT]
			,[CREATION_DATE_TIME]
			,[CREATING_USER_PROFILE_ID]
			,[CHANGED_DATE_TIME]
			,[CHANGING_USER_PROFILE_ID]
			,[OVERRIDE_LIST_IND]
			,[EFFECTIVE_DATE]
			,[EXPIRATION_DATE]
	FROM	[dbo].[FACILITY_LEVEL]
	WHERE [FACILITY_LEVEL_ID] = @FACILITY_LEVEL_ID
END

GO
