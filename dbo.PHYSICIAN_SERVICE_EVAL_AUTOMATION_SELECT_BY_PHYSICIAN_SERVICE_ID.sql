CREATE   PROCEDURE [dbo].[PHYSICIAN_SERVICE_EVAL_AUTOMATION_SELECT_BY_PHYSICIAN_SERVICE_ID]
	 @PHYSICIAN_SERVICE_ID int
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int = 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[PHYSICIAN_SERVICE_EVAL_AUTOMATION_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)

SET @sql = 'INSERT INTO #tmp (PHYSICIAN_SERVICE_EVAL_AUTOMATION_ID) ' +
		   'SELECT [PHYSICIAN_SERVICE_EVAL_AUTOMATION].[PHYSICIAN_SERVICE_EVAL_AUTOMATION_ID] ' +
		   'FROM [PHYSICIAN_SERVICE_EVAL_AUTOMATION] ' +
		   'WHERE [PHYSICIAN_SERVICE_EVAL_AUTOMATION].[PHYSICIAN_SERVICE_ID] = ' + CAST(@PHYSICIAN_SERVICE_ID AS VARCHAR(10)) 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [PHYSICIAN_SERVICE_EVAL_AUTOMATION].[DateTimeCreated] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [PHYSICIAN_SERVICE_EVAL_AUTOMATION].[PHYSICIAN_SERVICE_EVAL_AUTOMATION_ID]
	,[PHYSICIAN_SERVICE_EVAL_AUTOMATION].[CHART_ID]
	,[PHYSICIAN_SERVICE_EVAL_AUTOMATION].[PHYSICIAN_SERVICE_ID]
	,[PHYSICIAN_SERVICE_EVAL_AUTOMATION].[QUANTITY]
	,[PHYSICIAN_SERVICE_EVAL_AUTOMATION].[CREATION_DATE_TIME]
	,[PHYSICIAN_SERVICE_EVAL_AUTOMATION].[CREATING_USER_PROFILE_ID]
	,[PHYSICIAN_SERVICE_EVAL_AUTOMATION].[CHANGED_DATE_TIME]
	,[PHYSICIAN_SERVICE_EVAL_AUTOMATION].[CHANGING_USER_PROFILE_ID]
	,[PHYSICIAN_SERVICE_EVAL_AUTOMATION].[LEVEL_NUMBER]
FROM
	#tmp [tmp]
	INNER JOIN [PHYSICIAN_SERVICE_EVAL_AUTOMATION] 
			ON [PHYSICIAN_SERVICE_EVAL_AUTOMATION].[PHYSICIAN_SERVICE_EVAL_AUTOMATION_ID] = [tmp].[PHYSICIAN_SERVICE_EVAL_AUTOMATION_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]


GO
