SELECT
	 [CPT_CHANGE_REASON].[CPT_CHANGE_REASON_ID]
	,[CPT_CHANGE_REASON].[DISPLAY_NAME]
	,[CPT_CHANGE_REASON].[DESCRIPTION]
	,[CPT_CHANGE_REASON].[CREATION_DATE_TIME]
