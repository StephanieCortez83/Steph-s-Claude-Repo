CREATE PROCEDURE [dbo].[CEP_MENU_ITEM_RESTRICTION_SELECT]
	 @PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CEP_MENU_ITEM_RESTRICTION_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)

SET @sql = 'INSERT INTO #tmp (CEP_MENU_ITEM_RESTRICTION_ID) ' +
		   'SELECT [CEP_MENU_ITEM_RESTRICTION].[CEP_MENU_ITEM_RESTRICTION_ID] ' +
		   'FROM [CEP_MENU_ITEM_RESTRICTION] ' 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' WHERE (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CEP_MENU_ITEM_RESTRICTION].[CEP_MENU_ITEM_ID],[CEP_MENU_ITEM_RESTRICTION].[CEP_MENU_ITEM_RESTRICTION_ID]'

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CEP_MENU_ITEM_RESTRICTION].[CEP_MENU_ITEM_RESTRICTION_ID]
	,[CEP_MENU_ITEM_RESTRICTION].[CEP_MENU_ITEM_ID]
	,[CEP_MENU_ITEM_RESTRICTION].[CEP_USER_GROUP_RIGHT_TYPE_CODE]
	,[CEP_MENU_ITEM_RESTRICTION].[CREATION_DATE_TIME]
	,[CEP_MENU_ITEM_RESTRICTION].[CREATING_USER_PROFILE_ID]
	,[CEP_MENU_ITEM_RESTRICTION].[CHANGED_DATE_TIME]
	,[CEP_MENU_ITEM_RESTRICTION].[CHANGING_USER_PROFILE_ID]
FROM
	#tmp [tmp]
	INNER JOIN [CEP_MENU_ITEM_RESTRICTION] 
			ON [CEP_MENU_ITEM_RESTRICTION].[CEP_MENU_ITEM_RESTRICTION_ID] = [tmp].[CEP_MENU_ITEM_RESTRICTION_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
