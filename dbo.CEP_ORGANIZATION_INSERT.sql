CREATE PROCEDURE [dbo].[CEP_ORGANIZATION_INSERT]
	 @ORGANIZATION_NAME varchar(50)
	,@CEP_ORGANIZATION_TYPE_CODE int
	,@PRIMARY_CONTACT_FIRST_NAME varchar(50)
	,@PRIMARY_CONTACT_LAST_NAME varchar(50)
	,@PRIMARY_CONTACT_EMAIL_ADDRESS varchar(50)
	,@CONTRACT_ESTIMATED_VOLUME int = NULL
	,@CEP_CONTRACT_ESTIMATED_VOLUME_TYPE_CODE int = NULL
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@CEP_ORGANIZATION_ID int OUTPUT
AS

INSERT INTO [dbo].[CEP_ORGANIZATION]
(
	 [ORGANIZATION_NAME]
	,[CEP_ORGANIZATION_TYPE_CODE]
	,[PRIMARY_CONTACT_FIRST_NAME]
	,[PRIMARY_CONTACT_LAST_NAME]
	,[PRIMARY_CONTACT_EMAIL_ADDRESS]
	,[CONTRACT_ESTIMATED_VOLUME]
	,[CEP_CONTRACT_ESTIMATED_VOLUME_TYPE_CODE]
	,[CREATING_USER_PROFILE_ID]
	,[CHANGING_USER_PROFILE_ID]
)
VALUES
(
	 @ORGANIZATION_NAME
	,@CEP_ORGANIZATION_TYPE_CODE
	,@PRIMARY_CONTACT_FIRST_NAME
	,@PRIMARY_CONTACT_LAST_NAME
	,@PRIMARY_CONTACT_EMAIL_ADDRESS
	,@CONTRACT_ESTIMATED_VOLUME
	,@CEP_CONTRACT_ESTIMATED_VOLUME_TYPE_CODE
	,@CREATING_USER_PROFILE_ID
	,@CHANGING_USER_PROFILE_ID 
)

SET @CEP_ORGANIZATION_ID = @@IDENTITY

GO
