--CREATE OR ALTER PROCEDURE [dbo].[FACILITY_SERVICE_EVALUATION_SELECT_BY_CHART_ID] 
CREATE PROCEDURE [dbo].[FACILITY_SERVICE_EVALUATION_SELECT_BY_CHART_ID] 
	@CHART_ID INT, 
	@SortOrder INT, 
	@Direction VARCHAR(4)
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT	 [FACILITY_SVC_EVAL_ID]
			,[CHART_ID]
			,[FACILITY_SERVICE_ID]
			,[CREATION_DATE_TIME]
			,[CREATING_USER_PROFILE_ID]
			,[CHANGED_DATE_TIME]
			,[CHANGING_USER_PROFILE_ID]
			,[FACILITY_SERVICE_SCHEDULE_ID]
			,[FACILITY_SERVICE_SCHEDULE_ITEM_ID]
			,CASE
				(
					SELECT		COUNT(*)
					FROM	[dbo].[CODER_QA_REPORT_EXCLUSION] [ex]
					WHERE	[ex].[SOURCE_RECORD_TABLE_NAME] = 'FACILITY_SERVICE_EVALUATION'
							AND [ex].[KEY_VALUE_1] = [FACILITY_SVC_EVAL_ID]
				)
					WHEN 0 
					THEN 0
					ELSE 1
			  END AS [EXCLUDE_FROM_CODER_QA_REPORT]
	FROM	[dbo].[FACILITY_SERVICE_EVALUATION]
	WHERE 	((@CHART_ID = 0) OR ([CHART_ID] = @CHART_ID))
	ORDER BY 
		CASE WHEN @Direction = 'ASC' THEN (CASE WHEN @SortOrder = 0 THEN [FACILITY_SVC_EVAL_ID] 
												WHEN @SortOrder = 1 THEN [FACILITY_SERVICE_ID]
												WHEN @SortOrder = 2 THEN [FACILITY_SERVICE_SCHEDULE_ID]
												WHEN @SortOrder = 3 THEN [FACILITY_SERVICE_SCHEDULE_ITEM_ID]
												ELSE [FACILITY_SVC_EVAL_ID] END ) END ,
		CASE WHEN @Direction = 'DESC' THEN (CASE WHEN @SortOrder = 0 THEN [FACILITY_SVC_EVAL_ID] 
												WHEN @SortOrder = 1 THEN [FACILITY_SERVICE_ID]
												WHEN @SortOrder = 2 THEN [FACILITY_SERVICE_SCHEDULE_ID]
												WHEN @SortOrder = 3 THEN [FACILITY_SERVICE_SCHEDULE_ITEM_ID]
												ELSE [FACILITY_SVC_EVAL_ID] END )  END DESC
END

GO
