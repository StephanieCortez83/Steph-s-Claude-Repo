CREATE PROCEDURE [dbo].[GET_MAPPED_ICD10_TO_ICD9_CODE]
@ICD10Code varchar(10)
AS

if (select count(*) from ICD10CM_TO_ICD9CM_GEM_DEFAULT def
	where def.ICD_10_CODE = REPLACE(@ICD10Code, '.','')) > 0 
BEGIN
	SELECT TOP 1 df.DEFAULT_ICD_9_CODE FROM ICD10CM_TO_ICD9CM_GEM_DEFAULT df 
	WHERE  df.ICD_10_CODE = REPLACE(@ICD10Code, '.','')
END
	
ELSE IF (select count(*) FROM ICD10CM_TO_ICD9CM_GEM_DEFAULT def
		  where def.ICD_10_CODE = SUBSTRING(REPLACE(@ICD10Code, '.',''), 1, LEN(def.ICD_10_CODE))) > 0 
BEGIN 
	SELECT TOP 1 df.DEFAULT_ICD_9_CODE FROM ICD10CM_TO_ICD9CM_GEM_DEFAULT df 
	WHERE  df.ICD_10_CODE = SUBSTRING(REPLACE(@ICD10Code, '.',''), 1, LEN(df.ICD_10_CODE))
END	
				
ELSE IF (select count(*) from ICD10CM_TO_ICD9CM_GEM gm 
	WHERE    gm.ICD_10_CODE = REPLACE(@ICD10Code, '.','') 
	AND		 ((gm.APPROXIMATE_IND = 0) OR (gm.APPROXIMATE_IND = 1 and gm.SCENARIO = 0 ))) > 0
BEGIN
	SELECT cm2.ICD9_CODE
	FROM ICD10CM_TO_ICD9CM_GEM map, ICD_9_CM cm2  
	WHERE 
	   map.ICD_10_CODE = REPLACE(@ICD10Code, '.','') 
	   AND REPLACE(cm2.ICD9_CODE, '.','')  = map.ICD_9_CODE
	   AND ((map.APPROXIMATE_IND = 0) OR (map.APPROXIMATE_IND = 1 and map.SCENARIO = 0)) 
	   AND cm2.EFFECTIVE_DATE <= GetDate() and cm2.EXPIRATION_DATE >= GetDate()
	ORDER BY map.ICD_10_CODE, map.SCENARIO, map.CHOICE_LIST   	   
END

ELSE IF  (select count(*) from ICD10CM_TO_ICD9CM_GEM gm2 
		where gm2.ICD_10_CODE = REPLACE(@ICD10Code, '.','') 
		and   gm2.COMBINATION_IND = 1
		and   gm2.SCENARIO > 1) = 0
BEGIN 
	SELECT cm2.ICD9_CODE
	FROM ICD10CM_TO_ICD9CM_GEM map, ICD_9_CM cm2  
	WHERE 
	   map.ICD_10_CODE = REPLACE(@ICD10Code, '.','') 
	   AND REPLACE(cm2.ICD9_CODE, '.','')  = map.ICD_9_CODE
	   AND map.SCENARIO = 1
	   AND map.COMBINATION_IND = 1
	   AND cm2.EFFECTIVE_DATE <= GetDate() and cm2.EXPIRATION_DATE >= GetDate()
	ORDER BY map.ICD_10_CODE, map.SCENARIO, map.CHOICE_LIST   
END

ELSE IF  (select count(*) from ICD10CM_TO_ICD9CM_GEM gm2 
		where gm2.ICD_10_CODE = REPLACE(@ICD10Code, '.','') 
		and   gm2.COMBINATION_IND = 0
		and	  gm2.APPROXIMATE_IND = 1
		and   gm2.SCENARIO = 0) > 0

BEGIN
	SELECT cm2.ICD9_CODE
	FROM ICD10CM_TO_ICD9CM_GEM map, ICD_9_CM cm2  
	WHERE 
	   map.ICD_10_CODE = REPLACE(@ICD10Code, '.','') 
	   AND REPLACE(cm2.ICD9_CODE, '.','')  = map.ICD_9_CODE	   
	   AND map.SCENARIO = 0
	   AND map.COMBINATION_IND = 0
	   AND map.APPROXIMATE_IND = 1
	   AND cm2.EFFECTIVE_DATE <= GetDate() and cm2.EXPIRATION_DATE >= GetDate()
	ORDER BY map.ICD_9_CODE DESC
END

ELSE
		
BEGIN	
	SELECT cm2.ICD9_CODE
	FROM ICD10CM_TO_ICD9CM_GEM map, ICD_9_CM cm2  
	WHERE 
	   map.ICD_10_CODE = REPLACE(@ICD10Code, '.','') 
	   AND REPLACE(cm2.ICD9_CODE, '.','')  = map.ICD_9_CODE
	   AND map.SCENARIO = 1
	   AND map.COMBINATION_IND = 1
	   AND cm2.EFFECTIVE_DATE <= GetDate() and cm2.EXPIRATION_DATE >= GetDate()
	ORDER BY map.ICD_10_CODE, map.SCENARIO, map.CHOICE_LIST  		
END



GO
