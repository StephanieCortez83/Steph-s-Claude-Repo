CREATE PROCEDURE [dbo].[AUTOMATION_CODING_AUDIT_MESSAGE_SELECT_BY_CHART_ID]
	 @CHART_ID int
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[AUTOMATION_CODING_AUDIT_MESSAGE_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)
DECLARE @KeyWhereClause nvarchar(1000)

SET @sql = 'INSERT INTO #tmp (AUTOMATION_CODING_AUDIT_MESSAGE_ID) ' +
		   'SELECT [AUTOMATION_CODING_AUDIT_MESSAGE].[AUTOMATION_CODING_AUDIT_MESSAGE_ID] ' +
		   'FROM [AUTOMATION_CODING_AUDIT_MESSAGE] ' +
		   'WHERE [AUTOMATION_CODING_AUDIT_MESSAGE].[CHART_ID] = ' + CAST(@CHART_ID AS VARCHAR(10)) 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [AUTOMATION_CODING_AUDIT_MESSAGE].[CREATION_DATE_TIME] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [AUTOMATION_CODING_AUDIT_MESSAGE].[AUTOMATION_CODING_AUDIT_MESSAGE_ID]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CREATION_DATE_TIME]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CREATING_USER_PROFILE_ID]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CHANGED_DATE_TIME]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CHANGING_USER_PROFILE_ID]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[CHART_ID]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[MESSAGE]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[IS_ACKNOWLEDGED]
	,[AUTOMATION_CODING_AUDIT_MESSAGE].[RULE_ID]
FROM
	#tmp [tmp]
	INNER JOIN [AUTOMATION_CODING_AUDIT_MESSAGE] 
			ON [AUTOMATION_CODING_AUDIT_MESSAGE].[AUTOMATION_CODING_AUDIT_MESSAGE_ID] = [tmp].[AUTOMATION_CODING_AUDIT_MESSAGE_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
