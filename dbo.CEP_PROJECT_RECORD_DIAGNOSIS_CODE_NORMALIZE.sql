CREATE PROCEDURE [dbo].[CEP_PROJECT_RECORD_DIAGNOSIS_CODE_NORMALIZE]
	@CEP_PROJECT_RECORD_ID int
AS

UPDATE
	[CEP_PROJECT_RECORD_DIAGNOSIS_CODE]
SET
	[ORDINAL] = [ORDINAL_MAP].[NEW_ORDINAL]
FROM
	(
		SELECT
			[CEP_PROJECT_RECORD_DIAGNOSIS_CODE].[CEP_PROJECT_RECORD_DIAGNOSIS_CODE_ID],
			ROW_NUMBER() OVER (ORDER BY [ORDINAL] ASC, [CHANGED_DATE_TIME] DESC) AS [NEW_ORDINAL]
		FROM
			[CEP_PROJECT_RECORD_DIAGNOSIS_CODE] WITH (NOLOCK)
		WHERE
			[CEP_PROJECT_RECORD_DIAGNOSIS_CODE].[CEP_PROJECT_RECORD_ID] = @CEP_PROJECT_RECORD_ID
			AND
			[CEP_PROJECT_RECORD_DIAGNOSIS_CODE].[ORDINAL] IS NOT NULL
			AND
			[CEP_PROJECT_RECORD_DIAGNOSIS_CODE].[IS_DELETED] = 0
	) AS [ORDINAL_MAP]
	INNER JOIN [CEP_PROJECT_RECORD_DIAGNOSIS_CODE] 
			ON [ORDINAL_MAP].[CEP_PROJECT_RECORD_DIAGNOSIS_CODE_ID] = [CEP_PROJECT_RECORD_DIAGNOSIS_CODE].[CEP_PROJECT_RECORD_DIAGNOSIS_CODE_ID]
WHERE
	[CEP_PROJECT_RECORD_DIAGNOSIS_CODE].[Ordinal] <> [ORDINAL_MAP].[NEW_ORDINAL]
GO
