CREATE PROCEDURE [dbo].[OBSERVATION_EXCLUSION_HOURS_REASON_SELECT_DISTINCT_BY_SERVICE_AGREEMENT_ID]
	@SERVICE_AGREEMENT_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT DISTINCT 
	 [SERVICE_AGREEMENT_ID]
	,[EXCLUSION_HOURS_REASON_ID]
	,[DESCRIPTION]
FROM 
	[dbo].[OBSERVATION_EXCLUSION_HOURS_REASON] with (NOLOCK)
