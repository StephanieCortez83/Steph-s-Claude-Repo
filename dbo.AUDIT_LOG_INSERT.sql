CREATE PROCEDURE [dbo].[AUDIT_LOG_INSERT]
	@OBJECT_TYPE			  varchar(100)
   ,@OBJECT_ID				  int
   ,@EVENT_NAME				  varchar(50)  = NULL
   ,@COMMENT				  varchar(255) = NULL
   ,@CHANGING_USER_PROFILE_ID int   	   = NULL
   ,@CHANGING_SIGN_ON_ID	  varchar(15)  = NULL
   ,@CHANGING_EMAIL_ADDRESS	  varchar(50)  = NULL
   ,@CHANGING_FIRST_NAME	  varchar(50)  = NULL
   ,@CHANGING_LAST_NAME		  varchar(50)  = NULL   
   ,@AUDIT_LOG_ID			  int OUTPUT
AS

INSERT INTO [dbo].[AUDIT_LOG]
(
	[OBJECT_TYPE]
   ,[OBJECT_ID]
   ,[EVENT_NAME]
   ,[COMMENT]
   ,[CHANGING_USER_PROFILE_ID]
   ,[CHANGING_SIGN_ON_ID]
   ,[CHANGING_EMAIL_ADDRESS]
   ,[CHANGING_FIRST_NAME]
   ,[CHANGING_LAST_NAME]   
)
VALUES
(
	@OBJECT_TYPE
   ,@OBJECT_ID
   ,@EVENT_NAME
   ,@COMMENT
   ,@CHANGING_USER_PROFILE_ID
   ,@CHANGING_SIGN_ON_ID
   ,@CHANGING_EMAIL_ADDRESS
   ,@CHANGING_FIRST_NAME
   ,@CHANGING_LAST_NAME   
)

SET @AUDIT_LOG_ID = @@IDENTITY


GO
