CREATE PROCEDURE [dbo].[CHART_SELECT_ASSIGNED_TO_ID_AND_CHART_STATUS_ID_BY_CHART_ID]
	 @CHART_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		 [ASSIGNED_TO_ID]
		,[CHART_STATUS_ID]
    FROM 
		[dbo].[CHART] WITH (NOLOCK)
    WHERE 
		[CHART_ID] = @CHART_ID

GO
