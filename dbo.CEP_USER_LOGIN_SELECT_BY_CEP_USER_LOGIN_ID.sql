CREATE PROCEDURE [dbo].[CEP_USER_LOGIN_SELECT_BY_CEP_USER_LOGIN_ID]
	@CEP_USER_LOGIN_ID bigint
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [CEP_USER_LOGIN].[CEP_USER_LOGIN_ID]
	,[CEP_USER_LOGIN].[USER_PROFILE_ID]
	,[CEP_USER_LOGIN].[USER_IP_ADDRESS]
	,[CEP_USER_LOGIN].[CREATION_DATE_TIME]
	,[CEP_USER_LOGIN].[CREATING_USER_PROFILE_ID]
	,[CEP_USER_LOGIN].[CHANGED_DATE_TIME]
	,[CEP_USER_LOGIN].[CHANGING_USER_PROFILE_ID]
FROM
	[dbo].[CEP_USER_LOGIN]
WHERE
	[CEP_USER_LOGIN].[CEP_USER_LOGIN_ID] = @CEP_USER_LOGIN_ID

GO
