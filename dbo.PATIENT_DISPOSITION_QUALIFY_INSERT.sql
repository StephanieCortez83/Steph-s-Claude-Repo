CREATE PROCEDURE [dbo].[PATIENT_DISPOSITION_QUALIFY_INSERT]
	 @PATIENT_DISPOSITION_ID int
	,@PATIENT_DISPOSITION_DESCRIPTION varchar(50)
	,@OUTPATIENT_IND bit
	,@PATIENT_DISPOSITION_CREATED_ID int OUTPUT
AS

DECLARE @FOUND_PATIENT_DISPOSITION_ID int;

SELECT @FOUND_PATIENT_DISPOSITION_ID = [PATIENT_DISPOSITION_ID]
	FROM
		[dbo].[PATIENT_DISPOSITION] with (NOLOCK)
	WHERE
		([PATIENT_DISPOSITION_ID] = @PATIENT_DISPOSITION_ID) and 
		([DESCRIPTION] = @PATIENT_DISPOSITION_DESCRIPTION);

if @FOUND_PATIENT_DISPOSITION_ID is null
	BEGIN
		INSERT INTO [dbo].[PATIENT_DISPOSITION]
		(
			 [PATIENT_DISPOSITION_ID]
			,[DESCRIPTION]
			,[OUTPATIENT_IND]
		)
		VALUES
		(
			 @PATIENT_DISPOSITION_ID
			,@PATIENT_DISPOSITION_DESCRIPTION
			,@OUTPATIENT_IND		
		)

	END
ELSE
	BEGIN
		PRINT('PATIENT_DISPOSITION_QUALIFY_INSERT already exists.');
	END;

SET @PATIENT_DISPOSITION_CREATED_ID = @PATIENT_DISPOSITION_ID;
PRINT('PATIENT_DISPOSITION_CREATED_ID = ' + CAST(@PATIENT_DISPOSITION_CREATED_ID AS VARCHAR(32)));

GO
