CREATE OR ALTER PROCEDURE [dbo].[SelectChargeMasterForExportByServiceAgreementId]
	 @ServiceAgreementId INT
AS
BEGIN

	IF @ServiceAgreementId <= 0
	BEGIN
		SELECT Result = -1, Error = 'Error: SA Id is invalid.';
		RETURN;
	END;

	SELECT 
		 cm.CHARGE_MASTER_ID            
		,cm.SERVICE_AGREEMENT_ID            
		,cm.CHARGE_MASTER_CATEGORY_ID            
		,cm.[DESCRIPTION]
		,CPT_CODE            
		,BILLING_CODE            
		,MODIFIER_REQUIRED            
		,cm.CHARGE_MASTER_DEPT_ID            
		,cm.CHARGE_MASTER_USAGE_CODE            
		,cm.EFFECTIVE_DATE            
		,cm.EXPIRATION_DATE            
		,DISPLAY_SEQ            
		,LONG_DESCRIPTION            
		,MAX_QUANTITY            
		,cm.PATIENT_CLASS_ID            
		,ALIAS_BILLING_CODE            
		,cm.BYPASS_AUTO_APPROVAL            
		,OBSERVATION_PATIENT_ARRIVAL_SOURCE_ID            
		,OBSERVATION_HOUR_TYPE_ID            
		,OBSERVATION_TELEMETRY            
		,ALLOW_NEGATIVE_UNITS_IND            
		,SPECIAL_HANDLING_INSTRUCTIONS            
		,AGE_MINIMUM            
		,AGE_MAXIMUM 
		,cmc.[DESCRIPTION] AS CMCDescp
		,cmu.[DESCRIPTION] AS CMUDescp
		,cmd.[NAME] AS CMDName
		,(SELECT TOP 1 [DESCRIPTION] FROM PATIENT_CLASS pc WITH (NOLOCK) WHERE pc.PATIENT_CLASS_ID = cm.PATIENT_CLASS_ID AND pc.SERVICE_AGREEMENT_ID = @ServiceAgreementId AND EFFECTIVE_DATE <= GETDATE() AND (EXPIRATION_DATE IS NULL OR EXPIRATION_DATE <= GETDATE())) AS PCDescp
		,(SELECT TOP 1 CHARGE_AMOUNT FROM CHARGE_MASTER_CHARGE_AMOUNT cma WITH (NOLOCK) WHERE cma.CHARGE_MASTER_ID = cm.CHARGE_MASTER_ID AND EFFECTIVE_DATE <= GETDATE() AND (EXPIRATION_DATE IS NULL OR EXPIRATION_DATE <= GETDATE())) AS CHARGE_AMOUNT
	FROM 
		CHARGE_MASTER cm WITH (NOLOCK)
		JOIN CHARGE_MASTER_CATEGORY cmc WITH (NOLOCK) ON ( cmc.CHARGE_MASTER_CATEGORY_ID = cm.CHARGE_MASTER_CATEGORY_ID AND cmc.SERVICE_AGREEMENT_ID = @ServiceAgreementId)
		JOIN CHARGE_MASTER_USAGE_CODE cmu WITH (NOLOCK) ON cmu.CHARGE_MASTER_USAGE_CODE = cm.CHARGE_MASTER_USAGE_CODE
		JOIN CHARGE_MASTER_DEPARTMENT cmd WITH (NOLOCK) ON ( cmd.CHARGE_MASTER_DEPT_ID = cm.CHARGE_MASTER_DEPT_ID AND cmd.SERVICE_AGREEMENT_ID = @ServiceAgreementId)
	WHERE cm.SERVICE_AGREEMENT_ID = @ServiceAgreementId
		AND (cm.EFFECTIVE_DATE <= GETDATE() AND (cm.EXPIRATION_DATE IS NULL OR cm.EXPIRATION_DATE >= GETDATE()))
		AND cm.CPT_CODE <> ''
	ORDER BY cm.CPT_CODE


END -- end of stored procedure

GO