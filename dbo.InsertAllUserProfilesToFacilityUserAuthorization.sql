CREATE 
	--OR ALTER 
	PROCEDURE [dbo].[InsertAllUserProfilesToFacilityUserAuthorization]
	 @ServiceAgreementId int
	,@EffectiveDate datetime
AS

-- BEGIN TRANSACTION;
/* Give all user's (except for user's who already have authorization) authorization to the demo facility. */

INSERT INTO 
	[dbo].[FACILITY_USER_AUTHORIZATION]
	   ( [FACILITY_ID]
		,[USER_PROFILE_ID]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]    
		,[EFFECTIVE_DATE]
		,[EXPIRATION_DATE]
		,[CAN_APPROVE_CHARTS]
		,[AUDIT_APPROVAL_RATE]
		,[NUMBER_COMPLETED]
		,[AUDIT_PROCEDURE_RATE]    
		,[PROCEDURE_NUMBER_COMPLETED]
		,[ACCOUNT_MANAGER_IND]
		,[AUDIT_INFUSION_RATE]
		,[INFUSION_NUMBER_COMPLETED]
		,[AUDIT_OBSERVATION_RATE]    
		,[OBSERVATION_NUMBER_COMPLETED]
		,[CODER_AUTHORIZED_SERVICE_CODE]
		,[FACILITY_PROF_ID]
		,[SECOND_LEVEL_AUDIT_APPROVAL_RATE]
		,[FORCE_AUDIT]    
		,[ACTIVE_CHART_ID]
		,[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID]
		,[FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_OTHER_REASON]    
		,[EMR_ACCESS_EFFECTIVE_DATE]
		,[EMR_ACCESS_EXPIRATION_DATE]
		,[ALLOW_EMR_ACCESS]
		,[EMR_ACCESS_USER_PROFILE_ID]
	   )
	SELECT    
		@ServiceAgreementId
		, up.USER_PROFILE_ID
		,GETDATE()
		,6505
		,GETDATE()
		,6505    
		,@EffectiveDate
		,'12/21/2099'
		,'1'
		,0
		,0
		,0    
		,0
		,NULL
		,NULL
		,0
		,0    
		,0
		,0
		,NULL
		,0
		,NULL    
		,NULL
		,NULL
		,NULL    
		,NULL
		,NULL
		,NULL
		,NULL
	FROM [dbo].[USER_PROFILE] up
		LEFT OUTER JOIN [dbo].[FACILITY_USER_AUTHORIZATION] fua ON up.USER_PROFILE_ID = fua.USER_PROFILE_ID 
		AND fua.FACILITY_ID = @ServiceAgreementId
	WHERE 
		fua.USER_PROFILE_ID IS NULL 
		AND up.IS_ACTIVE = 'Y';

-- COMMIT TRANSACTION;

GO
