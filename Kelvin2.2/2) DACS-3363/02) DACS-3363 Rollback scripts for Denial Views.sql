   ON [GLOBAL_PROCEDURE_CODE_TYPE_CODE].[GLOBAL_PROCEDURE_CODE_TYPE_CODE] = [CEP_PROJECT_RECORD_PROCEDURE].[GLOBAL_PROCEDURE_CODE_TYPE_CODE]   
 LEFT  JOIN [GLOBAL_CPT_CODE]   
