 ,CASE [CEP_PROJECT_RECORD_PROCEDURE].[GLOBAL_PROCEDURE_CODE_TYPE_CODE]   
  WHEN 1 THEN [GLOBAL_CPT_CODE].[CODE]  
  WHEN 2 THEN [GLOBAL_HCPCS_CODE].[CODE]  
  END AS [GLOBAL_PROCEDURE_CODE]  
 ,CASE [CEP_PROJECT_RECORD_PROCEDURE].[GLOBAL_PROCEDURE_CODE_TYPE_CODE]   
  WHEN 1 THEN [GLOBAL_CPT_CODE].[SHORT_DESCRIPTION]  
  WHEN 2 THEN [GLOBAL_HCPCS_CODE].[SHORT_DESCRIPTION]  
  END AS [GLOBAL_PROCEDURE_CODE_SHORT_DESCRIPTION]  
 ,[PRIMARY_MODIFIER].[GLOBAL_MODIFIER_ID] AS [PRIMARY_MODIFIER_ID]  
 ,[PRIMARY_MODIFIER].[MODIFIER]    AS [PRIMARY_MODIFIER]  
 ,[PRIMARY_MODIFIER].[DESCRIPTION]   AS [PRIMARY_MODIFIER_DESCRIPTION]  
 ,(   
  -- convert the attached modifiers into a comma-delimited list  
  STUFF   
  (  
   (  
    SELECT ', ' + CAST([MODIFIER].[MODIFIER] as varchar(10))   
    FROM [dbo].[GLOBAL_MODIFIER] [MODIFIER]   
    INNER JOIN [CEP_PROJECT_RECORD_PROCEDURE_GLOBAL_MODIFIER] AS [PROCEDURE_MODIFIER]  
      ON [PROCEDURE_MODIFIER].[GLOBAL_MODIFIER_ID] = [MODIFIER].[GLOBAL_MODIFIER_ID]  
    WHERE [PROCEDURE_MODIFIER].[IS_DELETED] = 0  
      AND [PROCEDURE_MODIFIER].[CEP_PROJECT_RECORD_PROCEDURE_ID] = [CEP_PROJECT_RECORD_PROCEDURE].[CEP_PROJECT_RECORD_PROCEDURE_ID]  
    FOR XML PATH('')  
   )  
   ,1,1,''  
  )  
 ) AS [MODIFIERS]  
 ,[CEP_PROJECT_RECORD_PROCEDURE].[UNITS]  
 ,[CEP_PROJECT_RECORD_PROCEDURE].[IS_DELETED]  
