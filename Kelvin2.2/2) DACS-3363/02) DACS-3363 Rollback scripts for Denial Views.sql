CREATE VIEW [dbo].[VW_DENIAL_CLAIM_OUTCOME_NOTE_SUMMARY]
AS
SELECT   [DENIAL_CLAIM_OUTCOME_NOTE].[DENIAL_CLAIM_OUTCOME_NOTE_ID]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[DENIAL_CLAIM_OUTCOME_ID]
		,[DENIAL_CLAIM_OUTCOME].[DENIAL_CLAIM_ID]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[OBJECT_TYPE]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[EVENT_NAME]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[NOTE]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[IS_SYSTEM_GENERATED]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[IS_DELETED]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[USER_PROFILE_ID]
		,[USER_PROFILE].[FIRST_NAME] AS [USER_FIRST_NAME]
		,[USER_PROFILE].[LAST_NAME]	 AS [USER_LAST_NAME]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[CREATING_USER_PROFILE_ID] AS [CREATED_BY_USER_PROFILE_ID]
		,[CREATED_BY_USER_PROFILE].[FIRST_NAME] AS [CREATED_BY_USER_FIRST_NAME]
		,[CREATED_BY_USER_PROFILE].[LAST_NAME]	AS [CREATED_BY_USER_LAST_NAME]
		,[DENIAL_CLAIM_OUTCOME_NOTE].[CREATION_DATE_TIME]
		
FROM         
	[DENIAL_CLAIM_OUTCOME_NOTE]
	INNER JOIN [DENIAL_CLAIM_OUTCOME] 
			ON [DENIAL_CLAIM_OUTCOME].[DENIAL_CLAIM_OUTCOME_ID] = [DENIAL_CLAIM_OUTCOME_NOTE].[DENIAL_CLAIM_OUTCOME_ID]
	INNER JOIN [USER_PROFILE]
			ON [USER_PROFILE].[USER_PROFILE_ID] = [DENIAL_CLAIM_OUTCOME_NOTE].[USER_PROFILE_ID]
	INNER JOIN [USER_PROFILE] [CREATED_BY_USER_PROFILE]
			ON [CREATED_BY_USER_PROFILE].[USER_PROFILE_ID] = [DENIAL_CLAIM_OUTCOME_NOTE].[CHANGING_USER_PROFILE_ID]
