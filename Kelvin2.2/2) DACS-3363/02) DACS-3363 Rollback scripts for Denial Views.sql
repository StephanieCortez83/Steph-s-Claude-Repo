CREATE VIEW [dbo].[VW_DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_SUMMARY]

AS

SELECT [DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_ID]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[DENIAL_CLAIM_PROCEDURE_ID]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[ICD10_CODE]
	  ,[ICD_10_CODE_MASTER].[DESCRIPTION]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[IS_PRIMARY]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[ORDINAL]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[IS_DELETED]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[CREATION_DATE_TIME]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[CREATING_USER_PROFILE_ID]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[CHANGED_DATE_TIME]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[CHANGING_USER_PROFILE_ID]
FROM [dbo].[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE]
LEFT JOIN [ICD_10_CODE_MASTER]
	   ON [ICD_10_CODE_MASTER].[ICD_10_CODE] = [DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[ICD10_CODE]
WHERE
	[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[IS_DELETED] = 0
	AND 
	(
		-- if it's a user-acknowledged invalid dx code it won't be in the icd-10 master
		[ICD_10_CODE_MASTER].[ICD_10_CODE_MASTER_ID] IS NULL
		OR
		(
			-- otherwise grab the most up to date one
			[ICD_10_CODE_MASTER].[EFFECTIVE_DT]  <= CONVERT(date, GETDATE())
			AND 
			[ICD_10_CODE_MASTER].[EXPIRATION_DT] >= CONVERT(date, GETDATE())
		)
	)
GO

