CREATE VIEW [dbo].[VW_DENIAL_CLAIM_PROCEDURE_REVISION_SUMMARY]
AS
SELECT 
	   [DENIAL_CLAIM_PROCEDURE_REVISION_ID]
      ,[DENIAL_CLAIM_PROCEDURE_ID]
      ,[DENIAL_CLAIM_ID]
      ,[DATE_OF_SERVICE_START]
      ,[DATE_OF_SERVICE_END]
      ,[DENIAL_REVENUE_CODE_ID]
      ,[DENIAL_REVENUE_CODE]
      ,[DENIAL_REVENUE_CODE_DESCRIPTION]
      ,[GLOBAL_PROCEDURE_CODE_TYPE_CODE]
      ,[GLOBAL_PROCEDURE_CODE_TYPE_CODE_NAME]
      ,[GLOBAL_PROCEDURE_CODE_ID]
      ,[GLOBAL_PROCEDURE_CODE]
      ,[GLOBAL_PROCEDURE_CODE_SHORT_DESCRIPTION]
      ,[PRIMARY_DIAGNOSIS_CODE]
      ,[PRIMARY_DIAGNOSIS_CODE_DESCRIPTION]
      ,[REVISIONS].[DIAGNOSIS_CODES]
	  ,[PRIMARY_MODIFIER_ID]
	  ,[GLOBAL_MODIFIER].[MODIFIER]    AS [PRIMARY_MODIFIER]
	  ,[GLOBAL_MODIFIER].[DESCRIPTION] AS [PRIMARY_MODIFIER_DESCRIPTION]
	  ,[MODIFIERS]
      ,[CHARGE_AMOUNT]
      ,[UNITS]
      ,[PAYMENT_AMOUNT]
      ,[WRITE_OFF_AMOUNT]
      ,[ALLOWED_AMOUNT]      
      ,[DENIAL_REASON_CODE_ID]
      ,[DENIAL_REASON_CODE]
      ,[DENIAL_REASON_CODE_DESCRIPTION]
	  ,[DENIAL_REASON_GROUP_TYPE_CODE]
      ,[DENIAL_REASON_GROUP_TYPE_CODE_NAME]
      ,[DENIAL_REMIT_CODE_ID]
      ,[DENIAL_REMIT_CODE]
      ,[DENIAL_REMIT_CODE_DESCRIPTION]
      ,[DENIAL_CLAIM_ACTION_TYPE_CODE]
      ,[DENIAL_CLAIM_ACTION_TYPE_CODE_NAME]
      ,[DENIAL_CLAIM_ACTION_REASON_TYPE_CODE]
      ,[DENIAL_CLAIM_ACTION_REASON_TYPE_CODE_NAME]
	  ,[DENIAL_PAYOR_DETERMINATION_TYPE_CODE] -- deprecated
	  ,[DENIAL_PAYOR_DETERMINATION_TYPE_CODE_NAME] -- deprecated
	  ,[PAYOR_DETERMINATION_RECEIVED_DATETIME] -- deprecated
	  ,[FOLLOW_UP_DATETIME] -- deprecated
      ,[REVISION_DATE_TIME]
      ,[REVISION_USER_PROFILE_ID]
      ,[REVISION_USER_PROFILE_FIRST_NAME]
      ,[REVISION_USER_PROFILE_LAST_NAME]
      ,[IS_DELETED]
	  ,[PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE]
	  ,[PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE_NAME]
	  ,[PAID_GLOBAL_PROCEDURE_CODE_ID]
	  ,[PAID_GLOBAL_PROCEDURE_CODE]
	  ,[PAID_GLOBAL_PROCEDURE_CODE_SHORT_DESCRIPTION]
	  ,[LEVEL_1_DENIAL_PAYOR_DETERMINATION_TYPE_CODE]
	  ,[LEVEL_1_PAYOR_DETERMINATION_DATE_TIME]
	  ,[LEVEL_1_TICKET_NUMBER]
	  ,[LEVEL_2_DENIAL_PAYOR_DETERMINATION_TYPE_CODE]
	  ,[LEVEL_2_PAYOR_DETERMINATION_DATE_TIME]
	  ,[LEVEL_2_TICKET_NUMBER]
	  ,[PATIENT_RESPONSIBILITY_AMOUNT]
	  ,[DENIAL_REASONS]
FROM 
(
	SELECT
		 [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_PROCEDURE_ID]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_ID]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[DATE_OF_SERVICE_START]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[DATE_OF_SERVICE_END]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_REVENUE_CODE_ID]
		,[DENIAL_REVENUE_CODE].[CODE]		 AS [DENIAL_REVENUE_CODE]
		,[DENIAL_REVENUE_CODE].[DESCRIPTION] AS [DENIAL_REVENUE_CODE_DESCRIPTION]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[GLOBAL_PROCEDURE_CODE_TYPE_CODE]
		,[GLOBAL_PROCEDURE_CODE_TYPE_CODE].[DISPLAY_NAME] AS [GLOBAL_PROCEDURE_CODE_TYPE_CODE_NAME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[GLOBAL_PROCEDURE_CODE_ID]
		,CASE [DENIAL_CLAIM_PROCEDURE_REVISION].[GLOBAL_PROCEDURE_CODE_TYPE_CODE] 
			WHEN 1 THEN [GLOBAL_CPT_CODE].[CODE]
			WHEN 2 THEN [GLOBAL_HCPCS_CODE].[CODE]
		 END AS [GLOBAL_PROCEDURE_CODE]
		,CASE [DENIAL_CLAIM_PROCEDURE_REVISION].[GLOBAL_PROCEDURE_CODE_TYPE_CODE] 
			WHEN 1 THEN [GLOBAL_CPT_CODE].[SHORT_DESCRIPTION]
			WHEN 2 THEN [GLOBAL_HCPCS_CODE].[SHORT_DESCRIPTION]
		 END AS [GLOBAL_PROCEDURE_CODE_SHORT_DESCRIPTION]
		,[PRIMARY_DIAGNOSIS_CODE].[ICD10_CODE]   AS [PRIMARY_DIAGNOSIS_CODE]
		,[PRIMARY_DIAGNOSIS_CODE].[DESCRIPTION]	 AS [PRIMARY_DIAGNOSIS_CODE_DESCRIPTION]
		,(
		 	-- convert the attached diagnosis codes into a comma-delmited list
		 	STUFF
		 	(
		 		(
		 			SELECT ', ' + CAST([DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION].[ICD10_CODE] AS varchar(10))
		 			FROM
		 				[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION]
		 				LEFT JOIN [ICD_10_CODE_MASTER]
		 					   ON [ICD_10_CODE_MASTER].[ICD_10_CODE] = [DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION].[ICD10_CODE]
		 			WHERE
		 				[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]
		 				AND
		 				[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION].[IS_DELETED] = 0
		 				AND 
		 				(
		 					-- if it's a user-acknowledged invalid dx code it won't be in the icd-10 master
		 					[ICD_10_CODE_MASTER].[ICD_10_CODE_MASTER_ID] IS NULL
		 					OR
		 					(
		 						-- otherwise grab the most up to date one
		 						[ICD_10_CODE_MASTER].[EFFECTIVE_DT]  <= CONVERT(date, GETDATE())
		 			 			AND 
		 						[ICD_10_CODE_MASTER].[EXPIRATION_DT] >= CONVERT(date, GETDATE())
		 					)
		 				)
		 			FOR XML PATH('')
		 		)
		 		,1,1,''
		 	)
		 )  AS [DIAGNOSIS_CODES]
		,(
			SELECT TOP 1 [DENIAL_CLAIM_PROCEDURE_TO_GLOBAL_MODIFIER_REVISION].[GLOBAL_MODIFIER_ID]
			FROM [DENIAL_CLAIM_PROCEDURE_TO_GLOBAL_MODIFIER_REVISION]
			INNER JOIN [GLOBAL_MODIFIER]
					ON [GLOBAL_MODIFIER].[GLOBAL_MODIFIER_ID] = [DENIAL_CLAIM_PROCEDURE_TO_GLOBAL_MODIFIER_REVISION].[GLOBAL_MODIFIER_ID]
			WHERE [DENIAL_CLAIM_PROCEDURE_TO_GLOBAL_MODIFIER_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]
			ORDER BY
				[GLOBAL_MODIFIER].[MODIFIER]
		 ) AS [PRIMARY_MODIFIER_ID]
		,( 
			STUFF 
			(
				(
					SELECT ', ' + CAST([MODIFIER].[MODIFIER] as varchar(10)) 
					FROM [dbo].[GLOBAL_MODIFIER] [MODIFIER] 
					INNER JOIN [DENIAL_CLAIM_PROCEDURE_TO_GLOBAL_MODIFIER_REVISION] AS [PROCEDURE_MODIFIER]
							ON [PROCEDURE_MODIFIER].[GLOBAL_MODIFIER_ID] = [MODIFIER].[GLOBAL_MODIFIER_ID]
					WHERE [PROCEDURE_MODIFIER].[IS_DELETED] = 0
					  AND [PROCEDURE_MODIFIER].[DENIAL_CLAIM_PROCEDURE_REVISION_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]
					FOR XML PATH('')
				)
				,1,1,''
			)
		) AS [MODIFIERS]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[CHARGE_AMOUNT]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[UNITS]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[PAYMENT_AMOUNT]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[WRITE_OFF_AMOUNT]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[ALLOWED_AMOUNT]
		,[PRIMARY_DENIAL_REASON].[DENIAL_REASON_CODE_ID]
		,[DENIAL_REASON_CODE].[CODE]					 AS [DENIAL_REASON_CODE] 
		,[DENIAL_REASON_CODE].[SHORT_DESCRIPTION]		 AS [DENIAL_REASON_CODE_DESCRIPTION]
		,[PRIMARY_DENIAL_REASON].[DENIAL_REASON_GROUP_TYPE_CODE]
		,[DENIAL_REASON_GROUP_TYPE_CODE].[EXTERNAL_CODE] AS [DENIAL_REASON_GROUP_TYPE_CODE_NAME]
		,[DENIAL_REASON_CODE].[DENIAL_TYPE_CODE]
		,[DENIAL_TYPE_CODE].[DISPLAY_NAME]				 AS [DENIAL_TYPE_CODE_NAME]
		,[PRIMARY_DENIAL_REASON].[DENIAL_REMIT_CODE_ID]
		,[DENIAL_REMIT_CODE].[CODE]					     AS [DENIAL_REMIT_CODE] 
		,[DENIAL_REMIT_CODE].[SHORT_DESCRIPTION]		 AS [DENIAL_REMIT_CODE_DESCRIPTION] 
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_ACTION_TYPE_CODE]
		,[DENIAL_CLAIM_ACTION_TYPE_CODE].[DISPLAY_NAME] AS [DENIAL_CLAIM_ACTION_TYPE_CODE_NAME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_ACTION_REASON_TYPE_CODE]
		,[DENIAL_CLAIM_ACTION_REASON_TYPE_CODE].[DISPLAY_NAME] AS [DENIAL_CLAIM_ACTION_REASON_TYPE_CODE_NAME]		
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_PAYOR_DETERMINATION_TYPE_CODE]
		,[DENIAL_PAYOR_DETERMINATION_TYPE_CODE].[DISPLAY_NAME] AS [DENIAL_PAYOR_DETERMINATION_TYPE_CODE_NAME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[PAYOR_DETERMINATION_RECEIVED_DATETIME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[FOLLOW_UP_DATETIME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[REVISION_DATE_TIME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[REVISION_USER_PROFILE_ID]
		,[USER_PROFILE].[FIRST_NAME]  AS [REVISION_USER_PROFILE_FIRST_NAME]
		,[USER_PROFILE].[LAST_NAME]	  AS [REVISION_USER_PROFILE_LAST_NAME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[IS_DELETED]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE]
		,[PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE].[DISPLAY_NAME] AS [PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE_NAME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[PAID_GLOBAL_PROCEDURE_CODE_ID]
		,CASE [DENIAL_CLAIM_PROCEDURE_REVISION].[PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE] 
			WHEN 1 THEN [PAID_GLOBAL_CPT_CODE].[CODE]
			WHEN 2 THEN [PAID_GLOBAL_HCPCS_CODE].[CODE]
		 END AS [PAID_GLOBAL_PROCEDURE_CODE]
		,CASE [DENIAL_CLAIM_PROCEDURE_REVISION].[PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE] 
			WHEN 1 THEN [PAID_GLOBAL_CPT_CODE].[SHORT_DESCRIPTION]
			WHEN 2 THEN [PAID_GLOBAL_HCPCS_CODE].[SHORT_DESCRIPTION]
		 END AS [PAID_GLOBAL_PROCEDURE_CODE_SHORT_DESCRIPTION]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[LEVEL_1_DENIAL_PAYOR_DETERMINATION_TYPE_CODE]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[LEVEL_1_PAYOR_DETERMINATION_DATE_TIME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[LEVEL_1_TICKET_NUMBER]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[LEVEL_2_DENIAL_PAYOR_DETERMINATION_TYPE_CODE]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[LEVEL_2_PAYOR_DETERMINATION_DATE_TIME]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[LEVEL_2_TICKET_NUMBER]
		,[DENIAL_CLAIM_PROCEDURE_REVISION].[PATIENT_RESPONSIBILITY_AMOUNT]
		,( 
			-- convert the attached denial reasons, denial reason group types and denial remit code combinations into a comma-delimited list
			STUFF 
			(
				(
					--SELECT ', ' + CONCAT([DENIAL_REASON_CODE].[CODE], [DENIAL_REASON_GROUP_TYPE_CODE].[EXTERNAL_CODE])
					SELECT ', ' + CASE 
							WHEN [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REASON_GROUP_TYPE_CODE] > 0 AND [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REMIT_CODE_ID] IS NOT NULL
								THEN CONCAT([DENIAL_REASON_CODE].[CODE], ' - ', [DENIAL_REASON_GROUP_TYPE_CODE].[EXTERNAL_CODE], ' - ', [DENIAL_REMIT_CODE].[CODE])
							WHEN [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REASON_GROUP_TYPE_CODE] > 0
								THEN CONCAT([DENIAL_REASON_CODE].[CODE], ' - ', [DENIAL_REASON_GROUP_TYPE_CODE].[EXTERNAL_CODE])
							ELSE 
								[DENIAL_REASON_CODE].[CODE]
							END
					FROM [dbo].[DENIAL_REASON_CODE]
					INNER JOIN [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION]
							ON [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REASON_CODE_ID] = [DENIAL_REASON_CODE].[DENIAL_REASON_CODE_ID]
					LEFT  JOIN [DENIAL_REASON_GROUP_TYPE_CODE]
							ON [DENIAL_REASON_GROUP_TYPE_CODE].[DENIAL_REASON_GROUP_TYPE_CODE] = [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REASON_GROUP_TYPE_CODE]
					LEFT  JOIN [DENIAL_REMIT_CODE]
		 					ON [DENIAL_REMIT_CODE].[DENIAL_REMIT_CODE_ID] = [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REMIT_CODE_ID] 
					WHERE [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]
					FOR XML PATH('')
				)
				,1,1,''
			)
		) AS [DENIAL_REASONS]
	FROM            
		[DENIAL_CLAIM_PROCEDURE_REVISION]	
		LEFT  JOIN [DENIAL_REVENUE_CODE]
				ON [DENIAL_REVENUE_CODE].[DENIAL_REVENUE_CODE_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_REVENUE_CODE_ID]
		LEFT  JOIN [GLOBAL_PROCEDURE_CODE_TYPE_CODE]
				ON [GLOBAL_PROCEDURE_CODE_TYPE_CODE].[GLOBAL_PROCEDURE_CODE_TYPE_CODE] = [DENIAL_CLAIM_PROCEDURE_REVISION].[GLOBAL_PROCEDURE_CODE_TYPE_CODE] 
		LEFT  JOIN [DENIAL_CLAIM_ACTION_TYPE_CODE]
				ON [DENIAL_CLAIM_ACTION_TYPE_CODE].[DENIAL_CLAIM_ACTION_TYPE_CODE] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_ACTION_TYPE_CODE]
		LEFT  JOIN [DENIAL_CLAIM_ACTION_REASON_TYPE_CODE] 
				ON [DENIAL_CLAIM_ACTION_REASON_TYPE_CODE].[DENIAL_CLAIM_ACTION_REASON_TYPE_CODE] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_ACTION_REASON_TYPE_CODE] 
		LEFT  JOIN [DENIAL_PAYOR_DETERMINATION_TYPE_CODE]
				ON [DENIAL_PAYOR_DETERMINATION_TYPE_CODE].[DENIAL_PAYOR_DETERMINATION_TYPE_CODE] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_PAYOR_DETERMINATION_TYPE_CODE]
		LEFT  JOIN [GLOBAL_CPT_CODE] 
				ON [GLOBAL_CPT_CODE].[GLOBAL_CPT_CODE_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[GLOBAL_PROCEDURE_CODE_ID]
		LEFT  JOIN [GLOBAL_HCPCS_CODE]
				ON [GLOBAL_HCPCS_CODE].[GLOBAL_HCPCS_CODE_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[GLOBAL_PROCEDURE_CODE_ID]
		LEFT  JOIN [GLOBAL_PROCEDURE_CODE_TYPE_CODE] AS [PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE]
				ON [PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE].[GLOBAL_PROCEDURE_CODE_TYPE_CODE] = [DENIAL_CLAIM_PROCEDURE_REVISION].[PAID_GLOBAL_PROCEDURE_CODE_TYPE_CODE] 
		LEFT  JOIN [GLOBAL_CPT_CODE] AS [PAID_GLOBAL_CPT_CODE] 
				ON [PAID_GLOBAL_CPT_CODE].[GLOBAL_CPT_CODE_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[PAID_GLOBAL_PROCEDURE_CODE_ID]
		LEFT  JOIN [GLOBAL_HCPCS_CODE] AS [PAID_GLOBAL_HCPCS_CODE]
				ON [PAID_GLOBAL_HCPCS_CODE].[GLOBAL_HCPCS_CODE_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[PAID_GLOBAL_PROCEDURE_CODE_ID]
		LEFT  JOIN [USER_PROFILE]
				ON [USER_PROFILE].[USER_PROFILE_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[REVISION_USER_PROFILE_ID]

		LEFT  JOIN 
		(
			SELECT [DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]
				  ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION].[ICD10_CODE]
				  ,ISNULL([ICD_10_CODE_MASTER].[DESCRIPTION], 'Unknown') AS [DESCRIPTION]
			FROM
				[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION]
				LEFT JOIN [ICD_10_CODE_MASTER]
					   ON [ICD_10_CODE_MASTER].[ICD_10_CODE] = [DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION].[ICD10_CODE]
			WHERE
				[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE_REVISION].[IS_PRIMARY] = 1
				AND 
				(
					-- if it's a user-acknowledged invalid dx code it won't be in the icd-10 master
					[ICD_10_CODE_MASTER].[ICD_10_CODE_MASTER_ID] IS NULL
					OR
					(
						-- otherwise grab the most up to date one
						[ICD_10_CODE_MASTER].[EFFECTIVE_DT]  <= CONVERT(date, GETDATE())
						AND 
						[ICD_10_CODE_MASTER].[EXPIRATION_DT] >= CONVERT(date, GETDATE())
					)
				)
		) AS [PRIMARY_DIAGNOSIS_CODE]
		  ON [PRIMARY_DIAGNOSIS_CODE].[DENIAL_CLAIM_PROCEDURE_REVISION_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]

		 LEFT  JOIN
		 (
		 	SELECT [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]
		 		  ,[DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REASON_CODE_ID]
		 		  ,[DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REASON_GROUP_TYPE_CODE]			  
		 		  ,[DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_REMIT_CODE_ID]			  
		 		  ,ROW_NUMBER() OVER (PARTITION BY [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID] ORDER BY [DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION].[CREATION_DATE_TIME]) AS [ROW_NUMBER]
		 	FROM 
		 		[DENIAL_CLAIM_PROCEDURE_TO_DENIAL_REASON_CODE_REVISION]
		 ) AS [PRIMARY_DENIAL_REASON]
		   ON [PRIMARY_DENIAL_REASON].[DENIAL_CLAIM_PROCEDURE_REVISION_ID] = [DENIAL_CLAIM_PROCEDURE_REVISION].[DENIAL_CLAIM_PROCEDURE_REVISION_ID]
		  AND [PRIMARY_DENIAL_REASON].[ROW_NUMBER] = 1

		  LEFT  JOIN [DENIAL_REASON_CODE]
