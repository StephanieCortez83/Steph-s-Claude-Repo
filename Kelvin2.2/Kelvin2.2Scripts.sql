      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[CHANGED_DATE_TIME]
      ,[DENIAL_CLAIM_PROCEDURE_DIAGNOSIS_CODE].[CHANGING_USER_PROFILE_ID]
