CREATE PROCEDURE [dbo].[CEP_MENU_ITEM_SELECT_BY_PARENT_CEP_MENU_ITEM_ID]
	 @PARENT_CEP_MENU_ITEM_ID int = NULL
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CEP_MENU_ITEM_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)
DECLARE @KeyWhereClause nvarchar(1000)

SET @sql = 'INSERT INTO #tmp (CEP_MENU_ITEM_ID) ' +
		   'SELECT [CEP_MENU_ITEM].[CEP_MENU_ITEM_ID] ' +
		   'FROM [CEP_MENU_ITEM] ' +
		   'WHERE [CEP_MENU_ITEM].[PARENT_CEP_MENU_ITEM_ID] = ' + CAST(@PARENT_CEP_MENU_ITEM_ID AS VARCHAR(10)) 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CEP_MENU_ITEM].[PARENT_CEP_MENU_ITEM_ID],[CEP_MENU_ITEM].[ORDINAL] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CEP_MENU_ITEM].[CEP_MENU_ITEM_ID]
	,[CEP_MENU_ITEM].[PARENT_CEP_MENU_ITEM_ID]
	,[CEP_MENU_ITEM].[CEP_MENU_ITEM_TYPE_CODE]
	,[CEP_MENU_ITEM].[ORDINAL]
	,[CEP_MENU_ITEM].[LABEL]
	,[CEP_MENU_ITEM].[HELP_TEXT]
	,[CEP_MENU_ITEM].[PAGE_URL]
	,[CEP_MENU_ITEM].[ICON_URL]
	,[CEP_MENU_ITEM].[CREATION_DATE_TIME]
	,[CEP_MENU_ITEM].[CREATING_USER_PROFILE_ID]
	,[CEP_MENU_ITEM].[CHANGED_DATE_TIME]
	,[CEP_MENU_ITEM].[CHANGING_USER_PROFILE_ID]
FROM
	#tmp [tmp]
	INNER JOIN [CEP_MENU_ITEM] 
			ON [CEP_MENU_ITEM].[CEP_MENU_ITEM_ID] = [tmp].[CEP_MENU_ITEM_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
