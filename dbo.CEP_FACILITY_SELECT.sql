CREATE PROCEDURE [dbo].[CEP_FACILITY_SELECT]
	 @PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CEP_FACILITY_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)

SET @sql = 'INSERT INTO #tmp (CEP_FACILITY_ID) ' +
		   'SELECT [CEP_FACILITY].[CEP_FACILITY_ID] ' +
		   'FROM [CEP_FACILITY] ' 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' WHERE (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CEP_FACILITY].[FACILITY_NAME]'

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CEP_FACILITY].[CEP_FACILITY_ID]
	,[CEP_FACILITY].[CEP_ORGANIZATION_ID]
	,[CEP_FACILITY].[FACILITY_NAME]
	,[CEP_FACILITY].[CEP_FACILITY_TYPE_CODE]
	,[CEP_FACILITY].[PRIMARY_CONTACT_FIRST_NAME]
	,[CEP_FACILITY].[PRIMARY_CONTACT_LAST_NAME]
	,[CEP_FACILITY].[PRIMARY_CONTACT_EMAIL_ADDRESS]
	,[CEP_FACILITY].[CREATION_DATE_TIME]
	,[CEP_FACILITY].[CREATING_USER_PROFILE_ID]
	,[CEP_FACILITY].[CHANGED_DATE_TIME]
	,[CEP_FACILITY].[CHANGING_USER_PROFILE_ID]
FROM
	#tmp [tmp]
	INNER JOIN [CEP_FACILITY] 
			ON [CEP_FACILITY].[CEP_FACILITY_ID] = [tmp].[CEP_FACILITY_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]
GO
