CREATE PROCEDURE [dbo].[CHART_ACCESS_SELECT_SIGN_ON_ID_BY_CHART_ID_AND_CHART_ACCESS_EVENT_TYPE_CODE]
    @CHART_ID                       INT
   ,@CHART_ACCESS_EVENT_TYPE_CODE   VARCHAR(1)
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT 
    [UP].[SIGN_ON_ID] 
FROM 
    [USER_PROFILE] AS [UP] WITH(NOLOCK) 
JOIN 
    [CHART_ACCESS] AS [CA] WITH(NOLOCK) 
ON  [UP].[USER_PROFILE_ID] = [CA].[USER_PROFILE_ID] 
WHERE 
    [CA].[CHART_ID] = @CHART_ID 
AND [CA].[CHART_ACCESS_EVENT_TYPE_CODE] = @CHART_ACCESS_EVENT_TYPE_CODE 
AND [CA].[CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE] IS NULL

GO
