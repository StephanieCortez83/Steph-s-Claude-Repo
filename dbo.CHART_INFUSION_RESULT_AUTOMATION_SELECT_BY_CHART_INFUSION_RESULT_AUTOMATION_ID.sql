CREATE PROCEDURE [dbo].[CHART_INFUSION_RESULT_AUTOMATION_SELECT_BY_CHART_INFUSION_RESULT_AUTOMATION_ID]
	@CHART_INFUSION_RESULT_AUTOMATION_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [CHART_INFUSION_RESULT_AUTOMATION].[CHART_INFUSION_RESULT_AUTOMATION_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[CREATION_DATE_TIME]
	,[CHART_INFUSION_RESULT_AUTOMATION].[CREATING_USER_PROFILE_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[CHANGED_DATE_TIME]
	,[CHART_INFUSION_RESULT_AUTOMATION].[CHANGING_USER_PROFILE_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[CHART_INFUSION_RESULT_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[CHART_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[UNITS]
	,[CHART_INFUSION_RESULT_AUTOMATION].[CHARGE_MASTER_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[MODIFIERS]
	,[CHART_INFUSION_RESULT_AUTOMATION].[CHART_INFUSION_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[DATE_OF_SERVICE]
	,[CHART_INFUSION_RESULT_AUTOMATION].[OBS_DEPT_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[ICD_10_DRUG_CATEGORY_ID]
	,[CHART_INFUSION_RESULT_AUTOMATION].[ICD_10_PCS_CODE]
	,[CHART_INFUSION_RESULT_AUTOMATION].[ICD_10_PCS_BODY_SYSTEM_CHARACTER]
FROM
	[dbo].[CHART_INFUSION_RESULT_AUTOMATION]
WHERE
	[CHART_INFUSION_RESULT_AUTOMATION].[CHART_INFUSION_RESULT_AUTOMATION_ID] = @CHART_INFUSION_RESULT_AUTOMATION_ID

GO
