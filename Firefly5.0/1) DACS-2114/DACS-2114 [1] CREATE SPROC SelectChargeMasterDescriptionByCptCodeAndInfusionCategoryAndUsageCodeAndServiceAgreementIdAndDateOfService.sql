CREATE OR ALTER PROCEDURE [dbo].[SelectChargeMasterDescriptionByCptCodeAndInfusionCategoryAndUsageCodeAndServiceAgreementIdAndDateOfService]
    @CptCode            VARCHAR(5)
   ,@InfusionCategory   BIT
   ,@UsageCode          INT
   ,@ServiceAgreementId INT  
   ,@DateOfService      DATE
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT TOP 1 
    [CHARGE_MASTER].[DESCRIPTION] 
FROM 
    [CHARGE_MASTER] WITH (NOLOCK)
INNER JOIN 
    [CHARGE_MASTER_CATEGORY] WITH (NOLOCK)
ON  [CHARGE_MASTER].[CHARGE_MASTER_CATEGORY_ID] = [CHARGE_MASTER_CATEGORY].[CHARGE_MASTER_CATEGORY_ID]
WHERE 
    [CHARGE_MASTER].[CPT_CODE] = @CptCode 
AND [CHARGE_MASTER].[CHARGE_MASTER_USAGE_CODE] = @UsageCode
AND [CHARGE_MASTER].[SERVICE_AGREEMENT_ID] = @ServiceAgreementId
AND @DateOfService BETWEEN [CHARGE_MASTER].[EFFECTIVE_DATE] AND [CHARGE_MASTER].[EXPIRATION_DATE]
AND 
(
    (
        @InfusionCategory = 1 AND [CHARGE_MASTER_CATEGORY].[INFUSION_CATEGORY] = 1
    )
    OR
    (
        @InfusionCategory = 0 AND 
        (
            [CHARGE_MASTER_CATEGORY].[INFUSION_CATEGORY] = 0
        OR  [CHARGE_MASTER_CATEGORY].[INFUSION_CATEGORY] IS NULL
        )
    )
)
ORDER BY 
    [CHARGE_MASTER].[EFFECTIVE_DATE] DESC

GO