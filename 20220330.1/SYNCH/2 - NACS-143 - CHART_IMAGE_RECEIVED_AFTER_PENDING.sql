CREATE PROCEDURE [dbo].[CHART_IMAGE_RECEIVED_AFTER_PENDING]
	 @CHART_ID int
    ,@RETURN bit OUTPUT
AS


SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

DECLARE @CREATION_DATE_TIME1 DateTime
DECLARE @CREATION_DATE_TIME2 DateTime

SELECT
	 TOP 1 @CREATION_DATE_TIME1 = [CREATION_DATE_TIME]
	
FROM
	[IMPORT_IMAGE] 
WHERE
	[CHART_ID] = @CHART_ID

	IF @CREATION_DATE_TIME1 IS NOT NULL
		BEGIN
			SELECT TOP 1 @CREATION_DATE_TIME2 = [CREATION_DATE_TIME]
			FROM 
				[CHART_PENDING_REASON_HISTORY]
			WHERE
				[CHART_ID] = @CHART_ID
			ORDER BY [CREATION_DATE_TIME] DESC

			IF @CREATION_DATE_TIME2 IS NOT NULL
				BEGIN
					IF @CREATION_DATE_TIME1 > @CREATION_DATE_TIME2
						BEGIN
							SET @RETURN = 1
						END
					ELSE
						BEGIN
							SET @RETURN = 0
						END
				END
			ELSE
				BEGIN
					SET @RETURN = 0
				END
		END
	ELSE
		BEGIN
			SET @RETURN = 0
		END

GO

