CREATE   PROCEDURE [dbo].[DEFINED_RIGHT_QUALIFY_INSERT]
	 @DEFINED_RIGHT_ID int
	,@DEFINED_RIGHT_NAME varchar(50)
	,@DEFINED_RIGHT_DEFINITION varchar(2000) = NULL
	,@DEFINED_RIGHT_CREATING_USER_ID int = 10149 -- 12072 -- William Pippin, 10149 -- Marcus Ferrell
	,@DEFINED_RIGHT_IS_ADMIN bit = 0
	,@DEFINED_RIGHT_ALLOW_INHERITANCE bit = 1
	,@DEFINED_RIGHT_RESULT_ID int OUTPUT
AS

IF @DEFINED_RIGHT_ID <= 0
	BEGIN
		PRINT('@DEFINED_RIGHT_ID is invalid.  No operation performed.')
		RETURN
	END;

IF ISNULL(@DEFINED_RIGHT_NAME, '') = ''
	BEGIN
		PRINT('@DEFINED_RIGHT_NAME is invalid.  No operation performed.')
		RETURN
	END;

IF @DEFINED_RIGHT_DEFINITION IS NULL
	BEGIN
		PRINT('Setting @DEFINED_RIGHT_DEFINITION = @DEFINED_RIGHT_NAME.')
		SET @DEFINED_RIGHT_DEFINITION = @DEFINED_RIGHT_NAME
	END;

DECLARE @FOUND_DEFINED_RIGHT_ID int;

SELECT @FOUND_DEFINED_RIGHT_ID = [DEFINED_RIGHT_ID]
	FROM
		[dbo].[DEFINED_RIGHT] with (NOLOCK)
	WHERE
		([DEFINED_RIGHT_ID] = @DEFINED_RIGHT_ID);

if @FOUND_DEFINED_RIGHT_ID IS NULL
	BEGIN
		INSERT INTO [RevCycleDB].[dbo].[DEFINED_RIGHT]
		(
			  [DEFINED_RIGHT_ID]
			 ,[NAME]
			 ,[CREATION_DATE_TIME]
			 ,[CREATING_USER_PROFILE_ID]
			 ,[CHANGED_DATE_TIME]
			 ,[CHANGING_USER_PROFILE_ID]
			 ,[ALLOW_INHERITANCE]
			 ,[DEFINITION]
			 ,[IS_ADMIN]
		)
		VALUES
		(
			 @DEFINED_RIGHT_ID
			,@DEFINED_RIGHT_NAME
			,GETDATE()
			,@DEFINED_RIGHT_CREATING_USER_ID
			,GETDATE()
			,@DEFINED_RIGHT_CREATING_USER_ID
			,@DEFINED_RIGHT_ALLOW_INHERITANCE
			,@DEFINED_RIGHT_DEFINITION
			,@DEFINED_RIGHT_IS_ADMIN	 
		)
		
		SELECT TOP 1 @DEFINED_RIGHT_RESULT_ID = [DEFINED_RIGHT_ID]   
            FROM 
				[dbo].[DEFINED_RIGHT] with (NOLOCK) 
            WHERE 
				([DEFINED_RIGHT_ID] = @DEFINED_RIGHT_ID)
				AND ([CREATING_USER_PROFILE_ID] = @DEFINED_RIGHT_CREATING_USER_ID)
			ORDER BY 
				[DEFINED_RIGHT_ID] DESC;		
		
	END
ELSE
	BEGIN
		PRINT('@FOUND_DEFINED_RIGHT_ID already exists for @DEFINED_RIGHT_ID = ' + CAST(@DEFINED_RIGHT_ID AS VARCHAR(32)));
		SET @DEFINED_RIGHT_RESULT_ID = @FOUND_DEFINED_RIGHT_ID
	END;

PRINT('@DEFINED_RIGHT_RESULT_ID = ' + CAST(@DEFINED_RIGHT_RESULT_ID AS VARCHAR(32)));

GO
