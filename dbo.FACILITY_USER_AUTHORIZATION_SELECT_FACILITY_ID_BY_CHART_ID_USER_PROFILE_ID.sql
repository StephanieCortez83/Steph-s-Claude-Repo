CREATE PROCEDURE [dbo].[FACILITY_USER_AUTHORIZATION_SELECT_FACILITY_ID_BY_CHART_ID_USER_PROFILE_ID]
	 @CHART_ID int
	,@USER_PROFILE_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		[FACILITY_ID]
    FROM 
		[dbo].[FACILITY_USER_AUTHORIZATION] WITH (NOLOCK)
    WHERE 
		([FACILITY_USER_AUTHORIZATION].[USER_PROFILE_ID] = @USER_PROFILE_ID)
    AND 
		([FACILITY_USER_AUTHORIZATION].[FACILITY_ID] = (SELECT [FACILITY_ID] FROM [dbo].[CHART] WHERE [CHART_ID] = @CHART_ID))

GO
