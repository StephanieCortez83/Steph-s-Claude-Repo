CREATE PROCEDURE [dbo].[CEP_PROJECT_SELECT]
	 @PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CEP_PROJECT_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)
DECLARE @KeyWhereClause nvarchar(1000)

SET @sql = 'INSERT INTO #tmp (CEP_PROJECT_ID) ' +
		   'SELECT [CEP_PROJECT].[CEP_PROJECT_ID] ' +
		   'FROM [CEP_PROJECT] ' 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' WHERE (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CEP_PROJECT].[PROJECT_NAME] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CEP_PROJECT].[CEP_PROJECT_ID]
	,[CEP_PROJECT].[CEP_FACILITY_ID]
	,[CEP_PROJECT].[CEP_ORGANIZATION_ID]
	,[CEP_PROJECT].[CEP_PROJECT_TYPE_CODE]
	,[CEP_PROJECT].[PROJECT_NAME]
	,[CEP_PROJECT].[EFFECTIVE_DATE]
	,[CEP_PROJECT].[EXPIRATION_DATE]
	,[CEP_PROJECT].[CONTRACT_PRODUCTIVITY_REQUIREMENTS]
	,[CEP_PROJECT].[IS_DELETED]
	,[CEP_PROJECT].[CREATION_DATE_TIME]
	,[CEP_PROJECT].[CREATING_USER_PROFILE_ID]
	,[CEP_PROJECT].[CHANGED_DATE_TIME]
	,[CEP_PROJECT].[CHANGING_USER_PROFILE_ID]
FROM
	#tmp [tmp]
	INNER JOIN [CEP_PROJECT] 
			ON [CEP_PROJECT].[CEP_PROJECT_ID] = [tmp].[CEP_PROJECT_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
