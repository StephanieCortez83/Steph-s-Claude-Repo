CREATE PROCEDURE [dbo].[AUDIT_LOG_OBJECT_STATE_SELECT_BY_AUDIT_LOG_OBJECT_STATE_ID]
	@AUDIT_LOG_OBJECT_STATE_ID int
AS

SELECT [AUDIT_LOG_OBJECT_STATE_ID]
      ,[AUDIT_LOG_ID]
      ,[STATE]
      ,[CREATION_DATE_TIME]
FROM 
	[dbo].[AUDIT_LOG_OBJECT_STATE]
