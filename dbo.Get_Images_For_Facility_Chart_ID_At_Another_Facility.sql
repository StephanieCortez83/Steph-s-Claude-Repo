CREATE PROC [dbo].[Get_Images_For_Facility_Chart_ID_At_Another_Facility]

	@FacilityChartID varchar(20),
	@ServiceAgreementID int, 
	@CompanyID int

AS
BEGIN 
SELECT DISTINCT IMPORT_BATCH_ID,
		        MIME_TYPE,
		        CONTENT_SIZE,
		        FILE_SYSTEM_FILE_NAME
FROM IMPORT_IMAGE WITH (NOLOCK)
INNER JOIN SERVICE_AGREEMENT WITH (NOLOCK) ON SERVICE_AGREEMENT.SERVICE_AGREEMENT_ID = IMPORT_IMAGE.SERVICE_AGREEMENT_ID
WHERE CHART_ID > 0
AND SERVICE_AGREEMENT.COMPANY_ID = @CompanyId
AND IMPORT_IMAGE.FACILITY_CHART_ID = @FacilityChartId
AND NOT EXISTS (
				  SELECT *
				  FROM IMPORT_IMAGE i WITH (NOLOCK)
				  WHERE i.SERVICE_AGREEMENT_ID = @ServiceAgreementId
				  AND i.FILE_SYSTEM_FILE_NAME = IMPORT_IMAGE.FILE_SYSTEM_FILE_NAME
              )
END

GO
