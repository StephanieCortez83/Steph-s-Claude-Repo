-- Description:	SQL for the Pending Account Summary report
-- =============================================
CREATE PROCEDURE [dbo].[rpt_PendingAccountSummary] 
AS
BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

  DECLARE @TodayM60 DATE = GETDATE() - 60;

  SELECT CASE 
		  WHEN [RCP_BILLING_IND] = 1
			  THEN 'Billing'
		  WHEN [SERVICE_MODEL_CD] = 'ASP'
			  THEN 'Software as a Service (SaaS)'
		  ELSE 'Full Service'
		  END [SERVICE],
	  CHART.FACILITY_ID,
	  FACILITY.[NAME] FACILITY,
	  CHART.PENDING_REASON_ID,
	  PENDING_REASON.[DESCRIPTION] PENDING_REASON,
    DEFAULT_RANK_VALUE,
	  COUNT(*) TOTAL,
	  (
		  SELECT SUM(TOTAL) / COUNT(*)
		  FROM (
			  SELECT DATEADD(DAY, DATEDIFF(DAY, 0, TIME_OF_SERVICE), 0) DOS,
				  COUNT(*) TOTAL
			  FROM [dbo].[CHART] WITH (NOLOCK)
			  WHERE SERVICE_AGREEMENT_ID = SERVICE_AGREEMENT.SERVICE_AGREEMENT_ID
				  AND DATEDIFF(DAY, @TodayM60, DATEADD(DAY, DATEDIFF(DAY, 0, TIME_OF_SERVICE), 0)) > 0
			  GROUP BY DATEADD(DAY, DATEDIFF(DAY, 0, TIME_OF_SERVICE), 0)
			  ) x
		  ) [AVG_DAILY_VOL],
	  (
		  SELECT TOP 1 'Pending - ' + PENDING_REASON.[DESCRIPTION] + ' to ' + CASE 
				  WHEN CHART_STATUS_ID_TO = 1
					  THEN 'Work in Progress'
				  ELSE 'Pending - ' + pr2.[DESCRIPTION]
				  END + ' ' + CONVERT(VARCHAR, UNITS_OF_TIME) + ' ' + CASE 
				  WHEN DATE_PART = 0
					  THEN 'days'
				  ELSE 'hours'
				  END + ' after the ' + CASE 
				  WHEN DATE_TYPE = 0
					  THEN 'Date of Service'
				  ELSE 'Date of Discharge'
				  END
		  FROM [dbo].[SERVICE_AGREEMENT_CHART_STATUS_CHANGE_CRITERIA] WITH (NOLOCK)
		  INNER JOIN [dbo].[PENDING_REASON] WITH (NOLOCK) ON PENDING_REASON.PENDING_REASON_ID = [SERVICE_AGREEMENT_CHART_STATUS_CHANGE_CRITERIA].[PENDING_REASON_ID_FROM]
		  LEFT JOIN [dbo].[PENDING_REASON] pr2 WITH (NOLOCK) ON pr2.PENDING_REASON_ID = [SERVICE_AGREEMENT_CHART_STATUS_CHANGE_CRITERIA].[PENDING_REASON_ID_TO]
		  WHERE SERVICE_AGREEMENT_ID = SERVICE_AGREEMENT.SERVICE_AGREEMENT_ID
		  ) STATUS_CHANGE_CRITERIA
  FROM CHART
  INNER JOIN [dbo].[FACILITY] WITH (NOLOCK) ON FACILITY.FACILITY_ID = CHART.FACILITY_ID
  INNER JOIN [dbo].[PENDING_REASON] WITH (NOLOCK) ON PENDING_REASON.PENDING_REASON_ID = CHART.PENDING_REASON_ID
  INNER JOIN [dbo].[SERVICE_AGREEMENT] WITH (NOLOCK) ON SERVICE_AGREEMENT.SERVICE_AGREEMENT_ID = CHART.SERVICE_AGREEMENT_ID
  WHERE CHART.CHART_STATUS_ID = 2
	  AND SERVICE_AGREEMENT.EXPIRATION_DATE >= GETDATE()
	  AND DEMO_TEST_SITE_IND = 0
  GROUP BY CASE 
		  WHEN [RCP_BILLING_IND] = 1
			  THEN 'Billing'
		  WHEN [SERVICE_MODEL_CD] = 'ASP'
			  THEN 'Software as a Service (SaaS)'
		  ELSE 'Full Service'
		  END,
	  CHART.FACILITY_ID,
	  SERVICE_AGREEMENT.SERVICE_AGREEMENT_ID,
	  FACILITY.[NAME],
	  CHART.PENDING_REASON_ID,
	  PENDING_REASON.[DESCRIPTION],
    DEFAULT_RANK_VALUE
  ORDER BY [Service],
	  FACILITY,
	  PENDING_REASON
END
GO
GRANT EXECUTE ON  [dbo].[rpt_PendingAccountSummary] TO [dbx_ExecuteReportProcs]
GO
