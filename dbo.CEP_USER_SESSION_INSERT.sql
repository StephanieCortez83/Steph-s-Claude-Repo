CREATE PROCEDURE [dbo].[CEP_USER_SESSION_INSERT]
	 @USER_PROFILE_ID int
	,@SESSION_ID varchar(50)
	,@UU_ID uniqueidentifier = NULL
	,@IS_SIGNED_OUT bit = NULL
	,@LAST_REQUEST_DATE_TIME datetime
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@CEP_USER_SESSION_ID int OUTPUT
AS

INSERT INTO [dbo].[CEP_USER_SESSION]
(
	 [USER_PROFILE_ID]
	,[SESSION_ID]
	,[UU_ID]
	,[IS_SIGNED_OUT]
	,[LAST_REQUEST_DATE_TIME]
	,[CREATING_USER_PROFILE_ID]
	,[CHANGING_USER_PROFILE_ID]
)
VALUES
(
	 @USER_PROFILE_ID
	,@SESSION_ID
	,@UU_ID
	,@IS_SIGNED_OUT
	,@LAST_REQUEST_DATE_TIME
	,@CREATING_USER_PROFILE_ID
	,@CHANGING_USER_PROFILE_ID 
)

SET @CEP_USER_SESSION_ID = @@IDENTITY

GO
