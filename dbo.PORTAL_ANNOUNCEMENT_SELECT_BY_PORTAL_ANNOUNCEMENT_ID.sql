CREATE   PROCEDURE [dbo].[PORTAL_ANNOUNCEMENT_SELECT_BY_PORTAL_ANNOUNCEMENT_ID]
@PORTAL_ANNOUNCEMENT_ID INT
AS
BEGIN
SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT
		PORTAL_ANNOUNCEMENT_ID, 
		MODULE_ID, 
		TITLE,
		MORE_LINK,
		EFFECTIVE_DATE,
		EXPIRE_DATE,
		[DESCRIPTION],
		CREATION_DATE_TIME,
		CREATING_USER_PROFILE_ID,
		CHANGED_DATE_TIME,
		CHANGING_USER_PROFILE_ID
	FROM 
		PORTAL_ANNOUNCEMENT
	WHERE
		PORTAL_ANNOUNCEMENT_ID = @PORTAL_ANNOUNCEMENT_ID
END
GO
