CREATE PROCEDURE [dbo].[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION_SELECT_BY_CHART_ID]
	 @CHART_ID int
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)
DECLARE @KeyWhereClause nvarchar(1000)

SET @sql = 'INSERT INTO #tmp (CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION_ID) ' +
		   'SELECT [CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION_ID] ' +
		   'FROM [CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION] ' +
		   'WHERE [CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CHART_ID] = ' + CAST(@CHART_ID AS VARCHAR(10)) 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CREATION_DATE_TIME] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION_ID]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CHART_ID]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[ACTION]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[ACTION_DESCRIPTION]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[IS_CODER_CORRECT]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[AUDITOR_USER_PROFILE_ID]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[EXCLUDE_FROM_QA_REPORT]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[EXCLUDE_FROM_QA_REPORT_REASON_ID]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CREATION_DATE_TIME]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CREATING_USER_PROFILE_ID]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CHANGED_DATE_TIME]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CHANGING_USER_PROFILE_ID]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CODER_ANESTHESIA_CODE]
	,[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[AUDITOR_ANESTHESIA_CODE]
FROM
	#tmp [tmp]
	INNER JOIN [CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION] 
			ON [CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION].[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION_ID] = [tmp].[CHART_QA_SCORECARD_ANESTHESIA_AUDIT_ACTION_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
