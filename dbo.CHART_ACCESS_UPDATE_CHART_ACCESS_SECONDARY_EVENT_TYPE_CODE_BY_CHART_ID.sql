CREATE PROCEDURE [dbo].[CHART_ACCESS_UPDATE_CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE_BY_CHART_ID]  
	@CHART_ID                       			INT
   ,@CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE		CHAR(1)
AS  
  
SET NOCOUNT ON  
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED  

UPDATE 
	[CHART_ACCESS]
SET 
	[CHART_ACCESS].[CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE] = @CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE
   ,[CHART_ACCESS].[SECONDARY_EVENT_COMPLETION_DATE_TIME] = GETDATE()
WHERE 
	[CHART_ACCESS].[CHART_ID] = @CHART_ID
AND [CHART_ACCESS].[CHART_ACCESS_EVENT_TYPE_CODE] = 'B' 
AND [CHART_ACCESS].[CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE] IS NULL

GO
