USE [RevCycleDB]
GO

CREATE   PROCEDURE [dbo].[PORTAL_ANNOUNCEMENT_UPDATE]
	@PORTAL_ANNOUNCEMENT_ID int
	,@MODULE_ID int
	,@TITLE nvarchar(150)
	,@MORE_LINK nvarchar(150)
	,@EFFECTIVE_DATE datetime
	,@EXPIRE_DATE datetime
	,@DESCRIPTION nvarchar(2000)
	,@CHANGED_DATE_TIME datetime
	,@CHANGING_USER_PROFILE_ID int
AS
BEGIN

UPDATE [dbo].[PORTAL_ANNOUNCEMENT]
   SET [MODULE_ID] = @MODULE_ID
      ,[TITLE] = @TITLE
      ,[MORE_LINK] = @MORE_LINK
	  ,[EFFECTIVE_DATE] = @EFFECTIVE_DATE
      ,[EXPIRE_DATE] = @EXPIRE_DATE
      ,[DESCRIPTION] = @DESCRIPTION
      ,[CHANGED_DATE_TIME] = @CHANGED_DATE_TIME
      ,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
 WHERE
	PORTAL_ANNOUNCEMENT_ID = @PORTAL_ANNOUNCEMENT_ID
END
GO


