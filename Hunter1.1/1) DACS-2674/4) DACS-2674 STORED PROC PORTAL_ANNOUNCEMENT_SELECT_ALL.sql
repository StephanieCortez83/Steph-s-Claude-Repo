USE [RevCycleDB]
GO

CREATE PROCEDURE [dbo].[PORTAL_ANNOUNCEMENT_SELECT_ALL]
AS
BEGIN
SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT
		PORTAL_ANNOUNCEMENT_ID, 
		MODULE_ID, 
		TITLE,
		MORE_LINK,
		EFFECTIVE_DATE,
		EXPIRE_DATE,
		[DESCRIPTION],
		CREATION_DATE_TIME,
		CREATING_USER_PROFILE_ID,
		CHANGED_DATE_TIME,
		CHANGING_USER_PROFILE_ID
	FROM 
		PORTAL_ANNOUNCEMENT
	ORDER BY
		PORTAL_ANNOUNCEMENT_ID DESC
END
GO


