USE [RevCycleDB]
GO

CREATE PROCEDURE dbo.Maintenance_PendingReasonInsert
	@DESCRIPTION VARCHAR(100),
	@DEFAULT_PENDING_REASON_CATEGORY_ID INT,
	@DEFAULT_RANK_VALUE INT,
	@DEFICIENCY_CODE VARCHAR(10),
	@EXTENDED_DESCRIPTION VARCHAR(4000)

AS
	INSERT INTO [dbo].[PENDING_REASON]
           ([DESCRIPTION]
           ,[DEFAULT_PENDING_REASON_CATEGORY_ID]
           ,[DEFAULT_RANK_VALUE]
           ,[DEFICIENCY_CODE]
           ,[EXTENDED_DESCRIPTION])
     VALUES
           (@DESCRIPTION
           ,@DEFAULT_PENDING_REASON_CATEGORY_ID
           ,@DEFAULT_RANK_VALUE
           ,@DEFICIENCY_CODE
           ,@EXTENDED_DESCRIPTION);
GO
