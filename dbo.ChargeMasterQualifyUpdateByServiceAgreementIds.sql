CREATE   PROCEDURE [dbo].[ChargeMasterQualifyUpdateByServiceAgreementIds]
	 @SourceSAId INT
	,@TargetSAId INT
	,@UPId INT
	,@EffectiveDate DATETIME
	,@ExpirationDate DATETIME
	,@InsDate DATETIME = NULL
	,@MaxToProcess INT = 20000
AS
BEGIN
	IF @SourceSAId IS NULL OR @SourceSAId <= 0
	BEGIN
		SELECT Result = -1, Error = 'Error: Source SA Id is invalid.';
		RETURN;
	END;

	IF @TargetSAId IS NULL OR @TargetSAId <= 0
	BEGIN
		SELECT Result = -2, Error = 'Error: Target SA Id is invalid.';
		RETURN;
	END;

	IF @UPId IS NULL OR @UPId <= 0
	BEGIN
		SELECT Result = -3, Error = 'Error: UP Id is invalid.';
		RETURN;
	END;

	IF @InsDate IS NULL
	BEGIN
		SET @InsDate = CONVERT (date, GETDATE());
	END;


	IF @MaxToProcess IS NULL OR @MaxToProcess <= 0
	BEGIN
		SET @MaxToProcess = 1000;
	END;

	IF OBJECT_ID('tempdb..#TempRows') IS NOT NULL
	BEGIN
		DROP TABLE #TempRows
	END;

	-- Fill temp table with our data
	SELECT  TOP (@MaxToProcess)
		 [SERVICE_AGREEMENT_ID]
		,[CHARGE_MASTER_CATEGORY_ID]
		,[DESCRIPTION]
		,[CPT_CODE]
		,[BILLING_CODE]
		,[ICD9_CODE]
		,[MODIFIER_REQUIRED]
		,[CHARGE_MASTER_DEPT_ID]
		,[CHARGE_MASTER_USAGE_CODE]
		,[CHARGE_AMOUNT]
		,[EFFECTIVE_DATE]
		,[EXPIRATION_DATE]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[DISPLAY_SEQ]
		,[LONG_DESCRIPTION]
		,[MAX_QUANTITY]
		,[RVU]
		,[PATIENT_CLASS_ID]
		,[ALIAS_BILLING_CODE]
		,[BYPASS_AUTO_APPROVAL]
		,[OBSERVATION_PATIENT_ARRIVAL_SOURCE_ID]
		,[OBSERVATION_HOUR_TYPE_ID]
		,[OBSERVATION_TELEMETRY]
		,[ALLOW_NEGATIVE_UNITS_IND]
		,[SPECIAL_HANDLING_INSTRUCTIONS]
		,[AGE_MINIMUM]
		,[AGE_MAXIMUM]
	INTO #TempRows
	FROM
		(SELECT 
				 @TargetSAId AS [SERVICE_AGREEMENT_ID]
				,ISNULL((SELECT TOP(1) [CHARGE_MASTER_CATEGORY_ID] FROM [CHARGE_MASTER_CATEGORY] WITH (NOLOCK) WHERE [SERVICE_AGREEMENT_ID]= @TargetSAId AND [COPIED_FROM_CATEGORY_ID] = src.[CHARGE_MASTER_CATEGORY_ID]), -1) AS [CHARGE_MASTER_CATEGORY_ID] 
				,[DESCRIPTION]
				,[CPT_CODE]
				,[BILLING_CODE]
				,[ICD9_CODE]
				,[MODIFIER_REQUIRED]
				,ISNULL((SELECT TOP(1) [CHARGE_MASTER_DEPT_ID] FROM [CHARGE_MASTER_DEPARTMENT] WITH (NOLOCK) WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId AND [COPIED_FROM_DEPT_ID] = src.[CHARGE_MASTER_DEPT_ID]), -1) AS [CHARGE_MASTER_DEPT_ID] 				-- deptDao.GetDepartmentIdForCopiedAgreement(targetSa.ServiceAgreementID, item.DepartmentID);
				,[CHARGE_MASTER_USAGE_CODE]
				,[CHARGE_AMOUNT]
				,@EffectiveDate AS [EFFECTIVE_DATE]
				,@ExpirationDate AS [EXPIRATION_DATE]
				,@InsDate AS [CREATION_DATE_TIME]
				,@UPId AS [CREATING_USER_PROFILE_ID]
				,@InsDate AS [CHANGED_DATE_TIME]
				,@UPId AS [CHANGING_USER_PROFILE_ID]
				,[DISPLAY_SEQ]
				,[LONG_DESCRIPTION]
				,[MAX_QUANTITY]
				,[RVU]
				,ISNULL((SELECT TOP(1) [PATIENT_CLASS_ID] FROM [PATIENT_CLASS] WITH (NOLOCK) WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId AND [COPIED_FROM_PATIENT_CLASS_ID] = src.[PATIENT_CLASS_ID]), -1) AS [PATIENT_CLASS_ID] 					-- pcDao.GetPatientClassIdForCopiedAgreement(targetSa.ServiceAgreementID,item.PatientClassID);
				,[ALIAS_BILLING_CODE]
				,[BYPASS_AUTO_APPROVAL]
				,-1 AS [OBSERVATION_PATIENT_ARRIVAL_SOURCE_ID]
				,-1 AS [OBSERVATION_HOUR_TYPE_ID]
				,0 AS [OBSERVATION_TELEMETRY]
				,[ALLOW_NEGATIVE_UNITS_IND]
				,[SPECIAL_HANDLING_INSTRUCTIONS]
				,[AGE_MINIMUM]
				,[AGE_MAXIMUM]
		FROM
			[RevCycleDB].[dbo].[CHARGE_MASTER] src WITH (NOLOCK)
		WHERE 
			[SERVICE_AGREEMENT_ID] = @SourceSAId
			AND ([EFFECTIVE_DATE] <= GetDate())
			AND ([EXPIRATION_DATE] IS NULL OR ([EXPIRATION_DATE] >= GetDate()))
			-- The following must match to be counted as a row to skip
			AND (	  LOWER(RTRIM([CPT_CODE])) + ',' 
					+ LOWER(RTRIM([BILLING_CODE])) + ','
					+ LOWER(RTRIM([DESCRIPTION])) + ','
					+ CAST([CHARGE_MASTER_USAGE_CODE] AS varchar(20))
				) 
				NOT IN 
				(
					SELECT DISTINCT (     LOWER(RTRIM([CPT_CODE])) + ',' 
										+ LOWER(RTRIM([BILLING_CODE])) + ','
										+ LOWER(RTRIM([DESCRIPTION])) + ','
										+ CAST([CHARGE_MASTER_USAGE_CODE] AS varchar(20)) 
						) 
						FROM [RevCycleDB].[dbo].[CHARGE_MASTER] WITH (NOLOCK)
						WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId
						AND ([EFFECTIVE_DATE] <= GetDate())
						AND ([EXPIRATION_DATE] IS NULL OR ([EXPIRATION_DATE] >= GetDate()))
				)
			
		) AS sourceList

	DECLARE @tempTableRowCount INT = (SELECT COUNT(*) FROM #TempRows);
	print('temp table count Org: ' + CAST(@tempTableRowCount AS VARCHAR(20)));

	IF @tempTableRowCount <= 0
	BEGIN
		SELECT Result = 0, Error = 'No new data rows to insert';
		RETURN;
	END;

	DECLARE @preProcessingCount INT = (SELECT COUNT([CHARGE_MASTER_ID]) FROM [RevCycleDB].[dbo].[CHARGE_MASTER] WITH (NOLOCK) WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId)

	-- Perform insert action here
	BEGIN TRANSACTION
	BEGIN TRY

		INSERT INTO [RevCycleDB].[dbo].[CHARGE_MASTER]
			(
			 [SERVICE_AGREEMENT_ID]
			,[CHARGE_MASTER_CATEGORY_ID]
			,[DESCRIPTION]
			,[CPT_CODE]
			,[BILLING_CODE]
			,[ICD9_CODE]
			,[MODIFIER_REQUIRED]
			,[CHARGE_MASTER_DEPT_ID]
			,[CHARGE_MASTER_USAGE_CODE]
			,[CHARGE_AMOUNT]
			,[EFFECTIVE_DATE]
			,[EXPIRATION_DATE]
			,[CREATION_DATE_TIME]
			,[CREATING_USER_PROFILE_ID]
			,[CHANGED_DATE_TIME]
			,[CHANGING_USER_PROFILE_ID]
			,[DISPLAY_SEQ]
			,[LONG_DESCRIPTION]
			,[MAX_QUANTITY]
			,[RVU]
			,[PATIENT_CLASS_ID]
			,[ALIAS_BILLING_CODE]
			,[BYPASS_AUTO_APPROVAL]
			,[OBSERVATION_PATIENT_ARRIVAL_SOURCE_ID]
			,[OBSERVATION_HOUR_TYPE_ID]
			,[OBSERVATION_TELEMETRY]
			,[ALLOW_NEGATIVE_UNITS_IND]
			,[SPECIAL_HANDLING_INSTRUCTIONS]
			,[AGE_MINIMUM]
			,[AGE_MAXIMUM]
			)
			SELECT TOP (@MaxToProcess)
				 #TempRows.[SERVICE_AGREEMENT_ID]
				,#TempRows.[CHARGE_MASTER_CATEGORY_ID]
				,#TempRows.[DESCRIPTION]
				,#TempRows.[CPT_CODE]
				,#TempRows.[BILLING_CODE]
				,#TempRows.[ICD9_CODE]
				,#TempRows.[MODIFIER_REQUIRED]
				,#TempRows.[CHARGE_MASTER_DEPT_ID]
				,#TempRows.[CHARGE_MASTER_USAGE_CODE]
				,#TempRows.[CHARGE_AMOUNT]
				,#TempRows.[EFFECTIVE_DATE]
				,#TempRows.[EXPIRATION_DATE]
				,#TempRows.[CREATION_DATE_TIME]
				,#TempRows.[CREATING_USER_PROFILE_ID]
				,#TempRows.[CHANGED_DATE_TIME]
				,#TempRows.[CHANGING_USER_PROFILE_ID]
				,#TempRows.[DISPLAY_SEQ]
				,#TempRows.[LONG_DESCRIPTION]
				,#TempRows.[MAX_QUANTITY]
				,#TempRows.[RVU]
				,#TempRows.[PATIENT_CLASS_ID]
				,#TempRows.[ALIAS_BILLING_CODE]
				,#TempRows.[BYPASS_AUTO_APPROVAL]
				,#TempRows.[OBSERVATION_PATIENT_ARRIVAL_SOURCE_ID]
				,#TempRows.[OBSERVATION_HOUR_TYPE_ID]
				,#TempRows.[OBSERVATION_TELEMETRY]
				,#TempRows.[ALLOW_NEGATIVE_UNITS_IND]
				,#TempRows.[SPECIAL_HANDLING_INSTRUCTIONS]
				,#TempRows.[AGE_MINIMUM]
				,#TempRows.[AGE_MAXIMUM]
			From #TempRows;

		COMMIT TRANSACTION;

	END TRY
	BEGIN CATCH
		SELECT Result = -4, 
			Error = 'Error: Exception occurred.  Rollback Processed. Error = ' 
				+ CAST(ERROR_NUMBER() AS VARCHAR(30)) 
				+ ' :: ' + CAST(ERROR_MESSAGE() AS VARCHAR(4000));
		ROLLBACK TRANSACTION;
	END CATCH;

	DECLARE @CMRowCountNew INT = (SELECT COUNT(*) FROM CHARGE_MASTER WITH (NOLOCK) WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId AND ([EFFECTIVE_DATE] <= GETDATE() AND ([EXPIRATION_DATE] IS NULL OR [EXPIRATION_DATE] >= GETDATE()) ));
	print('CM table count after New: ' + CAST(@CMRowCountNew AS VARCHAR(20)));

	-- delete duplicate rows
	WITH CTE AS
	(
	SELECT 	  [SERVICE_AGREEMENT_ID]
			, [CPT_CODE]
			, [BILLING_CODE]
			, [DESCRIPTION]
			, [CHARGE_MASTER_CATEGORY_ID]
			, [CHARGE_MASTER_DEPT_ID]
			, [PATIENT_CLASS_ID]
			, ROW_NUMBER() 
		OVER (
			PARTITION BY [SERVICE_AGREEMENT_ID], [CPT_CODE], [BILLING_CODE], [DESCRIPTION], [CHARGE_MASTER_CATEGORY_ID], [CHARGE_MASTER_DEPT_ID], [PATIENT_CLASS_ID] 
			ORDER BY [SERVICE_AGREEMENT_ID], [CPT_CODE], [BILLING_CODE], [DESCRIPTION], [CHARGE_MASTER_CATEGORY_ID], [CHARGE_MASTER_DEPT_ID], [PATIENT_CLASS_ID]) AS RN
		FROM CHARGE_MASTER WITH (NOLOCK)
		WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId AND ([EFFECTIVE_DATE] <= GETDATE() AND ([EXPIRATION_DATE] IS NULL OR [EXPIRATION_DATE] >= GETDATE()) )
	)

	DELETE FROM CTE WHERE RN<>1

	DECLARE @CMRowCountDup INT = (SELECT COUNT(*) FROM CHARGE_MASTER WITH (NOLOCK) WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId AND ([EFFECTIVE_DATE] <= GETDATE() AND ([EXPIRATION_DATE] IS NULL OR [EXPIRATION_DATE] >= GETDATE()) ) );
	print('CM table count after Dup: ' + CAST(@CMRowCountDup AS VARCHAR(20)));

	DECLARE @resultCount INT = (SELECT COUNT([CHARGE_MASTER_ID]) FROM [RevCycleDB].[dbo].[CHARGE_MASTER] WITH (NOLOCK) WHERE [SERVICE_AGREEMENT_ID] = @TargetSAId)

	SELECT Result = @tempTableRowCount, Error = 'Total Rows = ' + CAST(@resultCount AS VARCHAR(20)) 
						+ ' :: Insert count = ' + CAST((@resultCount - @preProcessingCount) AS VARCHAR(20));

END -- end of stored procedure

GO
