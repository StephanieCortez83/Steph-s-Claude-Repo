CREATE PROCEDURE [dbo].[CHART_INFUSION_AUTOMATION_UPDATE_BY_CHART_INFUSION_AUTOMATION_ID]
	 @CHART_INFUSION_AUTOMATION_ID int
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@CHART_INFUSION_ID int
	,@CHART_ID int
	,@IV_SITE int = NULL
	,@SUBSTANCE_NUMBER int = NULL
	,@INFUSION_TYPE int = NULL
	,@START_DATE datetime = NULL
	,@STOP_DATE datetime = NULL
	,@INITIALS varchar(20) = NULL
	,@NO_STOP_TIME bit = NULL
	,@UNITS int = NULL
	,@CHARGE_MASTER_DEPT_ID int = NULL
	,@GENERIC_SUBSTANCE_NAME varchar(20) = NULL
	,@ICD_10_PCS_CODE varchar(7) = NULL
AS

UPDATE [dbo].[CHART_INFUSION_AUTOMATION] SET
	 [CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
	,[CHART_INFUSION_ID] = @CHART_INFUSION_ID
	,[CHART_ID] = @CHART_ID
