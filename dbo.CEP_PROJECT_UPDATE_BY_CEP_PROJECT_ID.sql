CREATE PROCEDURE [dbo].[CEP_PROJECT_UPDATE_BY_CEP_PROJECT_ID]
	 @CEP_PROJECT_ID int
	,@CEP_FACILITY_ID int
	,@CEP_ORGANIZATION_ID int
	,@CEP_PROJECT_TYPE_CODE int
	,@PROJECT_NAME varchar(50)
	,@EFFECTIVE_DATE datetime
	,@EXPIRATION_DATE datetime = NULL
	,@CONTRACT_PRODUCTIVITY_REQUIREMENTS varchar(250) = NULL
	,@IS_DELETED bit
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
AS

UPDATE [dbo].[CEP_PROJECT] SET
	 [CEP_FACILITY_ID] = @CEP_FACILITY_ID
	,[CEP_ORGANIZATION_ID] = @CEP_ORGANIZATION_ID
	,[CEP_PROJECT_TYPE_CODE] = @CEP_PROJECT_TYPE_CODE
	,[PROJECT_NAME] = @PROJECT_NAME
	,[EFFECTIVE_DATE] = @EFFECTIVE_DATE
	,[EXPIRATION_DATE] = @EXPIRATION_DATE
	,[CONTRACT_PRODUCTIVITY_REQUIREMENTS] = @CONTRACT_PRODUCTIVITY_REQUIREMENTS
	,[IS_DELETED] = @IS_DELETED
	,[CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
WHERE
	[CEP_PROJECT_ID] = @CEP_PROJECT_ID
GO
