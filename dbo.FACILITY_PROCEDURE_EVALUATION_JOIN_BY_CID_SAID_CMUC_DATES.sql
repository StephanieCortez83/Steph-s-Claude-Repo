CREATE PROCEDURE [dbo].[FACILITY_PROCEDURE_EVALUATION_JOIN_BY_CID_SAID_CMUC_DATES]
	 @CHART_ID int
	,@SERVICE_AGREEMENT_ID int
	,@CHARGE_MASTER_USAGE_CODE int
	,@SORT_ORDER varchar(20)
	,@EFFECTIVE_DATE DATETIME = '2099-12-31'  -- Default date fields are seemingly reversed due to this procedure wanting to find an inclusive date range
	,@EXPIRATION_DATE DATETIME = '1900-01-01'
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

IF @SORT_ORDER = 'DESC'
BEGIN

	SELECT  
		 CM.CHARGE_MASTER_ID
		,CM.CHARGE_MASTER_CATEGORY_ID
		,CM.DESCRIPTION
		,CM.LONG_DESCRIPTION
		,CM.CPT_CODE
		,CM.BILLING_CODE
		,CM.MODIFIER_REQUIRED
		,FPE.ICD9_CODE
		,FPE.ICD_10_CODE
		,CMC.DESCRIPTION
		,FPE.QUANTITY
		,FPE.MODIFIERS
		,FPE.ANESTHESIA_TYPE_ID
		,FPE.PROCEDURE_DATE
		,FPE.TRANSACTION_ID
		,FPE.PHYSICIAN_ID
		,FPE.INSUFFICIENT_DOCUMENTATION_TO_BILL
		,FPE.ADD_TO_PHYSICIAN_PROCEDURE
		,CM.MAX_QUANTITY
		,CM.ALLOW_NEGATIVE_UNITS_IND
		,FPE.ICD_10_PCS_CODE
		,CM.CHARGE_MASTER_DEPT_ID  
		,CASE 
			(select count(*) 
				from CODER_QA_REPORT_EXCLUSION ex 
				where (ex.SOURCE_RECORD_TABLE_NAME = 'FACILITY_PROCEDURE_EVALUATION')  
					AND (key_value_1 = FPE.CHART_ID) 
					AND (key_value_2 =  CAST(FPE.FACILITY_PROCEDURE_ID as varchar(15)))) 
			WHEN 0 THEN 0  
			ELSE 1  
			END  as EXCLUDE_FROM_CODER_QA_REPORT 
		,CAST
			((SELECT COUNT(*) FROM [ICD_10_PCS_CPT_XREF] WHERE CPT_CODE COLLATE Latin1_General_CI_AI = CM.CPT_CODE) AS BIT) 
				COLLECT_ICD10_PCS_IND ,CAST(0 AS BIT) MODIFIERS_AVAILABLE 
	FROM 
		CHARGE_MASTER CM WITH (NOLOCK) 
		LEFT OUTER JOIN FACILITY_PROCEDURE_EVALUATION FPE WITH (NOLOCK) ON CM.CHARGE_MASTER_ID = FPE.FACILITY_PROCEDURE_ID
		INNER JOIN CHARGE_MASTER_DEPARTMENT cmd WITH (NOLOCK) ON CM.CHARGE_MASTER_DEPT_ID = cmd.CHARGE_MASTER_DEPT_ID  
			AND ((CHART_ID = @CHART_ID) OR (CHART_ID = null))
		,CHARGE_MASTER_CATEGORY CMC WITH (NOLOCK)  
	WHERE  
		(CM.CHARGE_MASTER_CATEGORY_ID = CMC.CHARGE_MASTER_CATEGORY_ID) 
		AND (CM.CHARGE_MASTER_USAGE_CODE=@CHARGE_MASTER_USAGE_CODE) 
		AND (FPE.QUANTITY <> 0)  
		AND (CM.EFFECTIVE_DATE <= @EFFECTIVE_DATE) 
		AND (CM.EXPIRATION_DATE >= @EXPIRATION_DATE) 
		AND (CM.SERVICE_AGREEMENT_ID = @SERVICE_AGREEMENT_ID)				
			
	ORDER BY 
		CMC.DESCRIPTION
		,CM.DISPLAY_SEQ
		,CM.CPT_CODE DESC

END
ELSE
BEGIN

	SELECT  
		 CM.CHARGE_MASTER_ID
		,CM.CHARGE_MASTER_CATEGORY_ID
		,CM.DESCRIPTION
		,CM.LONG_DESCRIPTION
		,CM.CPT_CODE
		,CM.BILLING_CODE
		,CM.MODIFIER_REQUIRED
		,FPE.ICD9_CODE
		,FPE.ICD_10_CODE
		,CMC.DESCRIPTION
		,FPE.QUANTITY
		,FPE.MODIFIERS
		,FPE.ANESTHESIA_TYPE_ID
		,FPE.PROCEDURE_DATE
		,FPE.TRANSACTION_ID
		,FPE.PHYSICIAN_ID
		,FPE.INSUFFICIENT_DOCUMENTATION_TO_BILL
		,FPE.ADD_TO_PHYSICIAN_PROCEDURE
		,CM.MAX_QUANTITY
		,CM.ALLOW_NEGATIVE_UNITS_IND
		,FPE.ICD_10_PCS_CODE
		,CM.CHARGE_MASTER_DEPT_ID  
		,CASE 
			(select count(*) 
				from CODER_QA_REPORT_EXCLUSION ex 
				where (ex.SOURCE_RECORD_TABLE_NAME = 'FACILITY_PROCEDURE_EVALUATION')  
					AND (key_value_1 = FPE.CHART_ID) 
					AND (key_value_2 =  CAST(FPE.FACILITY_PROCEDURE_ID as varchar(15)))) 
			WHEN 0 THEN 0  
			ELSE 1  
			END  as EXCLUDE_FROM_CODER_QA_REPORT 
		,CAST
			((SELECT COUNT(*) FROM [ICD_10_PCS_CPT_XREF] WHERE CPT_CODE COLLATE Latin1_General_CI_AI = CM.CPT_CODE) AS BIT) 
				COLLECT_ICD10_PCS_IND 
		,CAST(0 AS BIT) MODIFIERS_AVAILABLE 
	FROM 
		CHARGE_MASTER CM WITH (NOLOCK) 
		LEFT OUTER JOIN FACILITY_PROCEDURE_EVALUATION FPE WITH (NOLOCK) ON CM.CHARGE_MASTER_ID = FPE.FACILITY_PROCEDURE_ID
		INNER JOIN CHARGE_MASTER_DEPARTMENT cmd WITH (NOLOCK) ON CM.CHARGE_MASTER_DEPT_ID = cmd.CHARGE_MASTER_DEPT_ID  
			AND ((CHART_ID = @CHART_ID) OR (CHART_ID = null))
		, CHARGE_MASTER_CATEGORY CMC WITH (NOLOCK)  
	WHERE  
		(CM.CHARGE_MASTER_CATEGORY_ID = CMC.CHARGE_MASTER_CATEGORY_ID) 
		AND (CM.CHARGE_MASTER_USAGE_CODE=@CHARGE_MASTER_USAGE_CODE) 
		AND (FPE.QUANTITY <> 0)  
		AND (CM.EFFECTIVE_DATE <= @EFFECTIVE_DATE) 
		AND (CM.EXPIRATION_DATE >= @EXPIRATION_DATE) 
		AND (CM.SERVICE_AGREEMENT_ID = @SERVICE_AGREEMENT_ID)				
			
	ORDER BY 
		CMC.DESCRIPTION
		,CM.DISPLAY_SEQ
		,CM.CPT_CODE

END;
	
GO
