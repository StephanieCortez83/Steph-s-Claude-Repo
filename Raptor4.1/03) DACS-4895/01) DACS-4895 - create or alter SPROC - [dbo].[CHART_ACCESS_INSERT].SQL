USE [RevCycleDB]
GO

SET ANSI_NULLS ON
GO

SET QUOTED_IDENTIFIER ON
GO

CREATE OR ALTER PROCEDURE [dbo].[CHART_ACCESS_INSERT]
    @USER_PROFILE_ID                        INT 
   ,@CHART_ID                               INT
   ,@ACCESS_DATE_TIME                       DATETIME
   ,@CHART_ACCESS_EVENT_TYPE_CODE           VARCHAR(1)    = NULL
   ,@EVENT_COMPLETION_DATE_TIME             DATETIME      = NULL
   ,@CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE VARCHAR(1)    = NULL
   ,@SECONDARY_EVENT_COMPLETION_DATE_TIME   DATETIME      = NULL
   ,@LogNoteCategoryId						INT			  = 0
   ,@LogNoteSummary							VARCHAR(256)  = NULL
   ,@LogNoteDetail							VARCHAR(4000) = NULL
AS
BEGIN
	SET NOCOUNT ON
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	INSERT INTO [CHART_ACCESS]
	(
		[USER_PROFILE_ID]
	   ,[CHART_ID]
	   ,[ACCESS_DATE_TIME]
	   ,[CHART_ACCESS_EVENT_TYPE_CODE]
	   ,[EVENT_COMPLETION_DATE_TIME]
	   ,[CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE]
	   ,[SECONDARY_EVENT_COMPLETION_DATE_TIME]    
	)
	VALUES
	(
		@USER_PROFILE_ID
	   ,@CHART_ID
	   ,@ACCESS_DATE_TIME
	   ,@CHART_ACCESS_EVENT_TYPE_CODE
	   ,@EVENT_COMPLETION_DATE_TIME
	   ,@CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE
	   ,@SECONDARY_EVENT_COMPLETION_DATE_TIME 
	);

	IF @LogNoteCategoryId IS NULL OR @LogNoteCategoryId <= 0
		RETURN;
		
	DECLARE @dos DATETIME = GETDATE();
		
	INSERT INTO [LOG_NOTE]
	(
		 [CHART_ID]
		,[COMPLETION_DATE]
		,[COMPLETED_BY_USER_ID]
		,[SUMMARY]
		,[DETAIL]
		,[CATEGORY_ID]
		,[SYSTEM_DEFINED]
		,[CHART_ADJUSTMENT_ID]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
	)
	VALUES
	(
		 @CHART_ID
		,@dos
		,@USER_PROFILE_ID
		,@LogNoteSummary
		,@LogNoteDetail
		,@LogNoteCategoryId
		,1
		,-1
		,@dos
		,@USER_PROFILE_ID
		,@dos
		,@USER_PROFILE_ID
	);
END
GO

DECLARE @exp VARCHAR(50) = (SELECT CAST(modify_date AS VARCHAR(50)) FROM sys.objects WHERE type = 'P' AND name = 'CHART_ACCESS_INSERT');

IF OBJECT_ID('dbo.CHART_ACCESS_INSERT', 'P') IS NOT NULL
	PRINT ('SPROC CHART_ACCESS_INSERT last changed ' + @exp);
ELSE
	PRINT ('failed to create SPROC CHART_ACCESS_INSERT');
GO

