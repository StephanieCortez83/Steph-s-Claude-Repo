CREATE   PROC [dbo].[Maintenance_SelectUserProfileWithActiveAndSsoExtIdentIsNull]  
AS  
	SET NOCOUNT ON
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT top 1000 
		--*
		  [USER_PROFILE_ID]
		, [SIGN_ON_ID]
		, [FIRST_NAME]
		, [LAST_NAME]
		, [EMAIL_ADDRESS]
	FROM 
		[USER_PROFILE]
	WHERE 
		[IS_ACTIVE] = 'Y'
		AND [SSO_EXTERNAL_IDENTIFIER] IS NULL;

GO
