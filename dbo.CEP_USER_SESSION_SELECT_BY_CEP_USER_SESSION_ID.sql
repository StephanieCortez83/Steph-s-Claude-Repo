CREATE PROCEDURE [dbo].[CEP_USER_SESSION_SELECT_BY_CEP_USER_SESSION_ID]
	@CEP_USER_SESSION_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [CEP_USER_SESSION].[CEP_USER_SESSION_ID]
	,[CEP_USER_SESSION].[USER_PROFILE_ID]
	,[CEP_USER_SESSION].[SESSION_ID]
	,[CEP_USER_SESSION].[UU_ID]
	,[CEP_USER_SESSION].[IS_SIGNED_OUT]
	,[CEP_USER_SESSION].[SESSION_START_DATE_TIME]
	,[CEP_USER_SESSION].[LAST_REQUEST_DATE_TIME]
	,[CEP_USER_SESSION].[CREATION_DATE_TIME]
	,[CEP_USER_SESSION].[CREATING_USER_PROFILE_ID]
	,[CEP_USER_SESSION].[CHANGED_DATE_TIME]
	,[CEP_USER_SESSION].[CHANGING_USER_PROFILE_ID]
FROM
	[dbo].[CEP_USER_SESSION]
WHERE
	[CEP_USER_SESSION].[CEP_USER_SESSION_ID] = @CEP_USER_SESSION_ID

GO
