CREATE   PROCEDURE [dbo].[SelectChargeMasterDepartmentForActiveObservationDepartmentsByServiceAgreementIdsAndDateOfService]
(
	@ServiceAgreementsCsv VARCHAR(MAX),
	@DateOfService DATE
)
AS
BEGIN
	SET NOCOUNT ON
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

	DECLARE @ServiceAgreementsIds TABLE (Id INT);

	INSERT INTO @ServiceAgreementsIds
	EXEC CsvToTableOfNumbers 
		@Csv = @ServiceAgreementsCsv,
		@Separator = ',';

	WITH FacilityTempTable AS 
	(
		SELECT 
			  SA.SERVICE_AGREEMENT_ID
			 ,SA.FACILITY_ID
			 ,FC.NAME AS FACILITY_NAME
		  FROM 
			   SERVICE_AGREEMENT SA
		       INNER JOIN FACILITY FC 
				  	   ON FC.FACILITY_ID = SA.FACILITY_ID
		WHERE 
			EXISTS
			(
				SELECT 1 
				  FROM @ServiceAgreementsIds SS 
				 WHERE SS.Id = SA.SERVICE_AGREEMENT_ID
			)
	)
	SELECT 
		 CHARGE_MASTER_DEPT_ID
		,CMD.SERVICE_AGREEMENT_ID
		,NAME
		,FACILITY_DEPARTMENT_CODE
		,FACILITY_DEPARTMENT_ALT
		,ACTIVE
		,CREATION_DATE_TIME
		,CREATING_USER_PROFILE_ID
		,CHANGED_DATE_TIME
		,CHANGING_USER_PROFILE_ID
		,CALCULATE_APC_RATES_IND
		,DEFAULT_IND
		,OBSERVATION_IND
		,OBSERVATION_CODER_ASSIGNMENT_CODE
		,EFFECTIVE_DATE
		,EXPIRATION_DATE
		,CHARGE_MASTER_DEPARTMENT_CLASS_ID
		,FACILITY_CAMPUS_CODE
		,COPIED_FROM_DEPT_ID 
		,TMP.FACILITY_ID
		,TMP.FACILITY_NAME
   FROM 
		CHARGE_MASTER_DEPARTMENT CMD
		INNER JOIN FacilityTempTable TMP
			    ON TMP.SERVICE_AGREEMENT_ID = CMD.SERVICE_AGREEMENT_ID
  WHERE
		ACTIVE = 1 
	AND OBSERVATION_IND = 1 
	AND (@DateOfService BETWEEN COALESCE(EFFECTIVE_DATE, '2000-01-01') and COALESCE(EXPIRATION_DATE, '9999-12-31'))
END;
GO
