CREATE OR ALTER PROCEDURE [dbo].[SelectUserProfileListBySsoExternalIdentifier]
    @SsoExternalIdentifier  VARCHAR(50)
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
    [USER_PROFILE].[USER_PROFILE_ID]
   ,[USER_PROFILE].[USER_GROUP_ID]
   ,[USER_PROFILE].[SIGN_ON_ID]
   ,[USER_PROFILE].[PASSWORD]
   ,[USER_PROFILE].[PASSWORD_LAST_CHANGED_DATE]
   ,[USER_PROFILE].[IS_ACTIVE]
   ,[USER_PROFILE].[FIRST_NAME]
   ,[USER_PROFILE].[MIDDLE_NAME]
   ,[USER_PROFILE].[LAST_NAME]
   ,[USER_PROFILE].[TITLE]
   ,[USER_PROFILE].[NAME_SUFFIX]
   ,[USER_PROFILE].[ADDR_LINE_1]
   ,[USER_PROFILE].[ADDR_LINE_2]
   ,[USER_PROFILE].[CITY]
   ,[USER_PROFILE].[STATE]
   ,[USER_PROFILE].[POSTAL_CODE]
   ,[USER_PROFILE].[PHONE_AREA_CODE]
   ,[USER_PROFILE].[PHONE_NUMBER]
   ,[USER_PROFILE].[PHONE_EXT]
   ,[USER_PROFILE].[FAX_AREA_CODE]
   ,[USER_PROFILE].[FAX_NUMBER]
   ,[USER_PROFILE].[EMAIL_ADDRESS]
   ,[USER_PROFILE].[USER_EXPERIENCE_LEVEL]
   ,[USER_PROFILE].[USER_CLASS_CD]
   ,[USER_PROFILE].[DEFAULT_FACILITY_USER]
   ,[USER_PROFILE].[CREATION_DATE_TIME]
   ,[USER_PROFILE].[CREATING_USER_PROFILE_ID]
   ,[USER_PROFILE].[CHANGED_DATE_TIME]
   ,[USER_PROFILE].[CHANGING_USER_PROFILE_ID]
   ,[USER_PROFILE].[FORCE_PASSWORD_CHANGE]
   ,[USER_PROFILE].[SECURITY_QUESTION_1_ID]
   ,[USER_PROFILE].[SECURITY_QUESTION_1_ANSWER]
   ,[USER_PROFILE].[SECURITY_QUESTION_2_ID]
   ,[USER_PROFILE].[SECURITY_QUESTION_2_ANSWER]
   ,[USER_PROFILE].[INACTIVATED_BY_USER_PROFILE_ID]
   ,[USER_PROFILE].[INACTIVATED_DATE_TIME]
   ,[USER_PROFILE].[ALTERNATE_EMAIL_ADDRESS]
   ,[USER_PROFILE].[QA_REPORT_RECIPIENT]
   ,[USER_PROFILE].[SEND_QA_REPORT_TO_CODER_AND_QA_REPORT_RECIPIENT]
   ,[USER_PROFILE].[LAST_REVIEWED_QA_FEEDBACK]
   ,[USER_PROFILE].[PASSWORD_SALT]
   ,[USER_PROFILE].[MANAGER_USER_PROFILE_ID]
   ,[USER_PROFILE].[SUPERVISOR_USER_PROFILE_ID]
   ,[USER_PROFILE].[SECONDARY_SUPERVISOR_USER_PROFILE_ID]
   ,[USER_PROFILE].[USER_PROFILE_DEACTIVATION_REASON_ID]
   ,[USER_PROFILE].[USER_PROFILE_DEACTIVATION_OTHER_REASON]
   ,[USER_PROFILE].[EMPLOYEE_ID]
   ,[USER_PROFILE].[SSO_COMPANY_ID]
   ,[USER_PROFILE].[SSO_EXTERNAL_IDENTIFIER]
   ,[USER_PROFILE].[IP_ADDRESS_WHITELIST_ID]
FROM 
    [USER_PROFILE]                              
WHERE 
    [USER_PROFILE].[SSO_EXTERNAL_IDENTIFIER] = @SsoExternalIdentifier

GO

