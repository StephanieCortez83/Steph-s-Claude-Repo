CREATE PROCEDURE [dbo].[AUDIT_LOG_SELECT_BY_AUDIT_LOG_ID]
	@AUDIT_LOG_ID int
AS

SELECT [AUDIT_LOG_ID]
      ,[OBJECT_TYPE]
      ,[OBJECT_ID]
	  ,[EVENT_NAME]
      ,[COMMENT]
      ,[CHANGING_USER_PROFILE_ID]
      ,[CHANGING_SIGN_ON_ID]
      ,[CHANGING_EMAIL_ADDRESS]
      ,[CHANGING_FIRST_NAME]
      ,[CHANGING_LAST_NAME]      
      ,[CREATION_DATE_TIME]
FROM 
	[dbo].[AUDIT_LOG]
WHERE
	[AUDIT_LOG_ID] = @AUDIT_LOG_ID
GO
