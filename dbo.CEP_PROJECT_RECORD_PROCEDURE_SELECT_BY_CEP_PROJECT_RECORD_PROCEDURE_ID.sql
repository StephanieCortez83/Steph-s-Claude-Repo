	 [CEP_PROJECT_RECORD_PROCEDURE].[CEP_PROJECT_RECORD_PROCEDURE_ID]
	,[CEP_PROJECT_RECORD_PROCEDURE].[CEP_PROJECT_RECORD_ID]
