CREATE   PROCEDURE [dbo].[MAINTENANCE_CLONE_FACILITY_USER_AUTHORIZATION]
	@SOURCE_FACILITY_ID INT,
	@DESTINATION_FACILITY_ID INT
AS
	----------------------------------------                                                               
	-- Step 1)  Get the needed variables in order to perform the task
	----------------------------------------

	DECLARE	@CREATING_USER_ID int =						10149; -- Marcus Ferrell
	DECLARE @CURRENT_DATE AS DATETIME =					GETDATE()

	SELECT
		[FACILITY_ID], [USER_PROFILE_ID] INTO  #TempDestinationFacilityAuthorizedUsers	
	FROM
		[FACILITY_USER_AUTHORIZATION]
	WHERE
		[FACILITY_ID] = @DESTINATION_FACILITY_ID

	BEGIN TRANSACTION  
	BEGIN TRY  

	INSERT INTO [FACILITY_USER_AUTHORIZATION]
	(
		[FACILITY_ID]
		,[USER_PROFILE_ID]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[EFFECTIVE_DATE]
		,[EXPIRATION_DATE]
		,[CAN_APPROVE_CHARTS]
		,[AUDIT_APPROVAL_RATE]
		,[AUDIT_PROCEDURE_RATE]
		,[AUDIT_INFUSION_RATE]
		,[AUDIT_OBSERVATION_RATE]
		,[CODER_AUTHORIZED_SERVICE_CODE]
		,[SECOND_LEVEL_AUDIT_APPROVAL_RATE]
		,[FORCE_AUDIT]
		,[EMR_ACCESS_EFFECTIVE_DATE]
		,[EMR_ACCESS_EXPIRATION_DATE]
		,[ALLOW_EMR_ACCESS]
		,[EMR_ACCESS_USER_PROFILE_ID]
	)
	SELECT 
		@DESTINATION_FACILITY_ID
		,[USER_PROFILE_ID]
		,@CURRENT_DATE
		,@CREATING_USER_ID
		,@CURRENT_DATE
		,@CREATING_USER_ID
		,[EFFECTIVE_DATE]
		,[EXPIRATION_DATE]
		,[CAN_APPROVE_CHARTS]
		,[AUDIT_APPROVAL_RATE]
		,[AUDIT_PROCEDURE_RATE]
		,[AUDIT_INFUSION_RATE]
		,[AUDIT_OBSERVATION_RATE]
		,[CODER_AUTHORIZED_SERVICE_CODE]
		,[SECOND_LEVEL_AUDIT_APPROVAL_RATE]
		,[FORCE_AUDIT]
		,[EMR_ACCESS_EFFECTIVE_DATE]
		,[EMR_ACCESS_EXPIRATION_DATE]
		,[ALLOW_EMR_ACCESS]
		,[EMR_ACCESS_USER_PROFILE_ID]
	FROM
	(
		SELECT 
			ROW_NUMBER() OVER(PARTITION BY source.[USER_PROFILE_ID] ORDER BY source.[EXPIRATION_DATE] DESC) AS Row#
			,source.[USER_PROFILE_ID]
			,source.[EFFECTIVE_DATE]
			,source.[EXPIRATION_DATE]
			,source.[CAN_APPROVE_CHARTS]
			,source.[AUDIT_APPROVAL_RATE]
			,source.[AUDIT_PROCEDURE_RATE]
			,source.[AUDIT_INFUSION_RATE]
			,source.[AUDIT_OBSERVATION_RATE]
			,source.[CODER_AUTHORIZED_SERVICE_CODE]
			,source.[SECOND_LEVEL_AUDIT_APPROVAL_RATE]
			,source.[FORCE_AUDIT]
			,source.[EMR_ACCESS_EFFECTIVE_DATE]
			,source.[EMR_ACCESS_EXPIRATION_DATE]
			,source.[ALLOW_EMR_ACCESS]
			,source.[EMR_ACCESS_USER_PROFILE_ID]
		FROM 
			[dbo].[FACILITY_USER_AUTHORIZATION] source
		LEFT JOIN
			#TempDestinationFacilityAuthorizedUsers dest
			ON source.[USER_PROFILE_ID] = dest.[USER_PROFILE_ID]
		WHERE
			source.FACILITY_ID = @SOURCE_FACILITY_ID
			AND dest.[USER_PROFILE_ID] IS NULL
	) temp
	WHERE temp.Row# = 1

	PRINT 'Inserted data in [FACILITY_USER_AUTHORIZATION] '
	
	SELECT 
		FACILITY_ID
		,[USER_PROFILE_ID]		
		,[EFFECTIVE_DATE]
		,[EXPIRATION_DATE]
		,[CAN_APPROVE_CHARTS]
		,[AUDIT_APPROVAL_RATE]
		,[AUDIT_PROCEDURE_RATE]
		,[AUDIT_INFUSION_RATE]
		,[AUDIT_OBSERVATION_RATE]
		,[CODER_AUTHORIZED_SERVICE_CODE]
		,[SECOND_LEVEL_AUDIT_APPROVAL_RATE]
		,[FORCE_AUDIT]
		,[EMR_ACCESS_EFFECTIVE_DATE]
		,[EMR_ACCESS_EXPIRATION_DATE]
		,[ALLOW_EMR_ACCESS]
		,[EMR_ACCESS_USER_PROFILE_ID]
		INTO 
		#TempDestinationFacilityExistingAuthorizedUsers
	FROM
	(
		SELECT 
			ROW_NUMBER() OVER(PARTITION BY source.[USER_PROFILE_ID] ORDER BY source.[EXPIRATION_DATE] DESC) AS Row#
			,source.FACILITY_ID
			,source.[USER_PROFILE_ID]
			,source.[EFFECTIVE_DATE]
			,source.[EXPIRATION_DATE]
			,source.[CAN_APPROVE_CHARTS]
			,source.[AUDIT_APPROVAL_RATE]
			,source.[AUDIT_PROCEDURE_RATE]
			,source.[AUDIT_INFUSION_RATE]
			,source.[AUDIT_OBSERVATION_RATE]
			,source.[CODER_AUTHORIZED_SERVICE_CODE]
			,source.[SECOND_LEVEL_AUDIT_APPROVAL_RATE]
			,source.[FORCE_AUDIT]
			,source.[EMR_ACCESS_EFFECTIVE_DATE]
			,source.[EMR_ACCESS_EXPIRATION_DATE]
			,source.[ALLOW_EMR_ACCESS]
			,source.[EMR_ACCESS_USER_PROFILE_ID]
		FROM 
			[dbo].[FACILITY_USER_AUTHORIZATION] source
		JOIN
			#TempDestinationFacilityAuthorizedUsers dest
			ON source.[USER_PROFILE_ID] = dest.[USER_PROFILE_ID]
		WHERE
			source.FACILITY_ID = @SOURCE_FACILITY_ID
			AND source.USER_PROFILE_ID = dest.[USER_PROFILE_ID]
	) temp
	WHERE temp.Row# = 1

	UPDATE dest
	SET
		[CHANGED_DATE_TIME] = @CURRENT_DATE
		,[CHANGING_USER_PROFILE_ID] = @CREATING_USER_ID
		,[EFFECTIVE_DATE] = source.[EFFECTIVE_DATE]
		,[EXPIRATION_DATE] = source.[EXPIRATION_DATE]
		,[CAN_APPROVE_CHARTS] = source.[CAN_APPROVE_CHARTS]
		,[AUDIT_APPROVAL_RATE] = source.[AUDIT_APPROVAL_RATE]
		,[AUDIT_PROCEDURE_RATE] = source.[AUDIT_PROCEDURE_RATE]
		,[AUDIT_INFUSION_RATE] = source.[AUDIT_INFUSION_RATE]
		,[AUDIT_OBSERVATION_RATE] = source.[AUDIT_OBSERVATION_RATE]
		,[CODER_AUTHORIZED_SERVICE_CODE] = source.[CODER_AUTHORIZED_SERVICE_CODE]
		,[SECOND_LEVEL_AUDIT_APPROVAL_RATE] = source.[SECOND_LEVEL_AUDIT_APPROVAL_RATE]
		,[FORCE_AUDIT] = source.[FORCE_AUDIT]
		,[EMR_ACCESS_EFFECTIVE_DATE] = source.[EMR_ACCESS_EFFECTIVE_DATE]
		,[EMR_ACCESS_EXPIRATION_DATE] = source.[EMR_ACCESS_EXPIRATION_DATE]
		,[ALLOW_EMR_ACCESS] = source.[ALLOW_EMR_ACCESS]
		,[EMR_ACCESS_USER_PROFILE_ID] = source.[EMR_ACCESS_USER_PROFILE_ID]
	FROM
		[dbo].[FACILITY_USER_AUTHORIZATION] dest 		
		JOIN
		#TempDestinationFacilityExistingAuthorizedUsers source
		ON source.[USER_PROFILE_ID] = source.[USER_PROFILE_ID]
		AND source.[FACILITY_ID] =  source.FACILITY_ID
	WHERE
		dest.[USER_PROFILE_ID] = source.[USER_PROFILE_ID]
		AND dest.FACILITY_ID = @DESTINATION_FACILITY_ID

	PRINT 'Updated data in [FACILITY_USER_AUTHORIZATION]'

	DELETE FROM USER_AUDIT_RATE_ADJUSTMENT_REASON WHERE FACILITY_ID = @DESTINATION_FACILITY_ID

	PRINT 'Deleted all rows for USER_AUDIT_RATE_ADJUSTMENT_REASON'

	INSERT INTO USER_AUDIT_RATE_ADJUSTMENT_REASON
		(USER_PROFILE_ID, FACILITY_ID, AUDIT_RATE, PRIOR_AUDIT_RATE, AUDIT_RATE_ADJUSTED_BY_USER_ID,AUDIT_RATE_ADJUSTMENT_REASON_ID, AUDIT_RATE_ADJUSTED_DATETIME, AUDIT_LEVEL)
	SELECT
		USER_PROFILE_ID, @DESTINATION_FACILITY_ID, AUDIT_RATE, PRIOR_AUDIT_RATE, AUDIT_RATE_ADJUSTED_BY_USER_ID,AUDIT_RATE_ADJUSTMENT_REASON_ID, AUDIT_RATE_ADJUSTED_DATETIME, AUDIT_LEVEL
	FROM
		USER_AUDIT_RATE_ADJUSTMENT_REASON source
	WHERE
		FACILITY_ID = @SOURCE_FACILITY_ID

	PRINT 'Inserted data in USER_AUDIT_RATE_ADJUSTMENT_REASON'

	COMMIT TRANSACTION;   
	END TRY  
	BEGIN CATCH  
	 ROLLBACK TRANSACTION;    
	 PRINT 'Rolback'
	 DECLARE @ERROR_MESSAGE VARCHAR(4000) = (SELECT Error_Message());  
  
	 THROW 50001 , @ERROR_MESSAGE, 1  
	END CATCH  
GO
