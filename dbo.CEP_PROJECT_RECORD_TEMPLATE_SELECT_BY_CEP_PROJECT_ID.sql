CREATE PROCEDURE [dbo].[CEP_PROJECT_RECORD_TEMPLATE_SELECT_BY_CEP_PROJECT_ID]
	 @CEP_PROJECT_ID int
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CEP_PROJECT_RECORD_TEMPLATE_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)
DECLARE @KeyWhereClause nvarchar(1000)

SET @sql = 'INSERT INTO #tmp (CEP_PROJECT_RECORD_TEMPLATE_ID) ' +
		   'SELECT [CEP_PROJECT_RECORD_TEMPLATE].[CEP_PROJECT_RECORD_TEMPLATE_ID] ' +
		   'FROM [CEP_PROJECT_RECORD_TEMPLATE] ' +
		   'WHERE [CEP_PROJECT_RECORD_TEMPLATE].[CEP_PROJECT_ID] = ' + CAST(@CEP_PROJECT_ID AS VARCHAR(10)) 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CEP_PROJECT_RECORD_TEMPLATE].[CEP_PROJECT_RECORD_TEMPLATE_ID] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CEP_PROJECT_RECORD_TEMPLATE].[CEP_PROJECT_RECORD_TEMPLATE_ID]
	,[CEP_PROJECT_RECORD_TEMPLATE].[CEP_PROJECT_ID]
	,[CEP_PROJECT_RECORD_TEMPLATE].[CEP_FACILITY_ID]
	,[CEP_PROJECT_RECORD_TEMPLATE].[CEP_ORGANIZATION_ID]
	,[CEP_PROJECT_RECORD_TEMPLATE].[CEP_RECORD_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[DATE_OF_BIRTH_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[GENDER_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[MEDICAL_RECORD_NUMBER_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[DATE_OF_SERVICE_END_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[ADDITIONAL_PROVIDERS_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[DIAGNOSIS_CODES_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[ALLOW_DIAGNOSIS_CODE_CHIEF_COMPLAINT]
	,[CEP_PROJECT_RECORD_TEMPLATE].[PROCEDURES_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[MODIFIERS_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[INSURANCE_TYPE_FIELD_COLLECTION_TYPE_CODE]
	,[CEP_PROJECT_RECORD_TEMPLATE].[CREATION_DATE_TIME]
	,[CEP_PROJECT_RECORD_TEMPLATE].[CREATING_USER_PROFILE_ID]
	,[CEP_PROJECT_RECORD_TEMPLATE].[CHANGED_DATE_TIME]
	,[CEP_PROJECT_RECORD_TEMPLATE].[CHANGING_USER_PROFILE_ID]
FROM
	#tmp [tmp]
	INNER JOIN [CEP_PROJECT_RECORD_TEMPLATE] 
			ON [CEP_PROJECT_RECORD_TEMPLATE].[CEP_PROJECT_RECORD_TEMPLATE_ID] = [tmp].[CEP_PROJECT_RECORD_TEMPLATE_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
