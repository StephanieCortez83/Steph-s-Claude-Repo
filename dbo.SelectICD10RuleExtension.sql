CREATE   PROC [dbo].[SelectICD10RuleExtension]
WITH EXEC AS CALLER AS      
BEGIN      
	-- setup resources      
	SET NOCOUNT ON      
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED      
       
	SELECT       
		[ICD_10_RULE_EXTENSION_ID]
		,[RULE_TYPE_CD]
		,[FIRST_CODE]
		,[LAST_CODE]
		,[RULE_DESCRIPTION]
		,[FLAG_FOR_QA]
		,[SEQUENCING_RULE]
		,[ADDTL_CODE_RULE]
		,[CODE_LIST_RULE]
		,[SPECIAL_RULE_TYPE_CD]
		,[EFFECTIVE_DT]
		,[EXPIRATION_DT]  
	FROM       
		[ICD_10_RULE_EXTENSION]
END 
GO
