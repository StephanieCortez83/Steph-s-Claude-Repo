CREATE PROCEDURE [dbo].[ICD_10_RULE_SELECT_BY_SECTION_ID_AND_RULE_TYPE_CD_AND_DATE_OF_SERVICE]
				 @SECTION_ID VARCHAR(10) = NULL
				,@RULE_TYPE_CD INT = NULL
				,@DATE_OF_SERVICE DATE = NULL
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

DECLARE @FIRST_CODE VARCHAR(3)
DECLARE @LAST_CODE VARCHAR(3)
SELECT 
    @FIRST_CODE = [S].[FIRST_CODE]
   ,@LAST_CODE = [S].[LAST_CODE]
FROM
    [ICD_10_SECTION] S WITH (NOLOCK)
WHERE  
	[S].[SECTION_ID] = @SECTION_ID

SELECT 
    [IR].[ICD_10_RULE_ID]
   ,[IR].[DESCRIPTION]
   ,[IR].[RULE_TYPE_CD]
   ,[IR].[FIRST_CODE]
   ,[IR].[LAST_CODE]
FROM   
    [ICD_10_RULE] IR WITH (NOLOCK)
WHERE  
    [IR].[FIRST_CODE] = @FIRST_CODE
AND [IR].[LAST_CODE] = @LAST_CODE
AND [IR].[RULE_LEVEL] = 'S'
AND [IR].[RULE_TYPE_CD] = @RULE_TYPE_CD
AND [IR].[EFFECTIVE_DT] <= @DATE_OF_SERVICE
AND [IR].[EXPIRATION_DT] >= @DATE_OF_SERVICE
ORDER  BY 
    [IR].[ICD_10_RULE_ID]

GO
