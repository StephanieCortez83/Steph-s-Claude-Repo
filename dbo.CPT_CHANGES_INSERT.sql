CREATE PROCEDURE [dbo].[CPT_CHANGES_INSERT]
	 @CHART_ID int
	,@CPT varchar(20)
	,@CPT_MODIFIERS varchar(100) = NULL
	,@CPT_COUNT int
	,@CHANGE_REASON varchar(100) = NULL
	,@IS_ACTIVE bit
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@IS_MATCH_PRESENT bit = NULL
	,@CPT_CHANGES_ID int OUTPUT
AS

INSERT INTO [dbo].[CPT_CHANGES]
(
	 [CHART_ID]
	,[CPT]
	,[CPT_MODIFIERS]
	,[CPT_COUNT]
	,[CHANGE_REASON]
	,[IS_ACTIVE]
	,[CREATING_USER_PROFILE_ID]
	,[CHANGING_USER_PROFILE_ID]
	,[IS_MATCH_PRESENT]
)
VALUES
(
	 @CHART_ID
	,@CPT
	,@CPT_MODIFIERS
	,@CPT_COUNT
	,@CHANGE_REASON
	,@IS_ACTIVE
	,@CREATING_USER_PROFILE_ID
	,@CHANGING_USER_PROFILE_ID
	,@IS_MATCH_PRESENT 
)

SET @CPT_CHANGES_ID = @@IDENTITY

GO
