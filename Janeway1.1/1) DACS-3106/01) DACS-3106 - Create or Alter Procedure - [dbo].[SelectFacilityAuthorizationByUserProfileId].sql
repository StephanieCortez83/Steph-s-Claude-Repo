-- Description: Returns a list of active authorized facilities for the provided UserProfileID.  
-- =============================================  
CREATE OR ALTER PROCEDURE [dbo].[SelectFacilityAuthorizationByUserProfileId] 
	  @UserProfileID int
	, @IncludeInactive	 bit = 0
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED; -- == WITH NOLOCK

	DECLARE @EffectiveDate datetime = GETDATE();
	DECLARE @ExpirationDate datetime = @EffectiveDate;

	IF @IncludeInactive = 1
	BEGIN 
		SET @EffectiveDate  = '01-01-2200';
		SET @ExpirationDate = '01-01-1900';
	END;
		
	SELECT 
		  FACILITY_USER_AUTHORIZATION.FACILITY_AUTH_ID
		, FACILITY_USER_AUTHORIZATION.USER_PROFILE_ID
		, FACILITY_USER_AUTHORIZATION.FACILITY_ID
		, FACILITY_USER_AUTHORIZATION.EFFECTIVE_DATE
		, FACILITY_USER_AUTHORIZATION.EXPIRATION_DATE
		, FACILITY_USER_AUTHORIZATION.CAN_APPROVE_CHARTS
		, FACILITY_USER_AUTHORIZATION.AUDIT_APPROVAL_RATE
		, FACILITY_USER_AUTHORIZATION.SECOND_LEVEL_AUDIT_APPROVAL_RATE
		, FACILITY_USER_AUTHORIZATION.NUMBER_COMPLETED
		, FACILITY_USER_AUTHORIZATION.AUDIT_PROCEDURE_RATE
		, FACILITY_USER_AUTHORIZATION.PROCEDURE_NUMBER_COMPLETED
		, FACILITY_USER_AUTHORIZATION.AUDIT_INFUSION_RATE
		, FACILITY_USER_AUTHORIZATION.INFUSION_NUMBER_COMPLETED
		, FACILITY_USER_AUTHORIZATION.AUDIT_OBSERVATION_RATE
		, FACILITY_USER_AUTHORIZATION.OBSERVATION_NUMBER_COMPLETED
		, FACILITY_USER_AUTHORIZATION.CODER_AUTHORIZED_SERVICE_CODE
		, FACILITY_USER_AUTHORIZATION.FACILITY_PROF_ID
		, FACILITY_USER_AUTHORIZATION.CREATION_DATE_TIME
		, FACILITY_USER_AUTHORIZATION.CREATING_USER_PROFILE_ID
		, FACILITY_USER_AUTHORIZATION.CHANGED_DATE_TIME
		, FACILITY_USER_AUTHORIZATION.CHANGING_USER_PROFILE_ID
		, FACILITY_USER_AUTHORIZATION.FORCE_AUDIT
		, FACILITY_USER_AUTHORIZATION.ACTIVE_CHART_ID
		, FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_REASON_ID
		, FACILITY_USER_AUTHORIZATION_EXPIRATION_DATE_CHANGE_OTHER_REASON
		, ALLOW_EMR_ACCESS
		, EMR_ACCESS_EFFECTIVE_DATE
		, EMR_ACCESS_EXPIRATION_DATE
		, EMR_ACCESS_USER_PROFILE_ID
		 FROM 
			FACILITY_USER_AUTHORIZATION
			JOIN USER_PROFILE ON USER_PROFILE.USER_PROFILE_ID = FACILITY_USER_AUTHORIZATION.USER_PROFILE_ID
			JOIN FACILITY ON FACILITY.FACILITY_ID = FACILITY_USER_AUTHORIZATION.FACILITY_ID
		 WHERE 
			FACILITY_USER_AUTHORIZATION.USER_PROFILE_ID = @UserProfileID
			AND (FACILITY_USER_AUTHORIZATION.EFFECTIVE_DATE < @EffectiveDate AND FACILITY_USER_AUTHORIZATION.EXPIRATION_DATE > @ExpirationDate)
		ORDER BY 
			FACILITY.NAME;
END;
GO

