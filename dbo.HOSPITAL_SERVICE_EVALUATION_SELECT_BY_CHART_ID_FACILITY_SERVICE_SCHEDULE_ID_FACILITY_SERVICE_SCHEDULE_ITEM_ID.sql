CREATE PROCEDURE [dbo].[HOSPITAL_SERVICE_EVALUATION_SELECT_BY_CHART_ID_FACILITY_SERVICE_SCHEDULE_ID_FACILITY_SERVICE_SCHEDULE_ITEM_ID]
	@ChartID INT
	,@FacilityServiceScheduleID INT
	,@FacilityServiceScheduleItemID INT
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT	 [HOSPITAL_SERVICE_EVALUATION_ID]
			,[CHART_ID]
			,[FACILITY_SERVICE_ID]
			,[CREATION_DATE_TIME]
			,[CREATING_USER_PROFILE_ID]
			,[CHANGED_DATE_TIME]
			,[CHANGING_USER_PROFILE_ID]
			,[FACILITY_SERVICE_SCHEDULE_ID]
			,[FACILITY_SERVICE_SCHEDULE_ITEM_ID]
	FROM	[dbo].[HOSPITAL_SERVICE_EVALUATION]
	WHERE [CHART_ID] = @ChartID
	AND   [FACILITY_SERVICE_SCHEDULE_ID] = @FacilityServiceScheduleID
	AND   [FACILITY_SERVICE_SCHEDULE_ITEM_ID] = @FacilityServiceScheduleItemID;
END

GO
