ALTER PROCEDURE [dbo].[USER_LOGON_SELECT_BY_USER_LOGON_ID]
	@USER_LOGON_ID bigint
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [USER_LOGON].[USER_LOGON_ID]
	,[USER_LOGON].[USER_PROFILE_ID]
	,[USER_LOGON].[LOGON_DATE_TIME]
	,[USER_LOGON].[USER_HOST_ADDRESS]
FROM
	[dbo].[USER_LOGON]
WHERE
	[USER_LOGON].[USER_LOGON_ID] = @USER_LOGON_ID
GO

ALTER PROCEDURE [dbo].[USER_LOGON_SELECT_BY_USER_PROFILE_ID]
	 @USER_PROFILE_ID int = NULL
	,@LOGON_DATE_TIME datetime = NULL
	,@PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[USER_LOGON_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)
DECLARE @KeyWhereClause nvarchar(1000)

SET @sql = 'INSERT INTO #tmp (USER_LOGON_ID) ' +
		   'SELECT [USER_LOGON].[USER_LOGON_ID] ' +
		   'FROM [USER_LOGON] ' +
		   'WHERE [USER_LOGON].[USER_PROFILE_ID] = ' + CAST(@USER_PROFILE_ID AS VARCHAR(10)) 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [USER_LOGON].[CREATION_DATE_TIME] '

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [USER_LOGON].[USER_LOGON_ID]
	,[USER_LOGON].[USER_PROFILE_ID]
	,[USER_LOGON].[LOGON_DATE_TIME]
	,[USER_LOGON].[USER_HOST_ADDRESS]
FROM
	#tmp [tmp]
	INNER JOIN [USER_LOGON] 
			ON [USER_LOGON].[USER_LOGON_ID] = [tmp].[USER_LOGON_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]
GO


