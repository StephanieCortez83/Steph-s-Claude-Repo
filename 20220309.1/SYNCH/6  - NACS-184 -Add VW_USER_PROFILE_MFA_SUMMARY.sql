	  ,[VERIFIED_USER_PROFILE].[FIRST_NAME]			 AS [VERIFIED_USER_FIRST_NAME]
	  ,[VERIFIED_USER_PROFILE].[LAST_NAME]			 AS [VERIFIED_USER_LAST_NAME]
	  ,[USER_PROFILE_MFA].[VERIFIED_DATE_TIME]
	  ,[INVALIDATED_USER_PROFILE].[USER_PROFILE_ID] AS [INVALIDATED_USER_PROFILE_ID]
	  ,[INVALIDATED_USER_PROFILE].[FIRST_NAME]		 AS [INVALIDATED_USER_FIRST_NAME]
	  ,[INVALIDATED_USER_PROFILE].[LAST_NAME]		 AS [INVALIDATED_USER_LAST_NAME]
	  ,[USER_PROFILE_MFA].[INVALIDATED_DATE_TIME]
FROM
	[USER_PROFILE_MFA] WITH (NOLOCK)
	INNER JOIN [USER_PROFILE] WITH (NOLOCK)
			ON [USER_PROFILE].[USER_PROFILE_ID] = [USER_PROFILE_MFA].[USER_PROFILE_ID]
	LEFT  JOIN [USER_PROFILE] [VERIFIED_USER_PROFILE] WITH (NOLOCK)
			ON [VERIFIED_USER_PROFILE].[USER_PROFILE_ID] = [USER_PROFILE_MFA].[USER_PROFILE_ID]
	LEFT  JOIN [USER_PROFILE] [INVALIDATED_USER_PROFILE] WITH (NOLOCK)
			ON [INVALIDATED_USER_PROFILE].[USER_PROFILE_ID] = [USER_PROFILE_MFA].[USER_PROFILE_ID]

