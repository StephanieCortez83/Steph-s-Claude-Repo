--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[USER_PROFILE_ID] int NOT NULL
)

DECLARE @sql nvarchar(max)

-- wrapping this in an outer re-join to USER_PROFILE so we don't have to pull every
-- field into the temp table to do a dynamic sort as the inner joins can cause repeating
-- rows because of the 1:many user profile to group rights 

SET @sql = 'INSERT INTO #tmp (USER_PROFILE_ID) ' +
		   'SELECT [USER_PROFILE].[USER_PROFILE_ID] ' +
		   'FROM ' + 
		   '( ' +
		   '	SELECT DISTINCT [USER_PROFILE].[USER_PROFILE_ID] ' +
		   '	FROM [USER_PROFILE] ' +
		   '	INNER JOIN [USER_GROUP] [PRIMARY_USER_GROUP] ' +
		   '			ON [PRIMARY_USER_GROUP].[USER_GROUP_ID] = [USER_PROFILE].[USER_GROUP_ID] ' +
		   '	LEFT  JOIN [USER_GROUP_TO_USER_PROFILE] ' +
		   '			ON [USER_GROUP_TO_USER_PROFILE].[USER_PROFILE_ID] = [USER_PROFILE].[USER_PROFILE_ID] ' +
		   '	LEFT  JOIN [USER_GROUP] ' +
		   '			ON [USER_GROUP].[USER_GROUP_ID] = [USER_GROUP_TO_USER_PROFILE].[USER_GROUP_ID] ' +
		   '	LEFT  JOIN [GROUP_RIGHTS] ' +
		   '			ON [GROUP_RIGHTS].[USER_GROUP_ID] = [USER_GROUP].[USER_GROUP_ID] ' +
		   '	WHERE ' +
		   '		[GROUP_RIGHTS].[DEFINED_RIGHT_ID] = ' + CAST(@USER_GROUP_RIGHT_ID AS VARCHAR(10)) +
		   ') [USER_RIGHT_USERS] ' +
		   'INNER JOIN [USER_PROFILE] ' +
		   '		ON [USER_PROFILE].[USER_PROFILE_ID] = [USER_RIGHT_USERS].[USER_PROFILE_ID] '

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' AND (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [USER_PROFILE].[LAST_NAME] '
 
EXEC sp_executesql @sql

