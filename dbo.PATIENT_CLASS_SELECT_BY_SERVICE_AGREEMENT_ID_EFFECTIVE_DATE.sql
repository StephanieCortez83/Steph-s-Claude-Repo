--CREATE  PROCEDURE [dbo].[PATIENT_CLASS_SELECT_BY_SERVICE_AGREEMENT_ID_EFFECTIVE_DATE]
CREATE   PROCEDURE [dbo].[PATIENT_CLASS_SELECT_BY_SERVICE_AGREEMENT_ID_EFFECTIVE_DATE]
	@SERVICE_AGREEMENT_ID INT
	,@DATE_OF_SERVICE DATETIME
	,@SA_EFFECTIVE_DATE DATETIME
	,@SA_EXPIRATION_DATE DATETIME
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT	[PATIENT_CLASS_ID]
			,[SERVICE_AGREEMENT_ID]
			,[DESCRIPTION]
			,[PHYSICIAN_SERVICE_CLASS_CD]
			,[DEFAULT_IND]
			,[OBSERVATION_IND]
			,[LOCATION_OF_SERVICE]
			,[COPIED_FROM_PATIENT_CLASS_ID]
			,[EFFECTIVE_DATE]
			,[EXPIRATION_DATE]
			,[BYPASS_AUTO_APPROVAL]
	FROM	[dbo].[PATIENT_CLASS] 
	WHERE [SERVICE_AGREEMENT_ID] = @SERVICE_AGREEMENT_ID
	AND @DATE_OF_SERVICE BETWEEN ISNULL([EFFECTIVE_DATE], @SA_EFFECTIVE_DATE) AND ISNULL([EXPIRATION_DATE], @SA_EXPIRATION_DATE)
	ORDER BY [DESCRIPTION];  -- added to replace previous sorting
END

GO
