CREATE PROCEDURE [dbo].[OBSERVATION_EXCLUSION_HOURS_REASON_TEST_INSERT]
	 @SERVICE_AGREEMENT_ID int
	,@OBSERVATION_EXCLUSION_HOURS_REASON_DESCRIPTION varchar(50)
	,@OBSERVATION_EXCLUSION_HOURS_REASON_ID int OUTPUT
AS

DECLARE @FOUND_OBSERVATION_EXCLUSION_HOURS_REASON_ID int;

SELECT @FOUND_OBSERVATION_EXCLUSION_HOURS_REASON_ID = [EXCLUSION_HOURS_REASON_ID]
	FROM
		[dbo].[OBSERVATION_EXCLUSION_HOURS_REASON] with (NOLOCK)
	WHERE
		([SERVICE_AGREEMENT_ID] = @SERVICE_AGREEMENT_ID) and 
		([DESCRIPTION] = @OBSERVATION_EXCLUSION_HOURS_REASON_DESCRIPTION);

if @FOUND_OBSERVATION_EXCLUSION_HOURS_REASON_ID is null
	BEGIN
		INSERT INTO [dbo].[OBSERVATION_EXCLUSION_HOURS_REASON]
		(
			 [SERVICE_AGREEMENT_ID]
			,[DESCRIPTION]
		)
		VALUES
		(
			 @SERVICE_AGREEMENT_ID
			,@OBSERVATION_EXCLUSION_HOURS_REASON_DESCRIPTION	 
		)

		SET @OBSERVATION_EXCLUSION_HOURS_REASON_ID = @@IDENTITY;
		PRINT('OBSERVATION_EXCLUSION_HOURS_REASON_ID = ' + CAST(@OBSERVATION_EXCLUSION_HOURS_REASON_ID AS VARCHAR(32)));
	END
ELSE
	BEGIN
		PRINT('OBSERVATION_EXCLUSION_HOURS_REASON_DESCRIPTION already exists for this SERVICE_AGREEMENT_ID = ' + CAST(@OBSERVATION_EXCLUSION_HOURS_REASON_ID AS VARCHAR(32)));
		SET @OBSERVATION_EXCLUSION_HOURS_REASON_ID = @FOUND_OBSERVATION_EXCLUSION_HOURS_REASON_ID
	END;

GO
