-- Description:	SQL for the Processed Accounts by Client report.
-- =============================================
CREATE PROCEDURE [dbo].[rpt_Processed_Accounts_by_Client] @From DATE,
	@Thru DATE = NULL,
	@ByDateProcessed BIT = 0,
	@Company INT,
	@Facility INT = - 1,
  @ReportUser INT
AS
BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

	-- Insert statements for procedure here
	DECLARE @m_From DATE = @From;
	DECLARE @m_Thru DATE = ISNULL(@Thru, @From);
	DECLARE @m_ByDateProcessed BIT = @ByDateProcessed;
	DECLARE @m_Company INT = @Company;
	DECLARE @m_Facility INT = @Facility;
  DECLARE @m_ReportUser INT = @ReportUser;

	SELECT f.CLIENT_FACILITY_NUMBER [Client],
		f.FACILITY_NUMBER [Location],
		sp.FACILITY_CHART_ID [VisitID],
		sp.TIME_OF_SERVICE [DOS],
		sp.SENT_DATE [Processed],
		pd.[DESCRIPTION] [Disposition],
		sp.BILLING_CODE [SIM],
		sp.CPT_CODE [CPT],
		sp.QUANTITY [Units],
		sap.FACILITY_PAYOR_NAME [Payor],
		CASE sp.CLASS
			WHEN 'PL'
				THEN CASE 
						WHEN c.NURSE_PRACTITIONER_ID > 0
							AND (
								ISNULL(c.[NO_ATTENDING_PROVIDER_SELECTED_IND], 0) = 1
								OR ISNULL(ap.[UNSPECIFIED_PROVIDER_IND], 0) = 1
								)
							THEN mp.EMPLOYEE_IDENTIFIER
						ELSE ap.EMPLOYEE_IDENTIFIER
						END
			WHEN 'PP'
				THEN CASE 
						WHEN fpr.FACILITY_PROF_ROLE_ID = 2
							THEN fp.EMPLOYEE_IDENTIFIER
						WHEN ISNULL(c.[NO_ATTENDING_PROVIDER_SELECTED_IND], 0) = 1
							THEN mp.EMPLOYEE_IDENTIFIER
						ELSE ap.EMPLOYEE_IDENTIFIER
						END
			ELSE ap.EMPLOYEE_IDENTIFIER
			END [Bill_Provider_ID],
		CASE sp.CLASS
			WHEN 'PL'
				THEN CASE 
						WHEN c.NURSE_PRACTITIONER_ID > 0
							AND (
								ISNULL(c.[NO_ATTENDING_PROVIDER_SELECTED_IND], 0) = 1
								OR ISNULL(ap.[UNSPECIFIED_PROVIDER_IND], 0) = 1
								)
							THEN mp.SECONDARY_EMPLOYEE_ID
						ELSE ap.SECONDARY_EMPLOYEE_ID
						END
			WHEN 'PP'
				THEN CASE 
						WHEN fpr.FACILITY_PROF_ROLE_ID = 2
							THEN fp.SECONDARY_EMPLOYEE_ID
						WHEN ISNULL(c.[NO_ATTENDING_PROVIDER_SELECTED_IND], 0) = 1
							THEN mp.SECONDARY_EMPLOYEE_ID
						ELSE ap.SECONDARY_EMPLOYEE_ID
						END
			ELSE ap.SECONDARY_EMPLOYEE_ID
			END [Bill_2nd_ID],
		CASE sp.CLASS
			WHEN 'PL'
				THEN CASE 
						WHEN c.NURSE_PRACTITIONER_ID > 0
							AND (
								ISNULL(c.[NO_ATTENDING_PROVIDER_SELECTED_IND], 0) = 1
								OR ISNULL(ap.[UNSPECIFIED_PROVIDER_IND], 0) = 1
								)
							THEN mp.LAST_NAME + ', ' + mp.FIRST_NAME
						ELSE ap.LAST_NAME + ', ' + ap.FIRST_NAME
						END
			WHEN 'PP'
				THEN CASE 
						WHEN fpr.FACILITY_PROF_ROLE_ID = 2
							THEN fp.LAST_NAME + ', ' + fp.FIRST_NAME
						WHEN ISNULL(c.[NO_ATTENDING_PROVIDER_SELECTED_IND], 0) = 1
							THEN mp.LAST_NAME + ', ' + mp.FIRST_NAME
						ELSE ap.LAST_NAME + ', ' + ap.FIRST_NAME
						END
			ELSE ap.LAST_NAME + ', ' + ap.FIRST_NAME
			END [Bill_Provider_Name],
		CASE sp.CLASS
			WHEN 'PL'
				THEN CASE 
						WHEN c.NURSE_PRACTITIONER_ID > 0
							AND (
								ISNULL(c.[NO_ATTENDING_PROVIDER_SELECTED_IND], 0) = 1
								OR ISNULL(ap.[UNSPECIFIED_PROVIDER_IND], 0) = 1
								)
							THEN mpr.[DESCRIPTION]
						ELSE apr.[DESCRIPTION]
						END
			WHEN 'PP'
				THEN CASE 
						WHEN fpr.FACILITY_PROF_ROLE_ID = 2
							THEN fpr.[DESCRIPTION]
						WHEN ISNULL(c.[NO_ATTENDING_PROVIDER_SELECTED_IND], 0) = 1
							THEN mpr.[DESCRIPTION]
						ELSE apr.[DESCRIPTION]
						END
			ELSE apr.[DESCRIPTION]
			END [Bill_Provider_Role],
		CASE sp.CLASS
			WHEN 'PL'
				THEN CASE 
						WHEN c.NURSE_PRACTITIONER_ID > 0
							AND ISNULL(c.PROVIDER_EVAL_PERFORMED_BY_IND, 1) = 1
							THEN mp.EMPLOYEE_IDENTIFIER
						ELSE ap.EMPLOYEE_IDENTIFIER
						END
			WHEN 'PP'
				THEN CASE 
						WHEN sp.PHYSICIAN_ID > 0
							THEN fp.EMPLOYEE_IDENTIFIER
						ELSE ap.EMPLOYEE_IDENTIFIER
						END
			ELSE ap.EMPLOYEE_IDENTIFIER
			END [Performing_Provider_ID],
		CASE sp.CLASS
			WHEN 'PL'
				THEN CASE 
						WHEN c.NURSE_PRACTITIONER_ID > 0
							AND ISNULL(c.PROVIDER_EVAL_PERFORMED_BY_IND, 1) = 1
							THEN mp.SECONDARY_EMPLOYEE_ID
						ELSE ap.SECONDARY_EMPLOYEE_ID
						END
			WHEN 'PP'
				THEN CASE 
						WHEN sp.PHYSICIAN_ID > 0
							THEN fp.SECONDARY_EMPLOYEE_ID
						ELSE ap.SECONDARY_EMPLOYEE_ID
						END
			ELSE ap.SECONDARY_EMPLOYEE_ID
			END [Performing_2nd_ID],
		CASE sp.CLASS
			WHEN 'PL'
				THEN CASE 
						WHEN c.NURSE_PRACTITIONER_ID > 0
							AND ISNULL(c.PROVIDER_EVAL_PERFORMED_BY_IND, 1) = 1
							THEN mp.LAST_NAME + ', ' + mp.FIRST_NAME
						ELSE ap.LAST_NAME + ', ' + ap.FIRST_NAME
						END
			WHEN 'PP'
				THEN CASE 
						WHEN sp.PHYSICIAN_ID > 0
							THEN fp.LAST_NAME + ', ' + fp.FIRST_NAME
						ELSE ap.LAST_NAME + ', ' + ap.FIRST_NAME
						END
			ELSE ap.LAST_NAME + ', ' + ap.FIRST_NAME
			END [Performing_Provider_Name],
		CASE sp.CLASS
			WHEN 'PL'
				THEN CASE 
						WHEN c.NURSE_PRACTITIONER_ID > 0
							AND ISNULL(c.PROVIDER_EVAL_PERFORMED_BY_IND, 1) = 1
							THEN mpr.[DESCRIPTION]
						ELSE apr.[DESCRIPTION]
						END
			WHEN 'PP'
				THEN CASE 
						WHEN sp.PHYSICIAN_ID > 0
							THEN fpr.[DESCRIPTION]
						ELSE apr.[DESCRIPTION]
						END
			ELSE apr.[DESCRIPTION]
			END [Performing_Provider_Role],
		CASE 
			WHEN c.NURSE_PRACTITIONER_ID > 0
				AND ISNULL(c.PROVIDER_EVAL_PERFORMED_BY_IND, 1) = 1
				THEN 'Midlevel Provider'
			ELSE 'Attending Physician'
			END [PerformingProvider]
	FROM CHART c WITH (NOLOCK)
	INNER JOIN SENT_PROCEDURE sp WITH (NOLOCK) ON sp.CHART_ID = c.CHART_ID
	INNER JOIN SERVICE_AGREEMENT sa WITH (NOLOCK) ON sa.SERVICE_AGREEMENT_ID = sp.SERVICE_AGREEMENT_ID
	INNER JOIN FACILITY f WITH (NOLOCK) ON f.FACILITY_ID = sa.FACILITY_ID
	INNER JOIN FACILITY_PROFESSIONAL fp WITH (NOLOCK) ON fp.FACILITY_PROF_ID = sp.PHYSICIAN_ID
	INNER JOIN FACILITY_PROFESSIONAL_ROLE fpr WITH (NOLOCK) ON fpr.FACILITY_PROF_ROLE_ID = fp.ROLE_ID
	LEFT JOIN FACILITY_PROFESSIONAL ap WITH (NOLOCK) ON ap.FACILITY_PROF_ID = c.PHYSICIAN_ID
	LEFT JOIN FACILITY_PROFESSIONAL_ROLE apr WITH (NOLOCK) ON apr.FACILITY_PROF_ROLE_ID = ap.ROLE_ID
	LEFT JOIN FACILITY_PROFESSIONAL mp WITH (NOLOCK) ON mp.FACILITY_PROF_ID = c.NURSE_PRACTITIONER_ID
	LEFT JOIN FACILITY_PROFESSIONAL_ROLE mpr WITH (NOLOCK) ON mpr.FACILITY_PROF_ROLE_ID = mp.ROLE_ID
	LEFT JOIN PATIENT_DISPOSITION pd WITH (NOLOCK) ON pd.PATIENT_DISPOSITION_ID = sp.PATIENT_DISPOSITION_ID
	LEFT JOIN CHART_PAYOR cp WITH (NOLOCK) ON cp.CHART_ID = c.CHART_ID
	LEFT JOIN SERVICE_AGREEMENT_PAYOR sap WITH (NOLOCK) ON sap.SERVICE_AGREEMENT_PAYOR_ID = cp.SERVICE_AGREEMENT_PAYOR_ID
	WHERE sa.COMPANY_ID = @m_Company
		AND (
			@m_Facility = - 1
			OR @m_Facility = sp.FACILITY_ID
			)
		AND (
			(
				@m_ByDateProcessed = 1
				AND DATEADD(DAY, DATEDIFF(DAY, 0, sp.SENT_DATE), 0) BETWEEN @m_From AND @m_Thru
				)
			OR (
				@m_ByDateProcessed = 0
				AND DATEADD(DAY, DATEDIFF(DAY, 0, sp.TIME_OF_SERVICE), 0) BETWEEN @m_From AND @m_Thru
				)
			)
    AND EXISTS (
      SELECT *
      FROM FACILITY_USER_AUTHORIZATION
      WHERE USER_PROFILE_ID = @m_ReportUser
        AND FACILITY_ID = sp.FACILITY_ID
        AND GETDATE() BETWEEN EFFECTIVE_DATE AND EXPIRATION_DATE
    )
	ORDER BY [Client],
		[Location],
		[DOS],
		[VisitID]
END

GO
