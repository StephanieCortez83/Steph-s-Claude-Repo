CREATE   PROCEDURE [dbo].[FACILITY_SELECT_AUTHORIZED_SIMPLE_FACILITY_BY_USER_PROFILE_ID]
    @USER_PROFILE_ID int
AS
BEGIN
    SET NOCOUNT ON;
    SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

    DECLARE @CURRENT_DATE DATE = CAST(GETDATE() AS DATE);

    SELECT DISTINCT
          [FACILITY].[FACILITY_ID]
         ,[FACILITY].[NAME]
    FROM
        [FACILITY]
        INNER JOIN [FACILITY_USER_AUTHORIZATION]
                ON [FACILITY_USER_AUTHORIZATION].[FACILITY_ID] = [FACILITY].[FACILITY_ID]
        INNER JOIN [SERVICE_AGREEMENT]
                ON [SERVICE_AGREEMENT].[FACILITY_ID] = [FACILITY].[FACILITY_ID]
    WHERE
        [FACILITY_USER_AUTHORIZATION].[USER_PROFILE_ID] = @USER_PROFILE_ID
        AND
        [FACILITY_USER_AUTHORIZATION].[EFFECTIVE_DATE] <= @CURRENT_DATE
        AND
        [FACILITY_USER_AUTHORIZATION].[EXPIRATION_DATE] >= @CURRENT_DATE
    ORDER BY
        [NAME];

    SELECT @@ROWCOUNT;
END;
GO
