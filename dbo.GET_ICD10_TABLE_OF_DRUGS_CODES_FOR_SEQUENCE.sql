CREATE PROC [dbo].[GET_ICD10_TABLE_OF_DRUGS_CODES_FOR_SEQUENCE]
(
	@seq varchar(20)
)
AS
BEGIN

	SELECT d.ICD_10_TABLE_OF_DRUGS_CODES_ID, d.ICD_10_TABLE_OF_DRUGS_AND_CHEMICALS_ID, d.SEQ_NUMBER,  d.COLUMN_NUMBER, d.CODE
	from ICD_10_TABLE_OF_DRUGS_CODES d
	where d.SEQ_NUMBER = @seq 
	order by d.column_number
END

GO
