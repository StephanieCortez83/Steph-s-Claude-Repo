CREATE PROCEDURE [dbo].[DEFINED_RIGHT_SELECT]
	 @PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[DEFINED_RIGHT_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)

SET @sql = 'INSERT INTO #tmp (DEFINED_RIGHT_ID) ' +
		   'SELECT [DEFINED_RIGHT].[DEFINED_RIGHT_ID] ' +
		   'FROM [DEFINED_RIGHT] ' 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' WHERE (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [DEFINED_RIGHT].[CREATION_DATE_TIME]'

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [DEFINED_RIGHT].[DEFINED_RIGHT_ID]
	,[DEFINED_RIGHT].[NAME]
	,[DEFINED_RIGHT].[CREATION_DATE_TIME]
	,[DEFINED_RIGHT].[CREATING_USER_PROFILE_ID]
	,[DEFINED_RIGHT].[CHANGED_DATE_TIME]
	,[DEFINED_RIGHT].[CHANGING_USER_PROFILE_ID]
	,[DEFINED_RIGHT].[ALLOW_INHERITANCE]
	,[DEFINED_RIGHT].[DEFINITION]
	,[DEFINED_RIGHT].[IS_ADMIN]
FROM
	#tmp [tmp]
	INNER JOIN [DEFINED_RIGHT] 
			ON [DEFINED_RIGHT].[DEFINED_RIGHT_ID] = [tmp].[DEFINED_RIGHT_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
