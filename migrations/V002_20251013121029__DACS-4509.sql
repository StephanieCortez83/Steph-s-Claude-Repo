CREATE OR ALTER PROCEDURE [dbo].[SelectPortalAnnouncementsForHomePage]
	@AsOf DATETIME = NULL
AS
BEGIN
	DECLARE @v_AsOf DATETIME = COALESCE(@AsOf, GETDATE());

	SELECT 
		 PORTAL_ANNOUNCEMENT_ID
		,TITLE
		,MORE_LINK
		,DESCRIPTION
		,CREATION_DATE_TIME
	FROM 
		PORTAL_ANNOUNCEMENT 
	WHERE 
		@v_AsOf BETWEEN EFFECTIVE_DATE AND EXPIRE_DATE;
END
