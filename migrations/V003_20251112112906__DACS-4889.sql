CREATE   PROCEDURE [dbo].[SelectActiveObservationChargeMasterDepartmentByServiceAgreementIdAndTimeOfService]
	 @ServiceAgreementId INT
	,@TimeOfService DATE = NULL
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED; 

	DROP TABLE IF EXISTS #TmpTableCMD;

	SELECT
		 [CHARGE_MASTER_DEPT_ID]
		,[SERVICE_AGREEMENT_ID]
		,[NAME]
		,[FACILITY_DEPARTMENT_CODE]
		,[FACILITY_DEPARTMENT_ALT]
		,[ACTIVE]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[CALCULATE_APC_RATES_IND]
		,[DEFAULT_IND]
		,[OBSERVATION_IND]
		,[OBSERVATION_CODER_ASSIGNMENT_CODE]
		,[EFFECTIVE_DATE]
		,[EXPIRATION_DATE]
		,[CHARGE_MASTER_DEPARTMENT_CLASS_ID]
		,[FACILITY_CAMPUS_CODE]
		,[COPIED_FROM_DEPT_ID]
	INTO #TmpTableCMD
	FROM
		[CHARGE_MASTER_DEPARTMENT]
	WHERE
		[SERVICE_AGREEMENT_ID] = @ServiceAgreementId
		AND ACTIVE = 1
		AND OBSERVATION_IND = 1;
		
	IF @TimeOfService > '01-01-1900'
	BEGIN
		DECLARE @dateTimeDos DATETIME = CAST(@TimeOfService AS DATETIME);
		
		DELETE
		FROM
			#TmpTableCMD
		WHERE
			@dateTimeDos NOT BETWEEN COALESCE([EFFECTIVE_DATE], '1/1/2000') AND COALESCE([EXPIRATION_DATE], '12/31/9999');
	END;
		
	SELECT
		*
	FROM
		#TmpTableCMD
	ORDER BY
		 COALESCE([DEFAULT_IND], 0) DESC
		,COALESCE([OBSERVATION_IND], 0)
		,[NAME];
		
