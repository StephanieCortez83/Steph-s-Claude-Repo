CREATE OR ALTER PROCEDURE [dbo].[SelectUserGroupListByReportId]
	@ReportId INT
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED; 

	SELECT 
		 [USER_GROUP].[USER_GROUP_ID]
		,[NAME]
		,[USER_ADMIN_CAN_ASSIGN]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[FORCE_CHART_SORT_BY_DOS]
		,[EXCLUDE_FROM_REPORTS_ALL_USER_GROUPS]
		,[CHART_WORK_QUEUE_ID]
		,[IS_MFA_ENABLED]
		,[INCLUDE_IN_CHARTS_COMPLETED_BY_USER_GROUP_DROPDOWN]
		,[IS_LEGACY_LOGIN_ALLOWED]
	FROM
		[USER_GROUP]
	INNER JOIN [USER_GROUP_TO_ANALYTICAL_REPORT]
			ON [USER_GROUP].[USER_GROUP_ID] = [USER_GROUP_TO_ANALYTICAL_REPORT].[USER_GROUP_ID]
	WHERE
		[USER_GROUP_TO_ANALYTICAL_REPORT].ANALYTICAL_REPORT_ID = @ReportId;
END -- end SPROC
