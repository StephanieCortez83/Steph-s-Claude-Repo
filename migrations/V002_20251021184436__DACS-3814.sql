	,@PageSection INT = NULL
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED; 

	IF @PageSection IS NULL
		SELECT 
			 [CHART_INFUSION_RESULT_ID]
			,[CHART_ID]
			,[UNITS]
			,[DATE_OF_SERVICE]
			,[CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]
			,[CHART_INFUSION_RESULT].[MODIFIERS]
			,[CHARGE_MASTER].[CPT_CODE]
