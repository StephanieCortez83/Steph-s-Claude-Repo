			,[CHART_INFUSION_RESULT].[ICD_10_PCS_CODE]
			,[ICD_10_PCS_BODY_SYSTEM_CHARACTER]
			,IIF(1 = (SELECT TOP 1 1 FROM [CODER_QA_REPORT_EXCLUSION] ex  where ex.[SOURCE_RECORD_TABLE_NAME] = 'CHART_INFUSION_RESULT' AND [key_value_1] = [CHART_INFUSION_RESULT_ID]), 1, 0) AS EXCLUDE_FROM_CODER_QA_REPORT
		FROM
			[CHART_INFUSION_RESULT]
			INNER JOIN [CHARGE_MASTER] ON [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID] = [CHARGE_MASTER].[CHARGE_MASTER_ID]
		WHERE
			[CHART_ID] = @ChartId;
	ELSE
		SELECT 
			 [CHART_INFUSION_RESULT_ID]
			,[CHART_ID]
			,[UNITS]
			,[DATE_OF_SERVICE]
			,[CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]
			,[CHART_INFUSION_RESULT].[MODIFIERS]
			,[CHARGE_MASTER].[CPT_CODE]
			,[CHARGE_MASTER].[BILLING_CODE]
			,[CHARGE_MASTER].[DESCRIPTION]
			,[CHARGE_MASTER].[MODIFIER_REQUIRED]
			,[CHARGE_MASTER].[CHARGE_MASTER_CATEGORY_ID]
			,[CHART_INFUSION_RESULT].[OBS_DEPT_ID]
			,(SELECT COUNT(*) FROM [CHARGE_MASTER_MODIFIER] WHERE [CHARGE_MASTER_MODIFIER].[CHARGE_MASTER_ID] = [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]) AS CHARGE_MASTER_MODIFIERS_COUNT
			,[CHART_INFUSION_RESULT].[ICD_10_DRUG_CATEGORY_ID]
			,[CHART_INFUSION_RESULT].[ICD_10_PCS_CODE]
			,[ICD_10_PCS_BODY_SYSTEM_CHARACTER]
			,IIF(1 = (SELECT TOP 1 1 FROM [CODER_QA_REPORT_EXCLUSION] ex  where ex.[SOURCE_RECORD_TABLE_NAME] = 'CHART_INFUSION_RESULT' AND [key_value_1] = [CHART_INFUSION_RESULT_ID]), 1, 0) AS EXCLUDE_FROM_CODER_QA_REPORT
		FROM
			[CHART_INFUSION_RESULT]
			INNER JOIN [CHARGE_MASTER] ON [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID] = [CHARGE_MASTER].[CHARGE_MASTER_ID]
			INNER JOIN [INFUSION_INJECTION_PAGE_CPT_CODE] iipcc ON [CHARGE_MASTER].[CPT_CODE] = iipcc.[CPT_CODE] AND iipcc.[PAGE_SECTION_CD] = @PageSection
		WHERE
			[CHART_ID] = @ChartId;
END;
