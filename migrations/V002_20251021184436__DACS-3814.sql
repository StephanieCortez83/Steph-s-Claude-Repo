CREATE   PROCEDURE [dbo].[SelectFromChartInfusionResultByChartIdAndModeAndEtAl]
	 @ChartId INT
	,@Mode INT = 1					-- Mode option:  1=CHART_INFUSION_RESULT, 2=CHART_INFUSION_RESULT_HISTORY, 3=CHART_SECOND_AUDIT_INFUSION_RESULT_HISTORY
	,@ObservationIndicator INT = 1	-- Observation option:  1=All, 2=Exclude Observation Depts, 3=Observation Depts only
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED; 

	DROP TABLE IF EXISTS #TmpSourceTable;
	CREATE TABLE #TmpSourceTable
	(
		 [CHART_INFUSION_RESULT_ID] INT NULL
		,[CHART_ID] INT NULL
		,[UNITS] INT NULL
		,[DATE_OF_SERVICE] DATETIME NULL
		,[CHARGE_MASTER_ID] INT NULL
		,[MODIFIERS] VARCHAR(500) NULL
		,[CPT_CODE] VARCHAR(5) NULL
		,[BILLING_CODE] VARCHAR(20) NULL
		,[DESCRIPTION] VARCHAR(100) NULL
		,[MODIFIER_REQUIRED] BIT NULL
		,[CHARGE_MASTER_CATEGORY_ID] INT NULL
		,[OBS_DEPT_ID] INT NULL
		,[CHARGE_MASTER_MODIFIERS_COUNT] INT NULL
		,[ICD_10_DRUG_CATEGORY_ID] NUMERIC NULL
		,[ICD_10_PCS_CODE] VARCHAR(100) NULL
		,[ICD_10_PCS_BODY_SYSTEM_CHARACTER] VARCHAR(1) NULL
		,[EXCLUDE_FROM_CODER_QA_REPORT] INT NULL
		,[OBSERVATION_IND] BIT NULL
	);
	
	IF @Mode = 2
		INSERT INTO #TmpSourceTable
		SELECT 
			 [CHART_INFUSION_RESULT_ID]
			,[CHART_ID]
			,[UNITS]
			,[DATE_OF_SERVICE]
			,[CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]
			,[CHART_INFUSION_RESULT].[MODIFIERS]
			,[CHARGE_MASTER].[CPT_CODE]
			,[CHARGE_MASTER].[BILLING_CODE]
			,[CHARGE_MASTER].[DESCRIPTION]
			,[CHARGE_MASTER].[MODIFIER_REQUIRED]
			,[CHARGE_MASTER].[CHARGE_MASTER_CATEGORY_ID]
			,[CHART_INFUSION_RESULT].[OBS_DEPT_ID]
			,(SELECT COUNT(*) FROM [CHARGE_MASTER_MODIFIER] WHERE [CHARGE_MASTER_MODIFIER].[CHARGE_MASTER_ID] = [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]) AS CHARGE_MASTER_MODIFIERS_COUNT
			,[CHART_INFUSION_RESULT].[ICD_10_DRUG_CATEGORY_ID]
			,[CHART_INFUSION_RESULT].[ICD_10_PCS_CODE]
			,[ICD_10_PCS_BODY_SYSTEM_CHARACTER]
			,IIF(1 = (SELECT TOP 1 1 FROM [CODER_QA_REPORT_EXCLUSION] ex  where ex.[SOURCE_RECORD_TABLE_NAME] = 'CHART_INFUSION_RESULT_HISTORY' AND [key_value_1] = [CHART_INFUSION_RESULT_ID]), 1, 0) AS EXCLUDE_FROM_CODER_QA_REPORT
			,cmd.[OBSERVATION_IND]
		FROM
			[CHART_INFUSION_RESULT_HISTORY] CHART_INFUSION_RESULT
			INNER JOIN [CHARGE_MASTER] ON [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID] = [CHARGE_MASTER].[CHARGE_MASTER_ID]
			INNER JOIN [CHARGE_MASTER_DEPARTMENT] cmd ON cmd.[CHARGE_MASTER_DEPT_ID] = [CHARGE_MASTER].[CHARGE_MASTER_DEPT_ID]
		WHERE
			[CHART_ID] = @ChartId;
	ELSE IF @Mode = 3
		INSERT INTO #TmpSourceTable
		SELECT 
			 [CHART_INFUSION_RESULT_ID]
			,[CHART_ID]
			,[UNITS]
			,[DATE_OF_SERVICE]
			,[CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]
			,[CHART_INFUSION_RESULT].[MODIFIERS]
			,[CHARGE_MASTER].[CPT_CODE]
			,[CHARGE_MASTER].[BILLING_CODE]
			,[CHARGE_MASTER].[DESCRIPTION]
			,[CHARGE_MASTER].[MODIFIER_REQUIRED]
			,[CHARGE_MASTER].[CHARGE_MASTER_CATEGORY_ID]
			,[CHART_INFUSION_RESULT].[OBS_DEPT_ID]
			,(SELECT COUNT(*) FROM [CHARGE_MASTER_MODIFIER] WHERE [CHARGE_MASTER_MODIFIER].[CHARGE_MASTER_ID] = [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]) AS CHARGE_MASTER_MODIFIERS_COUNT
			,[CHART_INFUSION_RESULT].[ICD_10_DRUG_CATEGORY_ID]
			,[CHART_INFUSION_RESULT].[ICD_10_PCS_CODE]
			,[ICD_10_PCS_BODY_SYSTEM_CHARACTER]
			,IIF(1 = (SELECT TOP 1 1 FROM [CODER_QA_REPORT_EXCLUSION] ex  where ex.[SOURCE_RECORD_TABLE_NAME] = 'CHART_INFUSION_RESULT_HISTORY' AND [key_value_1] = [CHART_INFUSION_RESULT_ID]), 1, 0) AS EXCLUDE_FROM_CODER_QA_REPORT
			,cmd.[OBSERVATION_IND]
		FROM
			[CHART_SECOND_AUDIT_INFUSION_RESULT_HISTORY] CHART_INFUSION_RESULT
			INNER JOIN [CHARGE_MASTER] ON [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID] = [CHARGE_MASTER].[CHARGE_MASTER_ID]
			INNER JOIN [CHARGE_MASTER_DEPARTMENT] cmd ON cmd.[CHARGE_MASTER_DEPT_ID] = [CHARGE_MASTER].[CHARGE_MASTER_DEPT_ID]
		WHERE
			[CHART_ID] = @ChartId;
	ELSE
		INSERT INTO #TmpSourceTable
		SELECT 
			 [CHART_INFUSION_RESULT_ID]
			,[CHART_ID]
			,[UNITS]
			,[DATE_OF_SERVICE]
			,[CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]
			,[CHART_INFUSION_RESULT].[MODIFIERS]
			,[CHARGE_MASTER].[CPT_CODE]
			,[CHARGE_MASTER].[BILLING_CODE]
			,[CHARGE_MASTER].[DESCRIPTION]
			,[CHARGE_MASTER].[MODIFIER_REQUIRED]
			,[CHARGE_MASTER].[CHARGE_MASTER_CATEGORY_ID]
			,[CHART_INFUSION_RESULT].[OBS_DEPT_ID]
			,(SELECT COUNT(*) FROM [CHARGE_MASTER_MODIFIER] WHERE [CHARGE_MASTER_MODIFIER].[CHARGE_MASTER_ID] = [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID]) AS CHARGE_MASTER_MODIFIERS_COUNT
			,[CHART_INFUSION_RESULT].[ICD_10_DRUG_CATEGORY_ID]
			,[CHART_INFUSION_RESULT].[ICD_10_PCS_CODE]
			,[ICD_10_PCS_BODY_SYSTEM_CHARACTER]
			,IIF(1 = (SELECT TOP 1 1 FROM [CODER_QA_REPORT_EXCLUSION] ex  where ex.[SOURCE_RECORD_TABLE_NAME] = 'CHART_INFUSION_RESULT' AND [key_value_1] = [CHART_INFUSION_RESULT_ID]), 1, 0) AS EXCLUDE_FROM_CODER_QA_REPORT
			,cmd.[OBSERVATION_IND]
		FROM
			[CHART_INFUSION_RESULT]
			INNER JOIN [CHARGE_MASTER] ON [CHART_INFUSION_RESULT].[CHARGE_MASTER_ID] = [CHARGE_MASTER].[CHARGE_MASTER_ID]
			INNER JOIN [CHARGE_MASTER_DEPARTMENT] cmd ON cmd.[CHARGE_MASTER_DEPT_ID] = [CHARGE_MASTER].[CHARGE_MASTER_DEPT_ID]
		WHERE
			[CHART_ID] = @ChartId;
		
	IF @ObservationIndicator = 2
		DELETE FROM #TmpSourceTable WHERE [OBSERVATION_IND] = 1;
	ELSE IF @ObservationIndicator = 3
		DELETE FROM #TmpSourceTable WHERE [OBSERVATION_IND] <> 1;

	SELECT 
		 [CHART_INFUSION_RESULT_ID]
		,[CHART_ID]
		,[UNITS]
		,[DATE_OF_SERVICE]
		,[CHARGE_MASTER_ID]
		,[MODIFIERS]
		,[CPT_CODE]
		,[BILLING_CODE]
		,[DESCRIPTION]
		,[MODIFIER_REQUIRED]
		,[CHARGE_MASTER_CATEGORY_ID]
		,[OBS_DEPT_ID]
		,[CHARGE_MASTER_MODIFIERS_COUNT]
		,[ICD_10_DRUG_CATEGORY_ID]
		,[ICD_10_PCS_CODE]
		,[ICD_10_PCS_BODY_SYSTEM_CHARACTER]
		,[EXCLUDE_FROM_CODER_QA_REPORT]
	FROM
		#TmpSourceTable tst;
END;
GO

