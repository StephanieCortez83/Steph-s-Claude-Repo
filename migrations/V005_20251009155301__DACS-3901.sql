CREATE OR ALTER PROCEDURE [dbo].[SelectUserGroupListByPortalReportId]
	@PortalReportId INT
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED; 

	SELECT 
		 [USER_GROUP].[USER_GROUP_ID]
		,[NAME]
		,[USER_ADMIN_CAN_ASSIGN]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[FORCE_CHART_SORT_BY_DOS]
		,[EXCLUDE_FROM_REPORTS_ALL_USER_GROUPS]
		-- 2025-10-08 - DACS-3901 - Commented this out to remove chart work queue feature - since is not being used anywhere
		--,[CHART_WORK_QUEUE_ID]
		,[IS_MFA_ENABLED]
		,[INCLUDE_IN_CHARTS_COMPLETED_BY_USER_GROUP_DROPDOWN]
		,[IS_LEGACY_LOGIN_ALLOWED]
	FROM
		[USER_GROUP]
	INNER JOIN [USER_GROUP_TO_PORTAL_REPORT]
			ON [USER_GROUP].[USER_GROUP_ID] = [USER_GROUP_TO_PORTAL_REPORT].[USER_GROUP_ID]
	WHERE
		[USER_GROUP_TO_PORTAL_REPORT].PORTAL_REPORT_ID = @PortalReportId;
END -- end SPROC
