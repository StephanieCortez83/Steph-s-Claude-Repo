CREATE OR ALTER PROCEDURE [dbo].[SELECT_USER_GROUP_BY_USER_GROUP_ID]
	@USER_GROUP_ID INT
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	SET NOCOUNT ON;
	
	SELECT
         [USER_GROUP_ID]
		,[NAME]
		,[USER_ADMIN_CAN_ASSIGN]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[FORCE_CHART_SORT_BY_DOS]
		,[EXCLUDE_FROM_REPORTS_ALL_USER_GROUPS]
		,[CHART_WORK_QUEUE_ID]
		,[IS_MFA_ENABLED]
		,[INCLUDE_IN_CHARTS_COMPLETED_BY_USER_GROUP_DROPDOWN]
		,[IS_LEGACY_LOGIN_ALLOWED]
	FROM	
		[dbo].[USER_GROUP] WITH (NOLOCK)
	WHERE 
		[USER_GROUP_ID] = @USER_GROUP_ID

	SET NOCOUNT OFF;
END;