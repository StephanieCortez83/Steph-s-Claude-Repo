CREATE OR ALTER PROCEDURE [dbo].[SelectUserGroupsByPortalDocumentId] 
	 @PortalDocumentId INT
AS
BEGIN
	SET NOCOUNT ON
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT
		 ug.[USER_GROUP_ID]
		,ug.[NAME]
		,ug.[USER_ADMIN_CAN_ASSIGN]
		,ug.[CREATION_DATE_TIME]
		,ug.[CREATING_USER_PROFILE_ID]
		,ug.[CHANGED_DATE_TIME]
		,ug.[CHANGING_USER_PROFILE_ID]
		,ug.[FORCE_CHART_SORT_BY_DOS]
		,ug.[EXCLUDE_FROM_REPORTS_ALL_USER_GROUPS]
		,[CHART_WORK_QUEUE_ID]
		,[IS_MFA_ENABLED]
		,ug.[INCLUDE_IN_CHARTS_COMPLETED_BY_USER_GROUP_DROPDOWN]
	FROM 
		[USER_GROUP] ug
		INNER JOIN [USER_GROUP_TO_PORTAL_DOCUMENT] u2 on ug.[USER_GROUP_ID] = u2.[USER_GROUP_ID]
	WHERE
		u2.[PORTAL_DOCUMENT_ID] = @PortalDocumentId;
END