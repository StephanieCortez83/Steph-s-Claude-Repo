CREATE PROC [dbo].[GET_ICD10_MAIN_TABLE_OF_DRUGS_FOR_LETTER]
(
	@root int
)
AS
BEGIN

	SELECT d.SEQ_NUMBER,  d.PARENT_SEQ_NUMBER, d.[LEVEL], d.TITLE, d.INDEX_LETTER_VALUE, d.SEE_DESCRIPTION, d.SEE_ALSO_DESCRIPTION, 
	d.NON_ESSENTIAL_MODIFIER_DESCRIPTION
	from ICD_10_TABLE_OF_DRUGS_AND_CHEMICALS d
	where d.INDEX_LETTER_VALUE = @root 

	order by d.TITLE
END

GO
