CREATE PROCEDURE [dbo].[PHYSICIAN_PROCEDURE_EVALUATION_SELECT_QUANTITY_BY_CPT_CODE_99217_AND_CHART_ID]
	 @CHART_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		QUANTITY 
	FROM 
		PHYSICIAN_PROCEDURE_EVALUATION WITH (NOLOCK)
	WHERE 
		(PHYSICIAN_PROCEDURE_EVALUATION.CHART_ID = @CHART_ID)
        AND PHYSICIAN_PROCEDURE_EVALUATION.PHYSICIAN_PROCEDURE_ID = 
			(SELECT 
				PHYSICIAN_PROCEDURE_EVALUATION.PHYSICIAN_PROCEDURE_ID 
			 FROM 
				PHYSICIAN_PROCEDURE_EVALUATION WITH (NOLOCK), CHARGE_MASTER WITH (NOLOCK)
			 WHERE
				(PHYSICIAN_PROCEDURE_EVALUATION.CHART_ID = @CHART_ID) 
				AND (CHARGE_MASTER.CHARGE_MASTER_ID = PHYSICIAN_PROCEDURE_EVALUATION.PHYSICIAN_PROCEDURE_ID)
                AND (CHARGE_MASTER.CHARGE_MASTER_USAGE_CODE <> 5) 
                AND (CHARGE_MASTER.CPT_CODE = '99217'))

GO
