	,[CEP_ORGANIZATION_USER_PROFILE].[CREATION_DATE_TIME]
	,[CEP_ORGANIZATION_USER_PROFILE].[CREATING_USER_PROFILE_ID]
	,[CEP_ORGANIZATION_USER_PROFILE].[CHANGED_DATE_TIME]
	,[CEP_ORGANIZATION_USER_PROFILE].[CHANGING_USER_PROFILE_ID]
