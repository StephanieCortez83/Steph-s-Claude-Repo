	 [CEP_ORGANIZATION_USER_PROFILE].[CEP_ORGANIZATION_USER_PROFILE_ID]
	,[CEP_ORGANIZATION_USER_PROFILE].[CEP_ORGANIZATION_ID]
	,[CEP_ORGANIZATION_USER_PROFILE].[USER_PROFILE_ID]
