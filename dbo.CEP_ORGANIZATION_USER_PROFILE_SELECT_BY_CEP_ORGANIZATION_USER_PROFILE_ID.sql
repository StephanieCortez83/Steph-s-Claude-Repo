	[dbo].[CEP_ORGANIZATION_USER_PROFILE]
WHERE
	[CEP_ORGANIZATION_USER_PROFILE].[CEP_ORGANIZATION_USER_PROFILE_ID] = @CEP_ORGANIZATION_USER_PROFILE_ID

