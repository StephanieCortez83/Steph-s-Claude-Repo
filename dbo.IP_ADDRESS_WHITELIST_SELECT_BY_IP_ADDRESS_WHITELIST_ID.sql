CREATE PROCEDURE [dbo].[IP_ADDRESS_WHITELIST_SELECT_BY_IP_ADDRESS_WHITELIST_ID]
	@IP_ADDRESS_WHITELIST_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [IP_ADDRESS_WHITELIST].[IP_ADDRESS_WHITELIST_ID]
	,[IP_ADDRESS_WHITELIST].[NAME]
	,[IP_ADDRESS_WHITELIST].[CREATION_DATE_TIME]
	,[IP_ADDRESS_WHITELIST].[CREATING_USER_PROFILE_ID]
	,[IP_ADDRESS_WHITELIST].[CHANGED_DATE_TIME]
	,[IP_ADDRESS_WHITELIST].[CHANGING_USER_PROFILE_ID]
