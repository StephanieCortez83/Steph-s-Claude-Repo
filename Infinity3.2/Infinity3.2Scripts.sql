CREATE OR ALTER PROCEDURE [dbo].[SelectAllReportNameFromUserGroupReportAccessByUserIdCsvList]
	@CsvListGroupIds varchar(4000)
AS
BEGIN
 
	SET NOCOUNT ON
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

