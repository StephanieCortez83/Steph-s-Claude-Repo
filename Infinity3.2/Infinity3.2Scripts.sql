	BEGIN
		SELECT Result = NULL;
		RETURN;
	END;
	
	DECLARE @dos datetime = getdate();
	
	-- load temp table with csv data
	DECLARE @tempUserGroupIds TABLE
	(
		UGID INT
	);

	INSERT @tempUserGroupIds(UGID)
