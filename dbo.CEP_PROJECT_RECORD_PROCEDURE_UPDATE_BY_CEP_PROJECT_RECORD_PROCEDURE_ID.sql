CREATE PROCEDURE [dbo].[CEP_PROJECT_RECORD_PROCEDURE_UPDATE_BY_CEP_PROJECT_RECORD_PROCEDURE_ID]
	 @CEP_PROJECT_RECORD_PROCEDURE_ID int
	,@CEP_PROJECT_RECORD_ID int
	,@CEP_PROJECT_ID int
	,@DATE_OF_SERVICE_START datetime
	,@DATE_OF_SERVICE_END datetime = NULL
	,@GLOBAL_PROCEDURE_CODE_TYPE_CODE tinyint
	,@GLOBAL_PROCEDURE_CODE_ID int
	,@UNITS int
	,@IS_DELETED bit
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
AS

UPDATE [dbo].[CEP_PROJECT_RECORD_PROCEDURE] SET
	 [CEP_PROJECT_RECORD_ID] = @CEP_PROJECT_RECORD_ID
	,[CEP_PROJECT_ID] = @CEP_PROJECT_ID
	,[DATE_OF_SERVICE_START] = @DATE_OF_SERVICE_START
	,[DATE_OF_SERVICE_END] = @DATE_OF_SERVICE_END
	,[GLOBAL_PROCEDURE_CODE_TYPE_CODE] = @GLOBAL_PROCEDURE_CODE_TYPE_CODE
	,[GLOBAL_PROCEDURE_CODE_ID] = @GLOBAL_PROCEDURE_CODE_ID
	,[UNITS] = @UNITS
	,[IS_DELETED] = @IS_DELETED
	,[CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
WHERE
	[CEP_PROJECT_RECORD_PROCEDURE_ID] = @CEP_PROJECT_RECORD_PROCEDURE_ID
GO
