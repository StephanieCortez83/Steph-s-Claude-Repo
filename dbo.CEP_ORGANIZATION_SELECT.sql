CREATE PROCEDURE [dbo].[CEP_ORGANIZATION_SELECT]
	 @PAGE_INDEX int = NULL
    ,@PAGE_SIZE int	= 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CEP_ORGANIZATION_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)

SET @sql = 'INSERT INTO #tmp (CEP_ORGANIZATION_ID) ' +
		   'SELECT [CEP_ORGANIZATION].[CEP_ORGANIZATION_ID] ' +
		   'FROM [CEP_ORGANIZATION] ' 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' WHERE (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CEP_ORGANIZATION].[ORGANIZATION_NAME]'

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX  + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CEP_ORGANIZATION].[CEP_ORGANIZATION_ID]
	,[CEP_ORGANIZATION].[ORGANIZATION_NAME]
	,[CEP_ORGANIZATION].[CEP_ORGANIZATION_TYPE_CODE]
	,[CEP_ORGANIZATION].[PRIMARY_CONTACT_FIRST_NAME]
	,[CEP_ORGANIZATION].[PRIMARY_CONTACT_LAST_NAME]
	,[CEP_ORGANIZATION].[PRIMARY_CONTACT_EMAIL_ADDRESS]
	,[CEP_ORGANIZATION].[CONTRACT_ESTIMATED_VOLUME]
	,[CEP_ORGANIZATION].[CEP_CONTRACT_ESTIMATED_VOLUME_TYPE_CODE]
	,[CEP_ORGANIZATION].[CREATION_DATE_TIME]
	,[CEP_ORGANIZATION].[CREATING_USER_PROFILE_ID]
	,[CEP_ORGANIZATION].[CHANGED_DATE_TIME]
	,[CEP_ORGANIZATION].[CHANGING_USER_PROFILE_ID]
FROM
	#tmp [tmp]
	INNER JOIN [CEP_ORGANIZATION] 
			ON [CEP_ORGANIZATION].[CEP_ORGANIZATION_ID] = [tmp].[CEP_ORGANIZATION_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]

GO
