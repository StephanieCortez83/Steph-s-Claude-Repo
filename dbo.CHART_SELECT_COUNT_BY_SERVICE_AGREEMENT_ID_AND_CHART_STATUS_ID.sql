CREATE PROCEDURE [dbo].[CHART_SELECT_COUNT_BY_SERVICE_AGREEMENT_ID_AND_CHART_STATUS_ID]
	  @SERVICE_AGREEMENT_ID int
	 ,@CHART_STATUS_1 int
	 ,@CHART_STATUS_2 int = -1
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

IF @CHART_STATUS_2 = -1
BEGIN

	SELECT 
		COUNT(*)
	FROM
		[dbo].[CHART] WITH (NOLOCK)
	WHERE
		([SERVICE_AGREEMENT_ID] = @SERVICE_AGREEMENT_ID)
		AND ([CHART_STATUS_ID] = @CHART_STATUS_1)

END
ELSE
BEGIN

	SELECT 
		COUNT(*)
	FROM
		[dbo].[CHART] WITH (NOLOCK)
	WHERE
		([SERVICE_AGREEMENT_ID] = @SERVICE_AGREEMENT_ID)
		AND ([CHART_STATUS_ID] IN (@CHART_STATUS_1,@CHART_STATUS_2))

END;

GO
