-- Description:	SQL for the Practice Chart List by Facility report (ACS-3063)
-- =============================================
CREATE PROCEDURE [dbo].[rpt_PracticeChartListByFacility]
	@Facility INT,
  @StartDate DATE,
  @EndDate DATE
AS
BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

    -- Insert statements for procedure here
  DECLARE @CPTCodes TABLE (CPT_CODE VARCHAR(5))
  DECLARE @ICD9Codes TABLE (ICD9_CODE VARCHAR(7))
  DECLARE @m_Facility INT = @Facility,
	  @m_StartDate DATE = @StartDate,
	  @m_EndDate DATE = @EndDate;

  -- Build the supporting tables
  INSERT INTO @CPTCodes (CPT_CODE)
  SELECT '99291'

  UNION

  SELECT '81002'

  UNION

  SELECT '81025'

  UNION

  SELECT '82270'

  UNION

  SELECT '82771'

  UNION

  SELECT '82272'

  UNION

  SELECT '82962'

  UNION

  SELECT '87804'

  UNION

  SELECT '87807'

  UNION

  SELECT '87880'

  UNION

  SELECT '93005'

  UNION

  SELECT '94640'

  UNION

  SELECT '31500'

  UNION

  SELECT '32551'

  UNION

  SELECT '32554'

  UNION

  SELECT '32555'

  UNION

  SELECT '33210'

  UNION

  SELECT '36430'

  UNION

  SELECT '92960'

  UNION

  SELECT '99149'

  UNION

  SELECT '62270'

  UNION

  SELECT '29105'

  UNION

  SELECT '29125'

  UNION

  SELECT 'SUPPL'

  UNION

  SELECT '10060'

  UNION

  SELECT '10061'

  INSERT INTO @ICD9Codes (ICD9_CODE)
  SELECT '959.01' ICD9_CODE_ID

  UNION

  SELECT DISTINCT ICD9_CODE_ID
  FROM CMS_ICD9_CODE WITH (NOLOCK)
  WHERE ICD9_CODE_ID LIKE '038.%'

  UNION

  SELECT DISTINCT ICD9_CODE_ID
  FROM CMS_ICD9_CODE WITH (NOLOCK)
  WHERE ICD9_CODE_ID BETWEEN '493.90' AND '493.92'

  UNION

  SELECT DISTINCT ICD9_CODE_ID
  FROM CMS_ICD9_CODE WITH (NOLOCK)
  WHERE ICD9_CODE_ID BETWEEN '800' AND '829'

  UNION

  SELECT DISTINCT ICD9_CODE_ID
  FROM CMS_ICD9_CODE WITH (NOLOCK)
  WHERE ICD9_CODE_ID BETWEEN '870' AND '897';

  -- Get a list of charts to report on
  WITH CHARTS
  AS (
	  SELECT CHART_ID,
		  FACILITY_CHART_ID,
		  TIME_OF_SERVICE,
		  PATIENT_LAST_NAME + ', ' + PATIENT_FIRST_NAME PATIENT_NAME
	  FROM CHART WITH (NOLOCK)
	  WHERE FACILITY_ID = @m_Facility
		  AND CHART_STATUS_ID IN (
			  3,
			  4,
			  5
			  )
		  AND DATEADD(DAY, DATEDIFF(DAY, 0, TIME_OF_SERVICE), 0) BETWEEN @m_StartDate AND @m_EndDate
		  AND EXISTS (
			  SELECT *
			  FROM PHYSICIAN_PROCEDURE_EVALUATION WITH (NOLOCK)
			  INNER JOIN CHARGE_MASTER WITH (NOLOCK) ON CHARGE_MASTER_ID = PHYSICIAN_PROCEDURE_ID
			  WHERE PHYSICIAN_PROCEDURE_EVALUATION.CHART_ID = CHART.CHART_ID
				  AND EXISTS (
					  SELECT *
					  FROM @CPTCodes
					  WHERE CPT_CODE = CHARGE_MASTER.CPT_CODE
					  )
			  )
	
	  UNION
	
	  SELECT CHART_ID,
		  FACILITY_CHART_ID,
		  TIME_OF_SERVICE,
		  PATIENT_LAST_NAME + ', ' + PATIENT_FIRST_NAME PATIENT_NAME
	  FROM CHART WITH (NOLOCK)
	  WHERE FACILITY_ID = @m_Facility
		  AND CHART_STATUS_ID IN (
			  3,
			  4,
			  5
			  )
		  AND DATEADD(DAY, DATEDIFF(DAY, 0, TIME_OF_SERVICE), 0) BETWEEN @m_StartDate AND @m_EndDate
		  AND EXISTS (
			  SELECT *
			  FROM FACILITY_PROCEDURE_EVALUATION WITH (NOLOCK)
			  INNER JOIN CHARGE_MASTER WITH (NOLOCK) ON CHARGE_MASTER_ID = FACILITY_PROCEDURE_ID
			  WHERE FACILITY_PROCEDURE_EVALUATION.CHART_ID = CHART.CHART_ID
				  AND EXISTS (
					  SELECT *
					  FROM @CPTCodes
					  WHERE CPT_CODE = CHARGE_MASTER.CPT_CODE
					  )
			  )
	
	  UNION
	
	  SELECT CHART_ID,
		  FACILITY_CHART_ID,
		  TIME_OF_SERVICE,
		  PATIENT_LAST_NAME + ', ' + PATIENT_FIRST_NAME PATIENT_NAME
	  FROM CHART WITH (NOLOCK)
	  WHERE FACILITY_ID = @m_Facility
		  AND CHART_STATUS_ID IN (
			  3,
			  4,
			  5
			  )
		  AND DATEADD(DAY, DATEDIFF(DAY, 0, TIME_OF_SERVICE), 0) BETWEEN @m_StartDate AND @m_EndDate
		  AND EXISTS (
			  SELECT *
			  FROM CHART_DIAGNOSIS_CODE WITH (NOLOCK)
			  WHERE CHART_ID = CHART.CHART_ID
				  AND EXISTS (
					  SELECT *
					  FROM @ICD9Codes
					  WHERE ICD9_CODE = CHART_DIAGNOSIS_CODE.ICD9_CODE
					  )
			  )
	  )

  -- Finally, add the CPT and Dx codes
  SELECT FACILITY_CHART_ID,
	  TIME_OF_SERVICE,
	  PATIENT_NAME,
	  (
		  STUFF((
				  SELECT ', ' + CPT_CODE
				  FROM (
					  SELECT CPT_CODE
					  FROM PHYSICIAN_PROCEDURE_EVALUATION WITH (NOLOCK)
					  INNER JOIN CHARGE_MASTER WITH (NOLOCK) ON CHARGE_MASTER_ID = PHYSICIAN_PROCEDURE_ID
					  WHERE PHYSICIAN_PROCEDURE_EVALUATION.CHART_ID = CHARTS.CHART_ID
					
					  UNION
					
					  SELECT CPT_CODE
					  FROM FACILITY_PROCEDURE_EVALUATION WITH (NOLOCK)
					  INNER JOIN CHARGE_MASTER WITH (NOLOCK) ON CHARGE_MASTER_ID = FACILITY_PROCEDURE_ID
					  WHERE FACILITY_PROCEDURE_EVALUATION.CHART_ID = CHARTS.CHART_ID
					  ) x
				  ORDER BY CPT_CODE
				  FOR XML PATH('')
				  ), 1, 2, '')
		  ) CPT_CODES,
	  (
		  STUFF((
				  SELECT ', ' + ICD9_CODE
				  FROM CHART_DIAGNOSIS_CODE WITH (NOLOCK)
				  WHERE CHART_ID = CHARTS.CHART_ID
				  ORDER BY POSTING_ORDER
				  FOR XML PATH('')
				  ), 1, 2, '')
		  ) ICD9_CODES
  FROM CHARTS
  ORDER BY FACILITY_CHART_ID
END
GO
GRANT EXECUTE ON  [dbo].[rpt_PracticeChartListByFacility] TO [dbx_ExecuteReportProcs]
GO
