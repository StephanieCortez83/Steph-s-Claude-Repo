CREATE PROCEDURE [dbo].[PHYSICIAN_PROCEDURE_EVALUATION_SELECT_BY_CHART_ID_SERVICE_AGREEMENT_ID_CHARGE_MASTER_USAGE_CODE_WITH_ORDER]
	 @CHART_ID int
	,@SERVICE_AGREEMENT_ID int
	,@DATE_OF_SERVICE datetime
	,@CHARGE_MASTER_USAGE_CODE int
	,@ORDER_DIRECTION varchar(20)		
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT
		CM.CHARGE_MASTER_ID
		,CM.CHARGE_MASTER_CATEGORY_ID
		,CM.DESCRIPTION
		,CM.LONG_DESCRIPTION
		,CM.CPT_CODE
		,CM.BILLING_CODE
		,CM.MODIFIER_REQUIRED
		,PPE.ICD9_CODE
		,PPE.ICD_10_CODE
		,PPE.PROCEDURE_DATE
		,CMC.DESCRIPTION
		,PPE.QUANTITY
		,PPE.MODIFIERS
		,PPE.PHYSICIAN_ID
		,PPE.INSUFFICIENT_DOCUMENTATION_TO_BILL
		,PPE.ADD_TO_FACILITY_PROCEDURE
		,CM.MAX_QUANTITY
		,CM.ALLOW_NEGATIVE_UNITS_IND
		,CM.CHARGE_MASTER_DEPT_ID
		,CASE ( SELECT count(*) FROM CODER_QA_REPORT_EXCLUSION ex 
				WHERE ex.SOURCE_RECORD_TABLE_NAME = 'PHYSICIAN_PROCEDURE_EVALUATION'
				AND (key_value_1 = CHART_ID) 
				AND (key_value_2 = CAST(PHYSICIAN_PROCEDURE_ID as varchar(15))) 
			)
			WHEN 0 THEN 0
			ELSE 1
			END
			as EXCLUDE_FROM_CODER_QA_REPORT
		,CAST(0 as bit) HAS_MODIFIERS
	FROM 
		CHARGE_MASTER CM WITH (NOLOCK)
		LEFT OUTER JOIN PHYSICIAN_PROCEDURE_EVALUATION PPE ON CM.CHARGE_MASTER_ID = PPE.PHYSICIAN_PROCEDURE_ID
			AND ((CHART_ID = @CHART_ID) OR (CHART_ID = null))
		,CHARGE_MASTER_CATEGORY CMC
	WHERE
		(CM.CHARGE_MASTER_CATEGORY_ID = CMC.CHARGE_MASTER_CATEGORY_ID)
		AND (CM.CHARGE_MASTER_USAGE_CODE = @CHARGE_MASTER_USAGE_CODE)
        AND (PPE.QUANTITY <> 0)
        AND (CM.EFFECTIVE_DATE <= @DATE_OF_SERVICE)
        AND (CM.EXPIRATION_DATE >= @DATE_OF_SERVICE)
        AND (CM.SERVICE_AGREEMENT_ID = @SERVICE_AGREEMENT_ID)
	--ORDER BY CMC.DESCRIPTION, CM.DISPLAY_SEQ,
	ORDER BY 
		CMC.DESCRIPTION, CM.DISPLAY_SEQ,
	 CASE UPPER(@ORDER_DIRECTION) WHEN 'DESC' THEN CM.CPT_CODE END DESC
	,CASE UPPER(@ORDER_DIRECTION) WHEN 'ASC' THEN CM.CPT_CODE END ASC
	,CASE UPPER(@ORDER_DIRECTION) WHEN '' THEN CM.CPT_CODE END ASC  ;
	
	
GO
