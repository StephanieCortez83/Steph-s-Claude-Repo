CREATE PROCEDURE [dbo].[rpt_ChartCodingDetail_Tuned]
	-- Add the parameters for the stored procedure here
	@ReportUser INT,
	@Facility VARCHAR(MAX),
	@DateType INT,
	@StartDate DATE,
	@EndDate DATE,
	@Coder VARCHAR(MAX),
	@Code INT = 0,
	@Status VARCHAR(MAX)
AS
BEGIN

	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

	-- Insert statements for procedure here
	DECLARE @m_ReportUser INT = @ReportUser,
		@m_Code AS INT = @Code,
		@m_Facility AS VARCHAR(MAX) = @Facility,
		@m_Status AS VARCHAR(MAX) = @Status,
		@m_Coder AS VARCHAR(MAX) = @Coder,
		@m_DateType AS INT = @DateType,
		@m_StartDate AS DATE = @StartDate,
		@m_EndDate AS DATE = @EndDate;


	if object_ID('TempDB..#ChartSubset', 'U') is not null DROP TABLE #ChartSubset;
	create table #ChartSubset
	(
		chart_ID	int	
		, facility_ID	int	
		, chart_status_ID	int	
		, approved_date	datetime	
		, sent_date	datetime	
		, SECOND_LEVEL_QA_APPROVED_DATETIME	datetime	
		, time_of_service	datetime	
		, facility_level_ID	int	
		, OVERRIDE_FACILITY_LEVEL_ID	int	
		, NON_ER_PROCEDURES_OVERRIDE	bit	
		, physician_service_proc_ID	int	
		, override_physician_service_proc_ID	int	
		, physician_service_mod	varchar(150)
		, patient_class_ID	int	
		, physician_history_ID	int	
		, chief_complaint	varchar(20)
		, primary_complaint	varchar(20)
		, COMPLETED_BY_USER_PROFILE_ID	int	
		, FACILITY_CHART_ID	varchar(50)
		, PATIENT_NAME	varchar(100)
		, DOS	datetime	
		, COMPLETION_DATE	datetime	
		, FACILITY varchar(100)
		, CODER varchar(100)
	)


	-- Although not ideal (in terms of code maintenance) to have separate INSERT queries here which are identical except for the date column used in 
	-- criteria for Start/End date, it improves performance by reducing logical reads nearly 80%.  The poorer performing alternative is using a 
	-- single query with a CASE statement for the criteria on Start/End date.
	IF @m_DateType = 3
	BEGIN
		INSERT INTO #ChartSubset
		SELECT 
			c.chart_ID, c.facility_ID, c.chart_status_ID, c.approved_date, c.sent_date, c.SECOND_LEVEL_QA_APPROVED_DATETIME,
			c.time_of_service, c.facility_level_ID, c.OVERRIDE_FACILITY_LEVEL_ID,
			c.NON_ER_PROCEDURES_OVERRIDE, c.physician_service_proc_ID, c.override_physician_service_proc_ID,
			c.physician_service_mod, c.patient_class_ID, c.physician_history_ID, c.chief_complaint, c.primary_complaint,
			c.COMPLETED_BY_USER_PROFILE_ID, c.FACILITY_CHART_ID, 
			c.PATIENT_LAST_NAME + ', ' + c.PATIENT_FIRST_NAME PATIENT_NAME,
			c.TIME_OF_SERVICE DOS, c.COMPLETION_DATE,
			f.Name FACILITY, 
			coder.LAST_NAME + ', ' + coder.FIRST_NAME CODER
		FROM CHART c WITH (NOLOCK)
			INNER JOIN FACILITY f WITH (NOLOCK) ON f.FACILITY_ID = c.FACILITY_ID
			INNER JOIN USER_PROFILE coder WITH (NOLOCK) ON coder.USER_PROFILE_ID = c.COMPLETED_BY_USER_PROFILE_ID
		WHERE 
			c.FACILITY_ID IN (Select Items From SPLITSTRING(@m_Facility, ','))
			AND c.CHART_STATUS_ID IN (Select Items From SPLITSTRING(@m_Status, ','))
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.COMPLETION_DATE), 0) BETWEEN @m_StartDate AND @m_EndDate		-- Use Completion_Date since @m_DateType = 3
			AND c.COMPLETED_BY_USER_PROFILE_ID IN (Select Items From SPLITSTRING(@m_Coder, ','))
			AND EXISTS (Select 1 From FACILITY_USER_AUTHORIZATION WITH (NOLOCK) Where USER_PROFILE_ID = @m_ReportUser And FACILITY_ID = c.FACILITY_ID)
	END;
	ELSE
	IF @m_DateType = 4
	BEGIN
		INSERT INTO #ChartSubset
		SELECT 
			c.chart_ID, c.facility_ID, c.chart_status_ID, c.approved_date, c.sent_date, c.SECOND_LEVEL_QA_APPROVED_DATETIME,
			c.time_of_service, c.facility_level_ID, c.OVERRIDE_FACILITY_LEVEL_ID,
			c.NON_ER_PROCEDURES_OVERRIDE, c.physician_service_proc_ID, c.override_physician_service_proc_ID,
			c.physician_service_mod, c.patient_class_ID, c.physician_history_ID, c.chief_complaint, c.primary_complaint,
			c.COMPLETED_BY_USER_PROFILE_ID, c.FACILITY_CHART_ID, 
			c.PATIENT_LAST_NAME + ', ' + c.PATIENT_FIRST_NAME PATIENT_NAME,
			c.TIME_OF_SERVICE DOS, c.COMPLETION_DATE,
			f.Name FACILITY, 
			coder.LAST_NAME + ', ' + coder.FIRST_NAME CODER
		FROM CHART c WITH (NOLOCK)
			INNER JOIN FACILITY f WITH (NOLOCK) ON f.FACILITY_ID = c.FACILITY_ID
			INNER JOIN USER_PROFILE coder WITH (NOLOCK) ON coder.USER_PROFILE_ID = c.COMPLETED_BY_USER_PROFILE_ID
		WHERE 
			c.FACILITY_ID IN (Select Items From SPLITSTRING(@m_Facility, ','))
			AND c.CHART_STATUS_ID IN (Select Items From SPLITSTRING(@m_Status, ','))
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.APPROVED_DATE), 0) BETWEEN @m_StartDate AND @m_EndDate		-- Use Approved_Date since @m_DateType = 4
			AND c.COMPLETED_BY_USER_PROFILE_ID IN (Select Items From SPLITSTRING(@m_Coder, ','))
			AND EXISTS (Select 1 From FACILITY_USER_AUTHORIZATION WITH (NOLOCK) Where USER_PROFILE_ID = @m_ReportUser And FACILITY_ID = c.FACILITY_ID)
	END;
	ELSE
	IF @m_DateType = 5
	BEGIN
		INSERT INTO #ChartSubset
		SELECT 
			c.chart_ID, c.facility_ID, c.chart_status_ID, c.approved_date, c.sent_date, c.SECOND_LEVEL_QA_APPROVED_DATETIME,
			c.time_of_service, c.facility_level_ID, c.OVERRIDE_FACILITY_LEVEL_ID,
			c.NON_ER_PROCEDURES_OVERRIDE, c.physician_service_proc_ID, c.override_physician_service_proc_ID,
			c.physician_service_mod, c.patient_class_ID, c.physician_history_ID, c.chief_complaint, c.primary_complaint,
			c.COMPLETED_BY_USER_PROFILE_ID, c.FACILITY_CHART_ID, 
			c.PATIENT_LAST_NAME + ', ' + c.PATIENT_FIRST_NAME PATIENT_NAME,
			c.TIME_OF_SERVICE DOS, c.COMPLETION_DATE,
			f.Name FACILITY, 
			coder.LAST_NAME + ', ' + coder.FIRST_NAME CODER
		FROM CHART c WITH (NOLOCK)
			INNER JOIN FACILITY f WITH (NOLOCK) ON f.FACILITY_ID = c.FACILITY_ID
			INNER JOIN USER_PROFILE coder WITH (NOLOCK) ON coder.USER_PROFILE_ID = c.COMPLETED_BY_USER_PROFILE_ID
		WHERE 
			c.FACILITY_ID IN (Select Items From SPLITSTRING(@m_Facility, ','))
			AND c.CHART_STATUS_ID IN (Select Items From SPLITSTRING(@m_Status, ','))
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.SENT_DATE), 0) BETWEEN @m_StartDate AND @m_EndDate		-- Use Sent_Date since @m_DateType = 5
			AND c.COMPLETED_BY_USER_PROFILE_ID IN (Select Items From SPLITSTRING(@m_Coder, ','))
			AND EXISTS (Select 1 From FACILITY_USER_AUTHORIZATION WITH (NOLOCK) Where USER_PROFILE_ID = @m_ReportUser And FACILITY_ID = c.FACILITY_ID)
	END;
	ELSE
	IF @m_DateType = 8
	BEGIN
		INSERT INTO #ChartSubset
		SELECT 
			c.chart_ID, c.facility_ID, c.chart_status_ID, c.approved_date, c.sent_date, c.SECOND_LEVEL_QA_APPROVED_DATETIME,
			c.time_of_service, c.facility_level_ID, c.OVERRIDE_FACILITY_LEVEL_ID,
			c.NON_ER_PROCEDURES_OVERRIDE, c.physician_service_proc_ID, c.override_physician_service_proc_ID,
			c.physician_service_mod, c.patient_class_ID, c.physician_history_ID, c.chief_complaint, c.primary_complaint,
			c.COMPLETED_BY_USER_PROFILE_ID, c.FACILITY_CHART_ID, 
			c.PATIENT_LAST_NAME + ', ' + c.PATIENT_FIRST_NAME PATIENT_NAME,
			c.TIME_OF_SERVICE DOS, c.COMPLETION_DATE,
			f.Name FACILITY, 
			coder.LAST_NAME + ', ' + coder.FIRST_NAME CODER
		FROM CHART c WITH (NOLOCK)
			INNER JOIN FACILITY f WITH (NOLOCK) ON f.FACILITY_ID = c.FACILITY_ID
			INNER JOIN USER_PROFILE coder WITH (NOLOCK) ON coder.USER_PROFILE_ID = c.COMPLETED_BY_USER_PROFILE_ID
		WHERE 
			c.FACILITY_ID IN (Select Items From SPLITSTRING(@m_Facility, ','))
			AND c.CHART_STATUS_ID IN (Select Items From SPLITSTRING(@m_Status, ','))
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.SECOND_LEVEL_QA_APPROVED_DATETIME), 0) BETWEEN @m_StartDate AND @m_EndDate		-- Use SECOND_LEVEL_QA_APPROVED_DATETIME since @m_DateType = 8
			AND c.COMPLETED_BY_USER_PROFILE_ID IN (Select Items From SPLITSTRING(@m_Coder, ','))
			AND EXISTS (Select 1 From FACILITY_USER_AUTHORIZATION WITH (NOLOCK) Where USER_PROFILE_ID = @m_ReportUser And FACILITY_ID = c.FACILITY_ID)
	END;
	ELSE
	BEGIN
		INSERT INTO #ChartSubset
		SELECT 
			c.chart_ID, c.facility_ID, c.chart_status_ID, c.approved_date, c.sent_date, c.SECOND_LEVEL_QA_APPROVED_DATETIME,
			c.time_of_service, c.facility_level_ID, c.OVERRIDE_FACILITY_LEVEL_ID,
			c.NON_ER_PROCEDURES_OVERRIDE, c.physician_service_proc_ID, c.override_physician_service_proc_ID,
			c.physician_service_mod, c.patient_class_ID, c.physician_history_ID, c.chief_complaint, c.primary_complaint,
			c.COMPLETED_BY_USER_PROFILE_ID, c.FACILITY_CHART_ID, 
			c.PATIENT_LAST_NAME + ', ' + c.PATIENT_FIRST_NAME PATIENT_NAME,
			c.TIME_OF_SERVICE DOS, c.COMPLETION_DATE,
			f.Name FACILITY, 
			coder.LAST_NAME + ', ' + coder.FIRST_NAME CODER
		FROM CHART c WITH (NOLOCK)
			INNER JOIN FACILITY f WITH (NOLOCK) ON f.FACILITY_ID = c.FACILITY_ID
			INNER JOIN USER_PROFILE coder WITH (NOLOCK) ON coder.USER_PROFILE_ID = c.COMPLETED_BY_USER_PROFILE_ID
		WHERE 
			c.FACILITY_ID IN (Select Items From SPLITSTRING(@m_Facility, ','))
			AND c.CHART_STATUS_ID IN (Select Items From SPLITSTRING(@m_Status, ','))
			AND DATEADD(DAY, DATEDIFF(DAY, 0, c.time_of_service), 0) BETWEEN @m_StartDate AND @m_EndDate		-- Use c.time_of_service since @m_DateType not in (3,4,5,8)
			AND c.COMPLETED_BY_USER_PROFILE_ID IN (Select Items From SPLITSTRING(@m_Coder, ','))
			AND EXISTS (Select 1 From FACILITY_USER_AUTHORIZATION WITH (NOLOCK) Where USER_PROFILE_ID = @m_ReportUser And FACILITY_ID = c.FACILITY_ID)
	END;


	SELECT 
		c.FACILITY,
		c.COMPLETED_BY_USER_PROFILE_ID,
		c.FACILITY_CHART_ID,
		c.PATIENT_NAME,
		c.TIME_OF_SERVICE DOS,
		c.CODER,
		c.COMPLETION_DATE,
		'Facility Level' [TYPE],
		'Points' [SUB_TYPE],
		NULL CODE,
		NULL MODIFIER,
		ISNULL(fssi.POINTS, fs.MAX_POINTS) UNITS,
		ISNULL(fssi.[DESCRIPTION], fs.[DESCRIPTION]) [DESCRIPTION],
		NULL [START_DATE],
		NULL [END_DATE],
		ISNULL(fssi.PRESENTATION_SEQUENCE, fs.SEQUENCE) SEQ,
		2 TYPE_SEQ,
		NULL DEPARTMENT
	FROM #ChartSubset c WITH (NOLOCK)
	INNER JOIN FACILITY_SERVICE_EVALUATION fse WITH (NOLOCK) ON fse.CHART_ID = c.CHART_ID
	LEFT JOIN FACILITY_SERVICE fs WITH (NOLOCK) ON fs.[FACILITY_SERVICE_ID] = fse.[FACILITY_SERVICE_ID]
	LEFT JOIN FACILITY_SERVICE_SCHEDULE_ITEM fssi WITH (NOLOCK) ON fssi.[FACILITY_SERVICE_SCHEDULE_ID] = fse.[FACILITY_SERVICE_SCHEDULE_ID]
		AND fssi.[FACILITY_SERVICE_SCHEDULE_ITEM_ID] = fse.[FACILITY_SERVICE_SCHEDULE_ITEM_ID]
	
	UNION
	
	SELECT 
		c.FACILITY,
		c.COMPLETED_BY_USER_PROFILE_ID,
		c.FACILITY_CHART_ID,
		c.PATIENT_NAME,
		c.TIME_OF_SERVICE DOS,
		c.coder,
		c.COMPLETION_DATE,
		'Facility Level' [TYPE],
		NULL [SUB_TYPE],
		CASE c.OVERRIDE_FACILITY_LEVEL_ID
			WHEN - 1
				THEN CASE @m_Code
						WHEN 0
							THEN fl.CPT_CODE
						ELSE fl.BILLING_CODE
						END
			ELSE CASE @m_Code
					WHEN 0
						THEN ofl.CPT_CODE
					ELSE ofl.BILLING_CODE
					END
			END [CODE],
		CASE 
			WHEN c.NON_ER_PROCEDURES_OVERRIDE = 1
				THEN '25'
			WHEN ISNULL(c.OVERRIDE_FACILITY_LEVEL_ID, -1) = -1
				THEN fl.MODIFIER
			ELSE ofl.MODIFIER
			END [MODIFIER],
		--CASE c.NON_ER_PROCEDURES_OVERRIDE
		--	WHEN 1
		--		THEN '25'
		--	ELSE NULL
		--	END [MODIFIER],
		NULL UNITS,
		CASE c.OVERRIDE_FACILITY_LEVEL_ID
			WHEN NULL
				THEN fl.[DESCRIPTION]
			WHEN - 1
				THEN fl.[DESCRIPTION]
			ELSE ofl.[DESCRIPTION]
			END [DESCRIPTION],
		NULL [START_DATE],
		NULL [END_DATE],
		1 SEQ,
		1 TYPE_SEQ,
		NULL DEPARTMENT
	FROM #ChartSubset c WITH (NOLOCK)
	INNER JOIN SERVICE_AGREEMENT sa WITH (NOLOCK) ON sa.FACILITY_ID = c.FACILITY_ID
	LEFT JOIN FACILITY_LEVEL fl WITH (NOLOCK) ON (fl.FACILITY_LEVEL_ID = c.FACILITY_LEVEL_ID)
	LEFT JOIN FACILITY_LEVEL ofl WITH (NOLOCK) ON (ofl.FACILITY_LEVEL_ID = c.OVERRIDE_FACILITY_LEVEL_ID)
	WHERE sa.EVALUATE_FACILITY_SVC = 1
	
	UNION
	
	SELECT 
		c.FACILITY,
		c.COMPLETED_BY_USER_PROFILE_ID,
		c.FACILITY_CHART_ID,
		c.PATIENT_NAME,
		c.TIME_OF_SERVICE DOS,
		c.CODER,
		c.COMPLETION_DATE,
		'Physician Level' [TYPE],
		NULL [SUB_TYPE],
		CASE c.OVERRIDE_PHYSICIAN_SERVICE_PROC_ID
			WHEN - 1
				THEN CASE @m_Code
						WHEN 0
							THEN psp.CPT_CODE
						ELSE psp.BILLING_CODE
						END
			ELSE CASE @m_Code
					WHEN 0
						THEN opsp.CPT_CODE
					ELSE opsp.BILLING_CODE
					END
			END [CODE],
		NULLIF(c.PHYSICIAN_SERVICE_MOD, '') MODIFIER,
		1 UNITS,
		CASE c.OVERRIDE_PHYSICIAN_SERVICE_PROC_ID
			WHEN - 1
				THEN psp.[DESCRIPTION]
			ELSE opsp.[DESCRIPTION]
			END [DESCRIPTION],
		NULL [START_DATE],
		NULL [END_DATE],
		1 SEQ,
		5 TYPE_SEQ,
		NULL DEPARTMENT
	FROM #ChartSubset c WITH (NOLOCK)
	INNER JOIN SERVICE_AGREEMENT sa WITH (NOLOCK) ON sa.FACILITY_ID = c.FACILITY_ID
	LEFT JOIN PHYSICIAN_SERVICE_PROCEDURE psp WITH (NOLOCK) ON (psp.PHYSICIAN_SERVICE_PROC_ID = c.PHYSICIAN_SERVICE_PROC_ID)
	LEFT JOIN PHYSICIAN_SERVICE_PROCEDURE opsp WITH (NOLOCK) ON (opsp.PHYSICIAN_SERVICE_PROC_ID = c.OVERRIDE_PHYSICIAN_SERVICE_PROC_ID)
	WHERE sa.EVALUATE_PHYSICIAN_SVC = 1
		AND (
			sa.CONDITION_PHYSICIAN_SERVICES_ON_DATE_OF_SERVICE = 0
			OR DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN sa.PHYSICIAN_PROCEDURES_START_DATE_OF_SERVICE AND sa.PHYSICIAN_SERVICES_END_DATE_OF_SERVICE
			)
	
	UNION
	
	SELECT 
		c.FACILITY,
		c.COMPLETED_BY_USER_PROFILE_ID,
		c.FACILITY_CHART_ID,
		c.PATIENT_NAME,
		c.TIME_OF_SERVICE DOS,
		c.CODER,
		c.COMPLETION_DATE,
		'Physician Level' [TYPE],
		'HPI' [SUB_TYPE],
		NULL [CODE],
		NULL MODIFIER,
		NULL UNITS,
		psrc.[DESCRIPTION],
		NULL [START_DATE],
		NULL [END_DATE],
		1 SEQ,
		5 TYPE_SEQ,
		NULL DEPARTMENT
	FROM #ChartSubset c WITH (NOLOCK)
	INNER JOIN SERVICE_AGREEMENT sa WITH (NOLOCK) ON sa.FACILITY_ID = c.FACILITY_ID
	INNER JOIN PATIENT_CLASS pc WITH (NOLOCK) ON pc.PATIENT_CLASS_ID = c.PATIENT_CLASS_ID
	LEFT JOIN PHYSICIAN_SERVICE_RATING_CODE psrc WITH (NOLOCK) ON psrc.PHYSICIAN_SERVICE_CATEGORY_RATING = c.PHYSICIAN_HISTORY_ID
		AND psrc.PHYSICIAN_SERVICE_CATEGORY_ID = 1
	LEFT JOIN CHART_PAYOR cp WITH (NOLOCK) ON cp.CHART_ID = c.CHART_ID
	WHERE psrc.PHYSICIAN_SERVICE_CLASS_CD = pc.[PHYSICIAN_SERVICE_CLASS_CD]
		AND DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN psrc.EFFECTIVE_DATE AND psrc.EXPIRATION_DATE
		AND ISNULL(cp.PHYSICIAN_SERVICE_GUIDELINE_ID, 1) = psrc.PHYSICIAN_SERVICE_GUIDELINE_ID
		AND sa.EVALUATE_PHYSICIAN_SVC = 1
		AND (
			sa.CONDITION_PHYSICIAN_SERVICES_ON_DATE_OF_SERVICE = 0
			OR DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN sa.PHYSICIAN_PROCEDURES_START_DATE_OF_SERVICE AND sa.PHYSICIAN_SERVICES_END_DATE_OF_SERVICE
			)
	
	UNION
	
	SELECT 
		c.FACILITY,
		c.COMPLETED_BY_USER_PROFILE_ID,
		c.FACILITY_CHART_ID,
		c.PATIENT_NAME,
		c.TIME_OF_SERVICE DOS,
		c.CODER,
		c.COMPLETION_DATE,
		'Physician Level' [TYPE],
		'Exam' [SUB_TYPE],
		NULL [CODE],
		NULL MODIFIER,
		NULL UNITS,
		psrc.[DESCRIPTION],
		NULL [START_DATE],
		NULL [END_DATE],
		2 SEQ,
		5 TYPE_SEQ,
		NULL DEPARTMENT
	FROM #ChartSubset c WITH (NOLOCK)
	INNER JOIN SERVICE_AGREEMENT sa WITH (NOLOCK) ON sa.FACILITY_ID = c.FACILITY_ID
	INNER JOIN PATIENT_CLASS pc WITH (NOLOCK) ON pc.PATIENT_CLASS_ID = c.PATIENT_CLASS_ID
	LEFT JOIN PHYSICIAN_SERVICE_RATING_CODE psrc WITH (NOLOCK) ON psrc.PHYSICIAN_SERVICE_CATEGORY_RATING = c.PHYSICIAN_HISTORY_ID
		AND psrc.PHYSICIAN_SERVICE_CATEGORY_ID = 2
	LEFT JOIN CHART_PAYOR cp WITH (NOLOCK) ON cp.CHART_ID = c.CHART_ID
	WHERE psrc.PHYSICIAN_SERVICE_CLASS_CD = pc.[PHYSICIAN_SERVICE_CLASS_CD]
		AND DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN psrc.EFFECTIVE_DATE AND psrc.EXPIRATION_DATE
		AND ISNULL(cp.PHYSICIAN_SERVICE_GUIDELINE_ID, 1) = psrc.PHYSICIAN_SERVICE_GUIDELINE_ID
		AND sa.EVALUATE_PHYSICIAN_SVC = 1
		AND (
			sa.CONDITION_PHYSICIAN_SERVICES_ON_DATE_OF_SERVICE = 0
			OR DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN sa.PHYSICIAN_PROCEDURES_START_DATE_OF_SERVICE AND sa.PHYSICIAN_SERVICES_END_DATE_OF_SERVICE
			)
	
	UNION
	
	SELECT 
		c.FACILITY,
		c.COMPLETED_BY_USER_PROFILE_ID,
		c.FACILITY_CHART_ID,
		c.PATIENT_NAME,
		c.TIME_OF_SERVICE DOS,
		c.CODER,
		c.COMPLETION_DATE,
		'Physician Level' [TYPE],
		'MDM' [SUB_TYPE],
		NULL [CODE],
		NULL MODIFIER,
		NULL UNITS,
		psrc.[DESCRIPTION],
		NULL [START_DATE],
		NULL [END_DATE],
		3 SEQ,
		5 TYPE_SEQ,
		NULL DEPARTMENT
	FROM #ChartSubset c WITH (NOLOCK)
	INNER JOIN SERVICE_AGREEMENT sa WITH (NOLOCK) ON sa.FACILITY_ID = c.FACILITY_ID
	INNER JOIN PATIENT_CLASS pc WITH (NOLOCK) ON pc.PATIENT_CLASS_ID = c.PATIENT_CLASS_ID
	LEFT JOIN PHYSICIAN_SERVICE_RATING_CODE psrc WITH (NOLOCK) ON psrc.PHYSICIAN_SERVICE_CATEGORY_RATING = c.PHYSICIAN_HISTORY_ID
		AND psrc.PHYSICIAN_SERVICE_CATEGORY_ID = 3
	LEFT JOIN CHART_PAYOR cp WITH (NOLOCK) ON cp.CHART_ID = c.CHART_ID
	WHERE psrc.PHYSICIAN_SERVICE_CLASS_CD = pc.[PHYSICIAN_SERVICE_CLASS_CD]
		AND DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN psrc.EFFECTIVE_DATE AND psrc.EXPIRATION_DATE
		AND ISNULL(cp.PHYSICIAN_SERVICE_GUIDELINE_ID, 1) = psrc.PHYSICIAN_SERVICE_GUIDELINE_ID
		AND sa.EVALUATE_PHYSICIAN_SVC = 1
		AND (
			sa.CONDITION_PHYSICIAN_SERVICES_ON_DATE_OF_SERVICE = 0
			OR DATEADD(DAY, DATEDIFF(DAY, 0, c.TIME_OF_SERVICE), 0) BETWEEN sa.PHYSICIAN_PROCEDURES_START_DATE_OF_SERVICE AND sa.PHYSICIAN_SERVICES_END_DATE_OF_SERVICE
			)
	
	UNION
	
	SELECT 
		c.FACILITY,
		c.COMPLETED_BY_USER_PROFILE_ID,
		c.FACILITY_CHART_ID,
		c.PATIENT_NAME,
		c.TIME_OF_SERVICE DOS,
		c.CODER,
		c.COMPLETION_DATE,
		'Facility Procedure' [TYPE],
		NULL [SUB_TYPE],
		CASE @m_Code
			WHEN 0
				THEN cm.CPT_CODE
			ELSE cm.BILLING_CODE
			END [CODE],
		NULLIF(fpe.MODIFIERS, '') MODIFIER,
		fpe.QUANTITY UNITS,
		cm.[DESCRIPTION],
		fpe.PROCEDURE_DATE [START_DATE],
		NULL [END_DATE],
		1 SEQ,
		6 TYPE_SEQ,
		CASE cmc.OBSERVATION_CATEGORY
