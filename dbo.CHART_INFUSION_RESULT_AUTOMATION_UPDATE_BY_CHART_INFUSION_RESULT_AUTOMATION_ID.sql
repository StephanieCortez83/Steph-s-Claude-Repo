	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@CHART_INFUSION_RESULT_ID int
	,@CHART_ID int
	,@UNITS int = NULL
	,@CHARGE_MASTER_ID int = NULL
	,@MODIFIERS varchar(500) = NULL
	,@CHART_INFUSION_ID int = NULL
	,@DATE_OF_SERVICE datetime = NULL
