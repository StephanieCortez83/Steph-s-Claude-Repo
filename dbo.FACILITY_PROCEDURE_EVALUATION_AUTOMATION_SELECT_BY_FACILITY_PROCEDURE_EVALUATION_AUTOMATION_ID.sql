	 [FACILITY_PROCEDURE_EVALUATION_AUTOMATION].[FACILITY_PROCEDURE_EVALUATION_AUTOMATION_ID]
	,[FACILITY_PROCEDURE_EVALUATION_AUTOMATION].[CREATION_DATE_TIME]
