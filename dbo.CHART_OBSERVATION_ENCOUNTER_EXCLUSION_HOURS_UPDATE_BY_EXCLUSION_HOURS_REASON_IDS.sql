CREATE PROCEDURE [dbo].[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS_UPDATE_BY_EXCLUSION_HOURS_REASON_IDS]
	 @OBSERVATION_EXCLUSION_HOURS_REASON_ID_EXISTING int
	,@OBSERVATION_EXCLUSION_HOURS_REASON_ID_REPLACEMENT int
	,@FACILITY_ID  int
	,@CHANGING_USER_PROFILE_ID int
	,@SHOW_STATS_ONLY bit = 1
	,@ROWS_AFFECTED int OUTPUT
	
AS

IF @OBSERVATION_EXCLUSION_HOURS_REASON_ID_REPLACEMENT <= 0
BEGIN
	PRINT('OBSERVATION_EXCLUSION_HOURS_REASON_ID_REPLACEMENT <= 0. Exiting');
	SET @ROWS_AFFECTED = 0;
	RETURN;
END;

-- Code copied from "Adding Obs Hour Exclusion Reasons for a Service Agreement.docx"
-- populate a temp table with the applicable CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS rows to update EXCLUSION_HOURS_REASON_ID
SET NOCOUNT OFF

IF OBJECT_ID('TempDB..#COEHRows', 'U') IS NOT NULL DROP TABLE [#COEHRows];

SELECT [CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS].[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS_ID]        
	INTO [#COEHRows]
		FROM 
			[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS] WITH (NOLOCK)
		WHERE 
			[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS].[CHART_ID] IN 
				(SELECT [CHART].[CHART_ID]
					FROM 
						[CHART] WITH (NOLOCK)
					WHERE 
						[CHART].[FACILITY_ID] = @FACILITY_ID
				)
			AND
				[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS].[EXCLUSION_HOURS_REASON_ID] = @OBSERVATION_EXCLUSION_HOURS_REASON_ID_EXISTING;

-- count the records in #COEHRows
--SELECT * FROM [#COEHRows]
DECLARE @ROW_COUNT_TO_PROCESS int;
SELECT @ROW_COUNT_TO_PROCESS = Count(*) FROM [#COEHRows];
PRINT('ROW_COUNT_TO_PROCESS = ' + CAST(@ROW_COUNT_TO_PROCESS AS VARCHAR(32)));

if @SHOW_STATS_ONLY = 1
BEGIN
	PRINT('OBSERVATION_EXCLUSION_HOURS_REASON_ID_EXISTING = ' + CAST(@OBSERVATION_EXCLUSION_HOURS_REASON_ID_EXISTING AS VARCHAR(32)));
	PRINT('OBSERVATION_EXCLUSION_HOURS_REASON_ID_REPLACEMENT = ' + CAST(@OBSERVATION_EXCLUSION_HOURS_REASON_ID_REPLACEMENT AS VARCHAR(32)));
	PRINT('FACILITY_ID = ' + CAST(@FACILITY_ID AS VARCHAR(32)));
	PRINT('CHANGING_USER_PROFILE_ID = ' + CAST(@CHANGING_USER_PROFILE_ID AS VARCHAR(32)));
	PRINT('SHOW_STATS_ONLY = ' + CAST(@SHOW_STATS_ONLY AS VARCHAR(32)));
	
	--SELECT COUNT(*) AS NUMBER FROM [#COEHRows];
	--SELECT * FROM [#COEHRows];
	RETURN;
END;

-- run a loop to update CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS rows
SET NOCOUNT ON
SET STATISTICS IO OFF

IF OBJECT_ID('TempDB..##Queue', 'U') IS NOT NULL DROP TABLE [##Queue]; 						-- use a global ## temp table so that progress can be monitored
SELECT [CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS_ID] INTO [##Queue] FROM [#COEHRows]; 	-- monitor progress by opening a new query and periodically running this:  SELECT count(*) FROM ##Queue

DECLARE @CoeehID int;
DECLARE @ROW_COUNT_PROCESSED int = 0;

WHILE EXISTS (SELECT 1 FROM ##Queue)
BEGIN
    SELECT TOP 1 @CoeehID = [CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS_ID] FROM [##Queue];
	BEGIN TRANSACTION;
		UPDATE [CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS]
		SET 
			[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS].[EXCLUSION_HOURS_REASON_ID] = @OBSERVATION_EXCLUSION_HOURS_REASON_ID_REPLACEMENT,
			[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS].[CHANGED_DATE_TIME] = GetDate(), 
			[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS].[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
		FROM 
			[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS]
			JOIN [#COEHRows] ON [CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS].[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS_ID] = [#COEHRows].[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS_ID]
		WHERE 
			[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS].[CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS_ID] = @CoeehID;

		DELETE FROM [##Queue] WHERE [CHART_OBSERVATION_ENCOUNTER_EXCLUSION_HOURS_ID] = @CoeehID;
		
		SET @ROW_COUNT_PROCESSED += 1;
		PRINT('Processed Row # ' + CAST(@ROW_COUNT_PROCESSED AS VARCHAR(32)) + ' of ' + CAST(@ROW_COUNT_TO_PROCESS AS VARCHAR(32)));
	COMMIT TRANSACTION;
END; 

PRINT('Total Rows Processed: ' + CAST(@ROW_COUNT_PROCESSED AS VARCHAR(32)) + ' of ' + CAST(@ROW_COUNT_TO_PROCESS AS VARCHAR(32)));
SET @ROWS_AFFECTED = @ROW_COUNT_PROCESSED;

GO
