CREATE   PROCEDURE [dbo].[FacilityChartArchiveGetChartMetadata] (@ChartList udt_int READONLY)
AS
	BEGIN
		SET NOCOUNT ON;

		SELECT	c.CHART_ID
			  , c.FACILITY_CHART_ID
			  , c.MEDICAL_RECORD_NUM
			  , c.PATIENT_TITLE
			  , c.PATIENT_FIRST_NAME
			  , c.PATIENT_MIDDLE_NAME
			  , c.PATIENT_LAST_NAME
			  , c.PATIENT_NAME_SUFFIX
			  , c.PATIENT_ADDR_LINE_1
			  , c.PATIENT_ADDR_LINE_2
			  , c.PATIENT_CITY
			  , c.PATIENT_STATE
			  , c.PATIENT_ZIPCODE
			  , c.PATIENT_DOB
			  , c.TIME_OF_SERVICE
			  , c.TIME_TO_ROOM
			  , c.TIME_OF_PHYS_EVAL
			  , c.TIME_OF_PHYS_DIS
			  , c.TIME_OF_TRIAGE
			  , c.TIME_OF_DIS
			  , triagenurse.TITLE				AS	TRIAGE_NURSE_TITLE
			  , triagenurse.FIRST_NAME			 AS TRIAGE_NURSE_FIRST_NAME
			  , triagenurse.MIDDLE_NAME			 AS TRIAGE_NURSE_MIDDLE_NAME
			  , triagenurse.LAST_NAME			 AS TRIAGE_NURSE_LAST_NAME
			  , triagenurse.NAME_SUFFIX			 AS TRIAGE_NURSE_NAME_SUFFIX
			  , dischargenurse.TITLE			 AS DHISCHARGE_NURSE_TITLE
			  , dischargenurse.FIRST_NAME		 AS DHISCHARGE_NURSE_FIRST_NAME
			  , dischargenurse.MIDDLE_NAME		 AS DHISCHARGE_NURSE_MIDDLE_NAME
			  , dischargenurse.LAST_NAME		 AS DHISCHARGE_NURSE_LAST_NAME
			  , dischargenurse.NAME_SUFFIX		 AS DHISCHARGE_NURSE_NAME_SUFFIX
			  , physician.TITLE					 AS PHYSICIAN_TITLE
			  , physician.FIRST_NAME			 AS PHYSICIAN_FIRST_NAME
			  , physician.MIDDLE_NAME			 AS PHYSICIAN_MIDDLE_NAME
			  , physician.LAST_NAME				 AS PHYSICIAN_LAST_NAME
			  , physician.NAME_SUFFIX			 AS PHYSICIAN_NAME_SUFFIX
			  , c.DATE_RECEIVED
			  , c.FACILITY_CRITICAL_CARE
			  , c.FACILITY_CRITICAL_CARE_MINUTES
			  , c.PHYSICIAN_CRITICAL_CARE
			  , c.PHYSICIAN_CRITICAL_CARE_MINUTES
			  , c.PHYSICIAN_SERVICE_OVERRIDE_MOD AS PHYSICIAN_SERVICE_OVERRIDE_MO
			  , pd.DESCRIPTION					 AS PATIENT_DISPOSITION
			  , fl.DESCRIPTION					 AS FACILITY_LEVEL_DESCRIPTION
			  , fl.CPT_CODE						 AS FACILITY_LEVEL_CPT
			  , fl.BILLING_CODE					 AS FACILITY_LEVEL_BILLING_CODE
			  , c.NON_ER_PROCEDURES_OVERRIDE
			  , c.PATIENT_DISPOSITION_ID
			  , c.COMPLETED_BY_USER_PROFILE_ID
			  , c.APPROVED_BY_USER_PROFILE_ID
			  , c.FACILITY_ADMIN_CHART_ID
		FROM	dbo.FacilityChartArchiveChartMetadata						c
				LEFT JOIN dbo.FacilityChartArchiveChartFacilityProfessionals triagenurse
					ON triagenurse.FACILITY_PROF_ID = c.TRIAGE_NURSE_ID
				LEFT JOIN dbo.FacilityChartArchiveChartFacilityProfessionals dischargenurse
					ON dischargenurse.FACILITY_PROF_ID = c.DIS_NURSE_ID
				LEFT JOIN dbo.FacilityChartArchiveChartFacilityProfessionals physician
					ON physician.FACILITY_PROF_ID = c.PHYSICIAN_ID
				LEFT JOIN dbo.PATIENT_DISPOSITION							pd WITH (NOLOCK)
					ON pd.PATIENT_DISPOSITION_ID = c.PATIENT_DISPOSITION_ID
				LEFT JOIN dbo.FACILITY_LEVEL								fl WITH (NOLOCK)
					ON fl.FACILITY_LEVEL_ID = c.FACILITY_LEVEL_ID
		WHERE	EXISTS (SELECT 1  FROM @ChartList  x WHERE x.x =  c.CHART_ID);
	END;
GO
