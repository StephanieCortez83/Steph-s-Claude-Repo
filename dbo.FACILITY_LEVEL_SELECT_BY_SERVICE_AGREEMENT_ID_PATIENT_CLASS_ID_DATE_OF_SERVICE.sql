--CREATE OR ALTER PROCEDURE [dbo].[FACILITY_LEVEL_SELECT_BY_SERVICE_AGREEMENT_ID_PATIENT_CLASS_ID_DATE_OF_SERVICE]
CREATE PROCEDURE [dbo].[FACILITY_LEVEL_SELECT_BY_SERVICE_AGREEMENT_ID_PATIENT_CLASS_ID_DATE_OF_SERVICE]
	@ServiceAgreementID INT
	,@PatientClassID INT
	,@DateOfService DATE
	,@Direction VARCHAR(4)
	,@SortOrder INT 
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	IF @Direction NOT IN ('ASC','DESC')
	BEGIN
		SET @Direction = 'ASC'
	END

	IF @SortOrder IN (2,3,4)
	BEGIN
		SELECT	[FACILITY_LEVEL_ID]
				,[SERVICE_AGREEMENT_ID]
				,[LEVEL_LOW]
				,[LEVEL_HIGH]
				,[DESCRIPTION]
				,[CPT_CODE]
				,[MODIFIER]
				,[PROCEDURES]
				,[BILLING_CODE]
				,[CRITICAL_CARE]
				,[PATIENT_CLASS_ID]
				,[REPORTING_COLUMN]
				,[LEVEL_NUMBER]
				,[DEPARTMENT]
				,[CREATION_DATE_TIME]
				,[CREATING_USER_PROFILE_ID]
				,[CHANGED_DATE_TIME]
				,[CHANGING_USER_PROFILE_ID]
				,[OVERRIDE_LIST_IND]
				,[EFFECTIVE_DATE]
				,[EXPIRATION_DATE]
		FROM	[dbo].[FACILITY_LEVEL]
		WHERE ((@ServiceAgreementID = 0) OR ([SERVICE_AGREEMENT_ID] = @ServiceAgreementID))
		AND   ((@PatientClassID = 0) OR ([PATIENT_CLASS_ID] = @PatientClassID))
		AND @DateOfService BETWEEN COALESCE([EFFECTIVE_DATE], '1/1/1753') AND COALESCE([EXPIRATION_DATE], '12/31/9999')
		ORDER BY CASE WHEN @Direction = 'ASC' THEN (CASE WHEN @SortOrder = 2 THEN [DESCRIPTION]  
													WHEN @SortOrder = 3 THEN [CPT_CODE] 
													WHEN @SortOrder = 4 THEN [BILLING_CODE]
													ELSE [DESCRIPTION] END )  END ,
				 CASE WHEN @Direction = 'DESC' THEN (CASE WHEN @SortOrder = 2 THEN [DESCRIPTION]
													WHEN @SortOrder = 3 THEN [CPT_CODE]
													WHEN @SortOrder = 4 THEN [BILLING_CODE]
													ELSE [DESCRIPTION] END )  END DESC
	END
	ELSE
    BEGIN
		SELECT	[FACILITY_LEVEL_ID]
				,[SERVICE_AGREEMENT_ID]
				,[LEVEL_LOW]
				,[LEVEL_HIGH]
				,[DESCRIPTION]
				,[CPT_CODE]
				,[MODIFIER]
				,[PROCEDURES]
				,[BILLING_CODE]
				,[CRITICAL_CARE]
				,[PATIENT_CLASS_ID]
				,[REPORTING_COLUMN]
				,[LEVEL_NUMBER]
				,[DEPARTMENT]
				,[CREATION_DATE_TIME]
				,[CREATING_USER_PROFILE_ID]
				,[CHANGED_DATE_TIME]
				,[CHANGING_USER_PROFILE_ID]
				,[OVERRIDE_LIST_IND]
				,[EFFECTIVE_DATE]
				,[EXPIRATION_DATE]
		FROM	[dbo].[FACILITY_LEVEL]
		WHERE ((@ServiceAgreementID = 0) OR ([SERVICE_AGREEMENT_ID] = @ServiceAgreementID))
		AND   ((@PatientClassID = 0) OR ([PATIENT_CLASS_ID] = @PatientClassID))
		AND   @DateOfService BETWEEN COALESCE([EFFECTIVE_DATE], '1/1/1753') AND COALESCE([EXPIRATION_DATE], '12/31/9999')
		ORDER BY CASE WHEN @Direction = 'ASC' THEN (CASE WHEN @SortOrder = 0 THEN [LEVEL_LOW] 
													WHEN @SortOrder = 1 THEN [LEVEL_HIGH]  
													ELSE [LEVEL_LOW] END )  END ,
				 CASE WHEN @Direction = 'DESC' THEN (CASE WHEN @SortOrder = 0 THEN [LEVEL_LOW] 
													WHEN @SortOrder = 1 THEN [LEVEL_HIGH]
													ELSE [LEVEL_LOW] END )  END DESC
	END 

END

GO
