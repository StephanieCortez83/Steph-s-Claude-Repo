CREATE PROCEDURE [dbo].[CHART_DIAGNOSIS_CODE_COMMENT_ICD10_SELECT_BY_CHART_DIAGNOSIS_CODE_COMMENT_ID]
	@CHART_DIAGNOSIS_CODE_COMMENT_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		 [CHART_DIAGNOSIS_CODE_COMMENT_ID]
		,[CHART_ID]
		,[COMMENTS]
		,[CHIEF_COMPLAINT_DOCUMENTATION_SCORE]
		,[PRIMARY_DX_DOCUMENTATION_SCORE]
        ,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
        ,[LEVEL_NUMBER]
	FROM 
		[dbo].[CHART_DIAGNOSIS_CODE_COMMENT_ICD10] with (NOLOCK)
    WHERE
        [CHART_DIAGNOSIS_CODE_COMMENT_ID] = @CHART_DIAGNOSIS_CODE_COMMENT_ID;
	
GO
