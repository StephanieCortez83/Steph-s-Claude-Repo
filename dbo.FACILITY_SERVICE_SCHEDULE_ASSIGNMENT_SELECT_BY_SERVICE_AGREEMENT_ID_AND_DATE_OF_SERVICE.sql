CREATE PROCEDURE [dbo].[FACILITY_SERVICE_SCHEDULE_ASSIGNMENT_SELECT_BY_SERVICE_AGREEMENT_ID_AND_DATE_OF_SERVICE]
	 @SERVICE_AGREEMENT_ID int
	,@DATE_OF_SERVICE DATETIME
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED


	SELECT 
		 [FACILITY_SERVICE_SCHEDULE_ASSIGNMENT].[FACILITY_SERVICE_SCHEDULE_ASSIGNMENT_ID]
		,[FACILITY_SERVICE_SCHEDULE_ASSIGNMENT].[SERVICE_AGREEMENT_ID]
		,[FACILITY_SERVICE_SCHEDULE_ASSIGNMENT].[FACILITY_SERVICE_SCHEDULE_ID]
		,[FACILITY_SERVICE_SCHEDULE_ASSIGNMENT].[EFFECTIVE_DATE]
		,[FACILITY_SERVICE_SCHEDULE_ASSIGNMENT].[EXPIRATION_DATE] 

	FROM 
		[dbo].[FACILITY_SERVICE_SCHEDULE_ASSIGNMENT] WITH (NOLOCK)
	WHERE
		([SERVICE_AGREEMENT_ID] = @SERVICE_AGREEMENT_ID)
		AND @DATE_OF_SERVICE BETWEEN DATEADD(DAY, DATEDIFF(DAY, 0, EFFECTIVE_DATE), 0) 
        AND ISNULL(DATEADD(DAY, DATEDIFF(DAY, 0, EXPIRATION_DATE), 0), @DATE_OF_SERVICE)
	
GO
