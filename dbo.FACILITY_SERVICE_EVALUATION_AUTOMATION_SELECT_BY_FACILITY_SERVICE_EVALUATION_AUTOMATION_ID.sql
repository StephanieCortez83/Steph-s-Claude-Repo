CREATE PROCEDURE [dbo].[FACILITY_SERVICE_EVALUATION_AUTOMATION_SELECT_BY_FACILITY_SERVICE_EVALUATION_AUTOMATION_ID]
	@FACILITY_SERVICE_EVALUATION_AUTOMATION_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [FACILITY_SERVICE_EVALUATION_AUTOMATION].[FACILITY_SERVICE_EVALUATION_AUTOMATION_ID]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[CREATION_DATE_TIME]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[CREATING_USER_PROFILE_ID]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[CHANGED_DATE_TIME]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[CHANGING_USER_PROFILE_ID]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[FACILITY_SERVICE_EVALUATION_ID]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[CHART_ID]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[FACILITY_SERVICE_ID]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[FACILITY_SERVICE_SCHEDULE_ID]
	,[FACILITY_SERVICE_EVALUATION_AUTOMATION].[FACILITY_SERVICE_SCHEDULE_ITEM_ID]
FROM
	[dbo].[FACILITY_SERVICE_EVALUATION_AUTOMATION]
WHERE
	[FACILITY_SERVICE_EVALUATION_AUTOMATION].[FACILITY_SERVICE_EVALUATION_AUTOMATION_ID] = @FACILITY_SERVICE_EVALUATION_AUTOMATION_ID

GO
