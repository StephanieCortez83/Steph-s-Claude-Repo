CREATE   PROC [dbo].[Maintenance_SelectIndexesForTablesbyTableName]  
	 @TableName VARCHAR(1024)
AS  
	-- Original implementation bt Mr. D. Sexton
	
	SET NOCOUNT ON
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	IF @TableName IS NULL OR LEN(@TableName) <= 0
	BEGIN
		SELECT 'Error' = -1, 'Message' = 'Error: TableName is invalid.';
		RETURN;
	END;

	PRINT('TableName = ' + @TableName);

	SELECT 
		  TABLENAME = T.NAME
		, INDEXNAME = I.NAME
		, COLUMNNAME = C.NAME
		, IC.KEY_ORDINAL
		, IC.IS_INCLUDED_COLUMN
		, IC.INDEX_COLUMN_ID
	FROM
		SYS.INDEXES AS I
		INNER JOIN SYS.INDEX_COLUMNS AS IC
			ON I.OBJECT_ID = IC.OBJECT_ID
			AND I.INDEX_ID = IC.INDEX_ID
		INNER JOIN SYS.COLUMNS AS C
			ON IC.OBJECT_ID = C.OBJECT_ID
			AND IC.COLUMN_ID = C.COLUMN_ID
		INNER JOIN SYS.TABLES AS T
			ON T.OBJECT_ID = C.OBJECT_ID
	WHERE 
		T.NAME = @TableName
	ORDER BY 
		INDEXNAME
		, CASE WHEN KEY_ORDINAL > 0 THEN KEY_ORDINAL ELSE 99 END

GO
