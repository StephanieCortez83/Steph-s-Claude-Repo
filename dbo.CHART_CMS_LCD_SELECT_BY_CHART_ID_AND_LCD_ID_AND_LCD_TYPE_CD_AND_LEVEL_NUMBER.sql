CREATE PROCEDURE [dbo].[CHART_CMS_LCD_SELECT_BY_CHART_ID_AND_LCD_ID_AND_LCD_TYPE_CD_AND_LEVEL_NUMBER]
	 @CHART_ID int
	,@LCD_ID int
	,@LCD_TYPE_CD [varchar](1)
	,@LEVEL_NUMBER int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		 [CHART_ID]
		,[LCD_ID]
		,[FAIL_EDIT_IND]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[LCD_TYPE_CD]
		,[LEVEL_NUMBER]
	FROM 
		[dbo].[CHART_CMS_LCD] with (NOLOCK)
    WHERE
        ([CHART_ID] = @CHART_ID)
        AND ([LCD_ID] = @LCD_ID)
        AND ([LEVEL_NUMBER] = @LEVEL_NUMBER)
        AND ([LCD_TYPE_CD] = @LCD_TYPE_CD);
	
GO
