CREATE PROC [dbo].[GET_ICD10_TABLE_OF_DRUGS_AND_CHEMICALS]
(
	@root int
)
AS
BEGIN
;With ret as (		
	SELECT d.SEQ_NUMBER,  d.PARENT_SEQ_NUMBER, d.[LEVEL], d.TITLE, d.INDEX_LETTER_VALUE, d.SEE_DESCRIPTION, d.SEE_ALSO_DESCRIPTION, 
	d.NON_ESSENTIAL_MODIFIER_DESCRIPTION
	from ICD_10_TABLE_OF_DRUGS_AND_CHEMICALS d
	where d.PARENT_SEQ_NUMBER = @root 
	UNION ALL
	SELECT d.SEQ_NUMBER,  d.PARENT_SEQ_NUMBER, d.[LEVEL], d.TITLE, d.INDEX_LETTER_VALUE,  d.SEE_DESCRIPTION, d.SEE_ALSO_DESCRIPTION, 
	 d.NON_ESSENTIAL_MODIFIER_DESCRIPTION
	from ICD_10_TABLE_OF_DRUGS_AND_CHEMICALS d
		INNER JOIN ret r on d.PARENT_SEQ_NUMBER = r.SEQ_NUMBER 
	)	
	
	select distinct * from ret	
	order by ret.title
END

GO
