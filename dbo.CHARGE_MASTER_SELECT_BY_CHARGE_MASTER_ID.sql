CREATE   PROCEDURE [dbo].[CHARGE_MASTER_SELECT_BY_CHARGE_MASTER_ID] 
	@CHARGE_MASTER_ID INT
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT	[CHARGE_MASTER_ID]
			,[SERVICE_AGREEMENT_ID]
			,[CHARGE_MASTER_CATEGORY_ID]
			,[DESCRIPTION]
			,[CPT_CODE]
			,[BILLING_CODE]
			,[ICD9_CODE]
			,[MODIFIER_REQUIRED]
			,[CHARGE_MASTER_DEPT_ID]
			,[CHARGE_MASTER_USAGE_CODE]
			,[EFFECTIVE_DATE]
			,[EXPIRATION_DATE]
			,[DISPLAY_SEQ]
			,[LONG_DESCRIPTION]
			,[MAX_QUANTITY]
			,[PATIENT_CLASS_ID]
			,[ALIAS_BILLING_CODE]
			,[CREATION_DATE_TIME]
			,[CREATING_USER_PROFILE_ID]
			,[CHANGED_DATE_TIME]
			,[CHANGING_USER_PROFILE_ID]
			,[BYPASS_AUTO_APPROVAL]
			,[OBSERVATION_PATIENT_ARRIVAL_SOURCE_ID]
			,[OBSERVATION_HOUR_TYPE_ID]
			,[OBSERVATION_TELEMETRY]
			,[ALLOW_NEGATIVE_UNITS_IND]
			,[SPECIAL_HANDLING_INSTRUCTIONS]
			,[AGE_MINIMUM]
			,[AGE_MAXIMUM]
	FROM	[dbo].[CHARGE_MASTER]
	WHERE [CHARGE_MASTER_ID] = @CHARGE_MASTER_ID
END;
GO
