CREATE PROCEDURE [dbo].[RPT_LIST_TIME_ZONES]
	@DST int		-- 1 = Daylight savings time entries; 0 = Standard
AS

--  Base script provided by SQL Team
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT 
	 [DESCRIPTION]
	,[REPORTING_DESCRIPTION]
FROM 
	[dbo].[TIME_ZONE] WITH (NOLOCK)
WHERE 
	(@DST=0 AND ([DESCRIPTION] LIKE '%Standard%')) 
	OR (@DST=1 AND ([DESCRIPTION] LIKE '%Daylight%'))
ORDER BY 
	[DESCRIPTION]  

GO
