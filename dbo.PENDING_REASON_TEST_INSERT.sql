CREATE PROCEDURE [dbo].[PENDING_REASON_TEST_INSERT]
	  @DESCRIPTION varchar(100)
	 ,@EXTENDED_DESCRIPTION varchar(4000)
	 ,@PENDING_REASON_REASON_ID int OUTPUT
AS

DECLARE @FOUND_PENDING_REASON_REASON_ID int;

SELECT @FOUND_PENDING_REASON_REASON_ID = [PENDING_REASON_ID]
	FROM
		[dbo].[PENDING_REASON] with (NOLOCK)
	WHERE
		([DESCRIPTION] = @DESCRIPTION);

if @FOUND_PENDING_REASON_REASON_ID is null
	BEGIN
		INSERT INTO [dbo].[PENDING_REASON]
		(
			 [DESCRIPTION]
			,[DEFAULT_PENDING_REASON_CATEGORY_ID]
			,[DEFAULT_RANK_VALUE]
			,[DEFICIENCY_CODE]
			,[EXTENDED_DESCRIPTION]
		)
		VALUES
		(
			 @DESCRIPTION
			,1
			,1		
			,null		
			,@EXTENDED_DESCRIPTION		
		)

		SET @PENDING_REASON_REASON_ID = @@IDENTITY
	END
ELSE
	BEGIN
		SET @PENDING_REASON_REASON_ID = -1
	END;

GO
