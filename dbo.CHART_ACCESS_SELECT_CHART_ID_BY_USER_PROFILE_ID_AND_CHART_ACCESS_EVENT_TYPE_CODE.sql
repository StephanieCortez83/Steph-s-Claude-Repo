CREATE PROCEDURE [dbo].[CHART_ACCESS_SELECT_CHART_ID_BY_USER_PROFILE_ID_AND_CHART_ACCESS_EVENT_TYPE_CODE]
    @USER_PROFILE_ID                INT
   ,@CHART_ACCESS_EVENT_TYPE_CODE   VARCHAR(1)
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT TOP 1 
    [CHART_ID]
FROM 
    [CHART_ACCESS] WITH(NOLOCK) 
WHERE 
    [USER_PROFILE_ID] = @USER_PROFILE_ID 
AND [CHART_ACCESS_EVENT_TYPE_CODE] = @CHART_ACCESS_EVENT_TYPE_CODE 
AND [CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE] IS NULL

GO
