CREATE PROCEDURE [dbo].[CHART_ACCESS_UPDATE_BY_USER_PROFILE_ID_AND_CHART_ID_AND_CHART_ACCESS_EVENT_TYPE_CODE]
    @USER_PROFILE_ID                        INT 
   ,@CHART_ID                               INT
   ,@CHART_ACCESS_EVENT_TYPE_CODE           VARCHAR(1)
   ,@CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE VARCHAR(1)
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

UPDATE 
    [CHART_ACCESS]
SET 
    [CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE] = @CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE
   ,[SECONDARY_EVENT_COMPLETION_DATE_TIME] = GETDATE() 
WHERE 
    [USER_PROFILE_ID] = @USER_PROFILE_ID 
AND [CHART_ID] = @CHART_ID 
AND [CHART_ACCESS_EVENT_TYPE_CODE] = @CHART_ACCESS_EVENT_TYPE_CODE 
AND [CHART_ACCESS_SECONDARY_EVENT_TYPE_CODE] IS NULL

GO
