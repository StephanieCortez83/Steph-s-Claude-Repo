CREATE PROCEDURE [dbo].[COMPANY_SELECT_COMPANY_ID_AND_NAME_BY_FACILITY_ID]
	@FACILITY_ID int
AS

--  Base script provided by SQL Team
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	COMPANY.COMPANY_ID, COMPANY.[NAME]
FROM 
	COMPANY WITH (NOLOCK)
	join SERVICE_AGREEMENT WITH (NOLOCK) on SERVICE_AGREEMENT.COMPANY_ID = COMPANY.COMPANY_ID
WHERE 
	SERVICE_AGREEMENT.FACILITY_ID = @FACILITY_ID;

GO
