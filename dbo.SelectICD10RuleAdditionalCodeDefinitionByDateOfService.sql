CREATE    PROC [dbo].[SelectICD10RuleAdditionalCodeDefinitionByDateOfService]    
 @DateOfService DATE    
WITH EXEC AS CALLER AS    
BEGIN    
 -- setup resources    
 SET NOCOUNT ON    
 SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED    
     
 SELECT     
    [ICD_10_RULE_EXTENSION_ID]  
  , [ADDITIONAL_CODE]    
  , [DESCRIPTION] + ' (' + [ADDITIONAL_CODE] + ')'    
  , (SELECT [dbo].GetLastICD10CodeForParent(REPLACE(ADDITIONAL_CODE, '-','')))    
  , SPECIAL_RULE_TYPE_CD  
 FROM     
  [dbo].[ICD_10_RULE_ADDITIONAL_CODE_DEFINITION] WITH (NOLOCK)    
  JOIN [dbo].[ICD_10_CODE_MASTER] WITH (NOLOCK)    
   ON REPLACE([ADDITIONAL_CODE], '-','') = [ICD_10_CODE]    
 WHERE    
  @DateOfService BETWEEN [EFFECTIVE_DT] AND [EXPIRATION_DT]  
END 
GO
