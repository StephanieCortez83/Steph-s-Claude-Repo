CREATE PROCEDURE [dbo].[FACILITY_SELECT_BY_HAS_CONFIDENTIALITYAGREEMENT]
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		 [FACILITY_ID]
		,[FACILITY_NUMBER]
		,[CLIENT_FACILITY_NUMBER]
		,[NAME]
		,[ADDR_LINE_1]
		,[ADDR_LINE_2]
		,[CITY]
		,[STATE]
		,[POSTAL_CODE]
		,[FEDERAL_TAX_ID]
		,[PRIMARY_CONTACT_TITLE]
		,[PRIMARY_CONTACT_FIRST_NAME]
		,[PRIMARY_CONTACT_MIDDLE_NAME]
		,[PRIMARY_CONTACT_LAST_NAME]
		,[PRIMARY_CONTACT_NAME_SUFFIX]
		,[PRIMARY_CONTACT_ADDR_LINE_1]
		,[PRIMARY_CONTACT_ADDR_LINE_2]
		,[PRIMARY_CONTACT_CITY]
		,[PRIMARY_CONTACT_STATE]
		,[PRIMARY_CONTACT_POSTAL_CODE]
        ,[PRIMARY_CONTACT_AREA_CODE]
		,[PRIMARY_CONTACT_PHONE_NUM]
		,[PRIMARY_CONTACT_PHONE_EXT]
		,[PRIMARY_CONTACT_FAX_AREA]
		,[PRIMARY_CONTACT_FAX_NUMBER]
        ,[PRIMARY_CONTACT_EMAIL]
		,[FISCAL_PERIOD_START_MONTH]
		,[CREATION_DATE_TIME]
		,[CREATING_USER_PROFILE_ID]
		,[CHANGED_DATE_TIME]
		,[CHANGING_USER_PROFILE_ID]
		,[ACCOUNTING_FACILITY_CODE]
		,[URGENT_CARE_CODE]
        ,[ABBREVIATED_NAME]
		,[ALTERNATE_FACILITY_NUMBER]
		,[REGION_ID]
	FROM 
		[dbo].[FACILITY] WITH (NOLOCK)
    WHERE ( SELECT 
				COUNT(*) 
		    FROM 
				 [dbo].[SERVICE_AGREEMENT_DOCUMENT] sd WITH (NOLOCK)
				,[dbo].[SERVICE_AGREEMENT] sa WITH (NOLOCK)
		    WHERE 
				(sd.SERVICE_AGREEMENT_ID = sa.SERVICE_AGREEMENT_ID)
				AND (sa.FACILITY_ID = facility.FACILITY_ID) 
				AND (sd.SERVICE_AGREEMENT_DOCUMENT_TYPE_ID = 1)
		  ) > 0;
	
GO
