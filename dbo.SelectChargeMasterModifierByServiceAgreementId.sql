CREATE   PROCEDURE [dbo].[SelectChargeMasterModifierByServiceAgreementId]
   @ServiceAgreementId INT  
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	SELECT 
		  CHARGE_MASTER_MODIFIER_ID
		, SERVICE_AGREEMENT_ID
		, CHARGE_MASTER_ID
		, MODIFIER
		, DESCRIPTION
		, BILLING_CODE
		, CREATION_DATE_TIME
		, CREATING_USER_PROFILE_ID
		, CHANGED_DATE_TIME
		, CHANGING_USER_PROFILE_ID
	FROM 
		[dbo].[CHARGE_MASTER_MODIFIER] WITH (NOLOCK)
	WHERE 
		[SERVICE_AGREEMENT_ID] = @ServiceAgreementId;

GO
