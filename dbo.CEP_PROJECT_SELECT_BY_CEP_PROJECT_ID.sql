CREATE PROCEDURE [dbo].[CEP_PROJECT_SELECT_BY_CEP_PROJECT_ID]
	@CEP_PROJECT_ID int
AS

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT
	 [CEP_PROJECT].[CEP_PROJECT_ID]
	,[CEP_PROJECT].[CEP_FACILITY_ID]
	,[CEP_PROJECT].[CEP_ORGANIZATION_ID]
	,[CEP_PROJECT].[CEP_PROJECT_TYPE_CODE]
	,[CEP_PROJECT].[PROJECT_NAME]
	,[CEP_PROJECT].[EFFECTIVE_DATE]
	,[CEP_PROJECT].[EXPIRATION_DATE]
	,[CEP_PROJECT].[CONTRACT_PRODUCTIVITY_REQUIREMENTS]
	,[CEP_PROJECT].[IS_DELETED]
	,[CEP_PROJECT].[CREATION_DATE_TIME]
	,[CEP_PROJECT].[CREATING_USER_PROFILE_ID]
	,[CEP_PROJECT].[CHANGED_DATE_TIME]
	,[CEP_PROJECT].[CHANGING_USER_PROFILE_ID]
FROM
	[dbo].[CEP_PROJECT]
WHERE
	[CEP_PROJECT].[CEP_PROJECT_ID] = @CEP_PROJECT_ID

GO
