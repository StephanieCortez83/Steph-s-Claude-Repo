CREATE   PROCEDURE [dbo].[FacilityChartArchiveStageFacilityLOS] (@UniqueID	 uniqueidentifier)
AS
	BEGIN
		SET NOCOUNT ON;


		SELECT c.CHART_ID,c.FACILITY_LEVEL_ID,c.SERVICE_AGREEMENT_ID,
	
		IIF(c.FACILITY_LOS_27_MODIFIER <> 0 AND c.FACILITY_LOS_27_MODIFIER IS NOT NULL,
				'27', '') +		
		IIF(c.FACILITY_LOS_32_MODIFIER <> 0 AND c.FACILITY_LOS_32_MODIFIER IS NOT NULL,
            IIF(
				 (c.FACILITY_LOS_27_MODIFIER = 0 OR c.FACILITY_LOS_27_MODIFIER IS NULL), '32', ',32'), '') +
		
		IIF(c.FACILITY_LOS_AF_MODIFIER <> 0 AND c.FACILITY_LOS_AF_MODIFIER IS NOT NULL,
			IIF(
				 (c.FACILITY_LOS_27_MODIFIER = 0 OR c.FACILITY_LOS_27_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_32_MODIFIER = 0 OR c.FACILITY_LOS_32_MODIFIER IS NULL), 'AF',',AF'), '') +
			 
		IIF(c.FACILITY_LOS_AG_MODIFIER <> 0 AND c.FACILITY_LOS_AG_MODIFIER IS NOT NULL,
			IIF(
				 (c.FACILITY_LOS_27_MODIFIER = 0 OR c.FACILITY_LOS_27_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_32_MODIFIER = 0 OR c.FACILITY_LOS_32_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_AF_MODIFIER = 0 OR c.FACILITY_LOS_AF_MODIFIER IS NULL), 'AG',',AG'), '') +				  
				  
		IIF(c.FACILITY_LOS_CS_MODIFIER <> 0 AND c.FACILITY_LOS_CS_MODIFIER IS NOT NULL,
			IIF(
				 (c.FACILITY_LOS_27_MODIFIER = 0 OR c.FACILITY_LOS_27_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_32_MODIFIER = 0 OR c.FACILITY_LOS_32_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_AF_MODIFIER = 0 OR c.FACILITY_LOS_AF_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_AG_MODIFIER = 0 OR c.FACILITY_LOS_AG_MODIFIER IS NULL), 'CS',',CS'), '') +
				  
		IIF(c.FACILITY_LOS_95_MODIFIER <> 0 AND c.FACILITY_LOS_95_MODIFIER IS NOT NULL,
			IIF(
				 (c.FACILITY_LOS_27_MODIFIER = 0 OR c.FACILITY_LOS_27_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_32_MODIFIER = 0 OR c.FACILITY_LOS_32_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_AF_MODIFIER = 0 OR c.FACILITY_LOS_AF_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_AG_MODIFIER = 0 OR c.FACILITY_LOS_AG_MODIFIER IS NULL)
				AND (c.FACILITY_LOS_CS_MODIFIER = 0 OR c.FACILITY_LOS_CS_MODIFIER IS NULL), '95',',95'), '')
		AS MODIFIER 
		INTO #t

		FROM dbo.FacilityChartArchiveStageCharts s 
		INNER JOIN dbo.FacilityChartArchiveItem i ON i.FacilityId = s.FacilityId AND i.ChartDOS BETWEEN s.DateFrom AND s.DateThru
		INNER JOIN dbo.FacilityChartArchiveChartMetadata c  ON c.CHART_ID=i.ChartId
		WHERE s.UniqueID=@UniqueID
		AND c.OVERRIDE_FACILITY_LEVEL_ID = -1;
		
		INSERT	dbo.FacilityChartArchiveChartFacilityLOS (CHART_ID
														, FACILITY_LEVEL_ID
														, MODIFIER
														, DESCRIPTION
														, CPT_CODE
														, BILLING_CODE
														, DEPARTMENT
														, QUANTITY)

		
				SELECT	ca.CHART_ID
					  , ca.FACILITY_LEVEL_ID
					  , ISNULL(IIF(fl.MODIFIER IS NULL,'',fl.MODIFIER+','+ca.MODIFIER),fl.MODIFIER)
					  , fl.DESCRIPTION
					  , fl.CPT_CODE
					  , fl.BILLING_CODE
					  , fl.DEPARTMENT
					  , 1 AS QUANTITY

		FROM	#t ca
				INNER JOIN FACILITY_LEVEL			  fl WITH (NOLOCK)
					ON ca.FACILITY_LEVEL_ID = fl.FACILITY_LEVEL_ID
					   AND ca.SERVICE_AGREEMENT_ID = fl.SERVICE_AGREEMENT_ID
		

	END;
GO
