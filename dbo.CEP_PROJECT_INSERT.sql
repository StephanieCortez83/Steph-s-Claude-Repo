CREATE PROCEDURE [dbo].[CEP_PROJECT_INSERT]
	 @CEP_FACILITY_ID int
	,@CEP_ORGANIZATION_ID int
	,@CEP_PROJECT_TYPE_CODE int
	,@PROJECT_NAME varchar(50)
	,@EFFECTIVE_DATE datetime
	,@EXPIRATION_DATE datetime = NULL
	,@CONTRACT_PRODUCTIVITY_REQUIREMENTS varchar(250) = NULL
	,@IS_DELETED bit
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@CEP_PROJECT_ID int OUTPUT
AS

INSERT INTO [dbo].[CEP_PROJECT]
(
	 [CEP_FACILITY_ID]
	,[CEP_ORGANIZATION_ID]
	,[CEP_PROJECT_TYPE_CODE]
	,[PROJECT_NAME]
	,[EFFECTIVE_DATE]
	,[EXPIRATION_DATE]
	,[CONTRACT_PRODUCTIVITY_REQUIREMENTS]
	,[IS_DELETED]
	,[CREATING_USER_PROFILE_ID]
	,[CHANGING_USER_PROFILE_ID]
)
VALUES
(
	 @CEP_FACILITY_ID
	,@CEP_ORGANIZATION_ID
	,@CEP_PROJECT_TYPE_CODE
	,@PROJECT_NAME
	,@EFFECTIVE_DATE
	,@EXPIRATION_DATE
	,@CONTRACT_PRODUCTIVITY_REQUIREMENTS
	,@IS_DELETED
	,@CREATING_USER_PROFILE_ID
	,@CHANGING_USER_PROFILE_ID 
)

SET @CEP_PROJECT_ID = @@IDENTITY

GO
