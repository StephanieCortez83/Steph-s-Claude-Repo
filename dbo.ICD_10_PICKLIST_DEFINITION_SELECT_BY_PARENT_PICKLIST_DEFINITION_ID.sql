CREATE PROCEDURE [dbo].[ICD_10_PICKLIST_DEFINITION_SELECT_BY_PARENT_PICKLIST_DEFINITION_ID]
				@PARENT_PICKLIST_ID INT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

SELECT 
    [ICD_10_PICKLIST_DEFINITION_ID]
   ,[PARENT_PICKLIST_DEFINITION_ID]
   ,[PICKLIST_DESCRIPTION]
   ,[PICKLIST_LEVEL]
   ,[ICD_10_CODE]
   ,[CREATION_DTTM]
   ,[CREATED_BY_USER_ID]
   ,[UPDATE_DTTM]
   ,[UPDATED_BY_USER_ID]
FROM   
    [dbo].[ICD_10_PICKLIST_DEFINITION]
WHERE  
    [PARENT_PICKLIST_DEFINITION_ID] = @PARENT_PICKLIST_ID
ORDER BY 
    [PICKLIST_DESCRIPTION]

GO
