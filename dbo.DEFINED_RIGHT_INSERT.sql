CREATE PROCEDURE [dbo].[DEFINED_RIGHT_INSERT]
	 @NAME varchar(50) = NULL
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@ALLOW_INHERITANCE bit = NULL
	,@DEFINITION varchar(2000) = NULL
	,@IS_ADMIN bit
	,@DEFINED_RIGHT_ID int OUTPUT
AS

INSERT INTO [dbo].[DEFINED_RIGHT]
(
	 [NAME]
	,[CREATING_USER_PROFILE_ID]
	,[CHANGING_USER_PROFILE_ID]
	,[ALLOW_INHERITANCE]
	,[DEFINITION]
	,[IS_ADMIN]
)
VALUES
(
	 @NAME
	,@CREATING_USER_PROFILE_ID
	,@CHANGING_USER_PROFILE_ID
	,@ALLOW_INHERITANCE
	,@DEFINITION
	,@IS_ADMIN 
)

SET @DEFINED_RIGHT_ID = @@IDENTITY

GO
