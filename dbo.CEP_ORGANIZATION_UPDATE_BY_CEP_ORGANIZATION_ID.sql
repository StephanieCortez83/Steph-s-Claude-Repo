CREATE PROCEDURE [dbo].[CEP_ORGANIZATION_UPDATE_BY_CEP_ORGANIZATION_ID]
	 @CEP_ORGANIZATION_ID int
	,@ORGANIZATION_NAME varchar(50)
	,@CEP_ORGANIZATION_TYPE_CODE int
	,@PRIMARY_CONTACT_FIRST_NAME varchar(50)
	,@PRIMARY_CONTACT_LAST_NAME varchar(50)
	,@PRIMARY_CONTACT_EMAIL_ADDRESS varchar(50)
	,@CONTRACT_ESTIMATED_VOLUME int = NULL
	,@CEP_CONTRACT_ESTIMATED_VOLUME_TYPE_CODE int = NULL
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
AS

UPDATE [dbo].[CEP_ORGANIZATION] SET
	 [ORGANIZATION_NAME] = @ORGANIZATION_NAME
	,[CEP_ORGANIZATION_TYPE_CODE] = @CEP_ORGANIZATION_TYPE_CODE
	,[PRIMARY_CONTACT_FIRST_NAME] = @PRIMARY_CONTACT_FIRST_NAME
	,[PRIMARY_CONTACT_LAST_NAME] = @PRIMARY_CONTACT_LAST_NAME
	,[PRIMARY_CONTACT_EMAIL_ADDRESS] = @PRIMARY_CONTACT_EMAIL_ADDRESS
	,[CONTRACT_ESTIMATED_VOLUME] = @CONTRACT_ESTIMATED_VOLUME
	,[CEP_CONTRACT_ESTIMATED_VOLUME_TYPE_CODE] = @CEP_CONTRACT_ESTIMATED_VOLUME_TYPE_CODE
	,[CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
WHERE
	[CEP_ORGANIZATION_ID] = @CEP_ORGANIZATION_ID
GO
