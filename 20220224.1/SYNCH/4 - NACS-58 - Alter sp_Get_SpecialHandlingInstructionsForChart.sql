ALTER PROCEDURE [dbo].[sp_Get_SpecialHandlingInstructionsForChart]
  @ChartId INT
AS
BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

  -- Insert statements for procedure here
  DECLARE @m_ChartId INT = @ChartId;

  SELECT DISTINCT CPT_CODE, SPECIAL_HANDLING_INSTRUCTIONS
  FROM CHART
  JOIN FACILITY_PROCEDURE_EVALUATION ON FACILITY_PROCEDURE_EVALUATION.CHART_ID = CHART.CHART_ID
  JOIN CHARGE_MASTER ON CHARGE_MASTER_ID = FACILITY_PROCEDURE_EVALUATION.FACILITY_PROCEDURE_ID
  WHERE CHART.CHART_ID = @m_ChartId
    AND NULLIF(SPECIAL_HANDLING_INSTRUCTIONS, LTRIM(RTRIM(''))) IS NOT NULL

  UNION

  SELECT DISTINCT CPT_CODE, SPECIAL_HANDLING_INSTRUCTIONS
  FROM CHART
  JOIN PHYSICIAN_PROCEDURE_EVALUATION ON PHYSICIAN_PROCEDURE_EVALUATION.CHART_ID = CHART.CHART_ID
  JOIN CHARGE_MASTER ON CHARGE_MASTER_ID = PHYSICIAN_PROCEDURE_EVALUATION.PHYSICIAN_PROCEDURE_ID
  WHERE CHART.CHART_ID = @m_ChartId
    AND NULLIF(SPECIAL_HANDLING_INSTRUCTIONS, LTRIM(RTRIM(''))) IS NOT NULL

 UNION

  SELECT DISTINCT CPT_CODE, SPECIAL_HANDLING_INSTRUCTIONS
  FROM CHART
  JOIN CHART_INFUSION_RESULT ON CHART_INFUSION_RESULT.CHART_ID = CHART.CHART_ID
  JOIN CHARGE_MASTER ON CHARGE_MASTER.CHARGE_MASTER_ID = CHART_INFUSION_RESULT.CHARGE_MASTER_ID
  WHERE CHART.CHART_ID = @m_ChartId
    AND NULLIF(SPECIAL_HANDLING_INSTRUCTIONS, LTRIM(RTRIM(''))) IS NOT NULL

 UNION

  SELECT DISTINCT FACILITY_LEVEL.CPT_CODE, SPECIAL_HANDLING_INSTRUCTIONS
  FROM CHART
  JOIN FACILITY_LEVEL ON FACILITY_LEVEL.SERVICE_AGREEMENT_ID = CHART.SERVICE_AGREEMENT_ID
		AND FACILITY_LEVEL.FACILITY_LEVEL_ID = (Case When CHART.OVERRIDE_FACILITY_LEVEL_ID > -1 Then CHART.OVERRIDE_FACILITY_LEVEL_ID Else CHART.FACILITY_LEVEL_ID End)
  JOIN CHARGE_MASTER ON CHARGE_MASTER.SERVICE_AGREEMENT_ID = FACILITY_LEVEL.SERVICE_AGREEMENT_ID
		AND CHARGE_MASTER.CPT_CODE = FACILITY_LEVEL.CPT_CODE
		AND CHARGE_MASTER.BILLING_CODE = FACILITY_LEVEL.BILLING_CODE
		AND (CHARGE_MASTER.PATIENT_CLASS_ID = FACILITY_LEVEL.PATIENT_CLASS_ID OR CHARGE_MASTER.PATIENT_CLASS_ID = -1)
  WHERE CHART.CHART_ID = @m_ChartId
		AND NULLIF(SPECIAL_HANDLING_INSTRUCTIONS, LTRIM(RTRIM(''))) IS NOT NULL

 UNION

  SELECT DISTINCT PHYSICIAN_SERVICE_PROCEDURE.CPT_CODE, SPECIAL_HANDLING_INSTRUCTIONS
  FROM CHART
  JOIN PHYSICIAN_SERVICE_PROCEDURE ON PHYSICIAN_SERVICE_PROCEDURE.SERVICE_AGREEMENT_ID = CHART.SERVICE_AGREEMENT_ID
		AND PHYSICIAN_SERVICE_PROCEDURE.PHYSICIAN_SERVICE_PROC_ID = (Case When CHART.OVERRIDE_PHYSICIAN_SERVICE_PROC_ID > -1 Then CHART.OVERRIDE_PHYSICIAN_SERVICE_PROC_ID Else CHART.PHYSICIAN_SERVICE_PROC_ID End)
  JOIN CHARGE_MASTER ON CHARGE_MASTER.SERVICE_AGREEMENT_ID = PHYSICIAN_SERVICE_PROCEDURE.SERVICE_AGREEMENT_ID
		AND CHARGE_MASTER.CPT_CODE = PHYSICIAN_SERVICE_PROCEDURE.CPT_CODE
		AND CHARGE_MASTER.BILLING_CODE = PHYSICIAN_SERVICE_PROCEDURE.BILLING_CODE
		AND (CHARGE_MASTER.PATIENT_CLASS_ID = PHYSICIAN_SERVICE_PROCEDURE.PATIENT_CLASS_ID OR CHARGE_MASTER.PATIENT_CLASS_ID = -1)
  WHERE CHART.CHART_ID = @m_ChartId
		AND NULLIF(SPECIAL_HANDLING_INSTRUCTIONS, LTRIM(RTRIM(''))) IS NOT NULL

  ORDER BY CPT_CODE
END