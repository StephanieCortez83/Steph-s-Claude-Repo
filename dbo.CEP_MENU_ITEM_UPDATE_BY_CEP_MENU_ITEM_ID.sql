CREATE PROCEDURE [dbo].[CEP_MENU_ITEM_UPDATE_BY_CEP_MENU_ITEM_ID]
	 @CEP_MENU_ITEM_ID int
	,@PARENT_CEP_MENU_ITEM_ID int = NULL
	,@CEP_MENU_ITEM_TYPE_CODE int
	,@ORDINAL tinyint
	,@LABEL varchar(100)
	,@HELP_TEXT varchar(500) = NULL
	,@PAGE_URL varchar(500) = NULL
	,@ICON_URL varchar(500) = NULL
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
AS

UPDATE [dbo].[CEP_MENU_ITEM] SET
	 [PARENT_CEP_MENU_ITEM_ID] = @PARENT_CEP_MENU_ITEM_ID
	,[CEP_MENU_ITEM_TYPE_CODE] = @CEP_MENU_ITEM_TYPE_CODE
	,[ORDINAL] = @ORDINAL
	,[LABEL] = @LABEL
	,[HELP_TEXT] = @HELP_TEXT
	,[PAGE_URL] = @PAGE_URL
	,[ICON_URL] = @ICON_URL
	,[CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
WHERE
	[CEP_MENU_ITEM_ID] = @CEP_MENU_ITEM_ID
GO
