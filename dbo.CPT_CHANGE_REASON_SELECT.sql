CREATE   -- comment out this line if DB version does not support
 PROCEDURE [dbo].[CPT_CHANGE_REASON_SELECT]
	 @PAGE_INDEX int = NULL
    ,@PAGE_SIZE int = 25
    ,@WHERE_CLAUSE varchar(1000) = NULL
    ,@ORDER_BY_CLAUSE varchar(250) = NULL
    ,@RECORD_COUNT int OUTPUT
AS

SET NOCOUNT ON
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

--[ID LIST]------------------------------------------------------

CREATE TABLE #tmp
(
	[INDEX_ID] int IDENTITY (1, 1) NOT NULL,
	[CPT_CHANGE_REASON_ID] int NOT NULL
)

DECLARE @sql nvarchar(2000)

SET @sql = 'INSERT INTO #tmp (CPT_CHANGE_REASON_ID) ' +
		   'SELECT [CPT_CHANGE_REASON_ID] ' +
		   'FROM [CPT_CHANGE_REASON] ' 

IF @WHERE_CLAUSE IS NOT NULL AND LEN(@WHERE_CLAUSE) > 0
	SET @sql = @sql + ' WHERE (' + @WHERE_CLAUSE + ') '

IF @ORDER_BY_CLAUSE IS NOT NULL AND LEN(@ORDER_BY_CLAUSE) > 0
	SET @sql = @sql + 'ORDER BY ' + @ORDER_BY_CLAUSE + ' '
ELSE
	SET @sql = @sql + 'ORDER BY [CPT_CHANGE_REASON].[DateTimeCreated]'

EXEC sp_executesql @sql

--[RANGE]----------------------------------------------------------

SELECT @RECORD_COUNT = @@ROWCOUNT

DECLARE @FIRST_RECORD int
DECLARE @LAST_RECORD  int

IF @PAGE_INDEX IS NOT NULL
BEGIN
	SET @FIRST_RECORD = (@PAGE_INDEX * @PAGE_SIZE) + 1
	SET @LAST_RECORD  = (@PAGE_INDEX + 1) * @PAGE_SIZE
END
ELSE
BEGIN
	SET @FIRST_RECORD = 1
	SET @LAST_RECORD  = @RECORD_COUNT
END

--[DATA]------------------------------------------------------------

SELECT
	 [CPT_CHANGE_REASON].[CPT_CHANGE_REASON_ID]
	,[CPT_CHANGE_REASON].[DISPLAY_NAME]
	,[CPT_CHANGE_REASON].[DESCRIPTION]
	,[CPT_CHANGE_REASON].[CREATION_DATE_TIME]
	,[CPT_CHANGE_REASON].[CREATING_USER_PROFILE_ID]
	,[CPT_CHANGE_REASON].[CHANGED_DATE_TIME]
	,[CPT_CHANGE_REASON].[CHANGING_USER_PROFILE_ID]
	,[CPT_CHANGE_REASON].[SERVICE_AGREEMENT_ID]
	,[CPT_CHANGE_REASON].[EFFECTIVE_DATE]
	,[CPT_CHANGE_REASON].[EXPIRATION_DATE]
FROM
	#tmp [tmp]
	INNER JOIN [CPT_CHANGE_REASON] 
			ON [CPT_CHANGE_REASON].[CPT_CHANGE_REASON_ID] = [tmp].[CPT_CHANGE_REASON_ID]
WHERE
	[tmp].[INDEX_ID] BETWEEN @FIRST_RECORD AND @LAST_RECORD
ORDER BY
	[tmp].[INDEX_ID]


GO
