CREATE PROCEDURE [dbo].[CEP_USER_SESSION_UPDATE_BY_CEP_USER_SESSION_ID]
	 @CEP_USER_SESSION_ID int
	,@USER_PROFILE_ID int
	,@SESSION_ID varchar(50)
	,@UU_ID uniqueidentifier = NULL
	,@IS_SIGNED_OUT bit = NULL
	,@LAST_REQUEST_DATE_TIME datetime
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
AS

UPDATE [dbo].[CEP_USER_SESSION] SET
	 [USER_PROFILE_ID] = @USER_PROFILE_ID
	,[SESSION_ID] = @SESSION_ID
	,[UU_ID] = @UU_ID
	,[IS_SIGNED_OUT] = @IS_SIGNED_OUT
	,[LAST_REQUEST_DATE_TIME] = @LAST_REQUEST_DATE_TIME
	,[CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
WHERE
	[CEP_USER_SESSION_ID] = @CEP_USER_SESSION_ID
GO
