CREATE PROCEDURE [dbo].[AUTOMATION_CODING_AUDIT_MESSAGE_UPDATE_BY_AUTOMATION_CODING_AUDIT_MESSAGE_ID]
	 @AUTOMATION_CODING_AUDIT_MESSAGE_ID int
	,@CREATING_USER_PROFILE_ID int = NULL
	,@CHANGING_USER_PROFILE_ID int = NULL
	,@CHART_ID int
	,@MESSAGE varchar(500)
	,@IS_ACKNOWLEDGED bit = NULL
	,@RULE_ID varchar(10)
AS

UPDATE [dbo].[AUTOMATION_CODING_AUDIT_MESSAGE] SET
	 [CREATING_USER_PROFILE_ID] = @CREATING_USER_PROFILE_ID
	,[CHANGED_DATE_TIME] = GETDATE()
	,[CHANGING_USER_PROFILE_ID] = @CHANGING_USER_PROFILE_ID
	,[CHART_ID] = @CHART_ID
	,[MESSAGE] = @MESSAGE
	,[IS_ACKNOWLEDGED] = @IS_ACKNOWLEDGED
	,[RULE_ID] = @RULE_ID
WHERE
	[AUTOMATION_CODING_AUDIT_MESSAGE_ID] = @AUTOMATION_CODING_AUDIT_MESSAGE_ID
GO
